#!/usr/bin/env python3
"""Generate links/verification.yaml, the test -> requirement links (WP-P-06 §5.3), from WP-W-06 §4.1.

WP-W-06 §4.1 lists, for the reference configuration, the existing opendbc safety unit tests (class::method) and
the requirement each exercises. The tests are inherited from the shared base `common.py`, so WP-P-06 §6 links them
through this file with the concrete class path rather than with `@req` tags in the shared base. The concrete class
is the reference-configuration class that WP-W-06 §4.1 names (`TestToyotaSafetyTorque`).

A link is a specified test -> requirement relation, not a result: the file holds no pass/fail. WP-W-06 marks
several of these tests as covering a requirement in part; `partial` carries that through.

  python3 assurance/trace/tools/verification_links.py           # regenerate links/verification.yaml
  python3 assurance/trace/tools/verification_links.py --check   # fail if it is stale, or a linked test does not
                                                                # exist on the concrete class (needs opendbc_repo)
Standard library only.
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

TRACE_DIR = Path(__file__).resolve().parent.parent
ASSURANCE_DIR = TRACE_DIR.parent
REPO = ASSURANCE_DIR.parent
OUT = TRACE_DIR / "links" / "verification.yaml"
UV_MD = ASSURANCE_DIR / "05-software" / "WP-W-06-software-unit-verification.md"
TESTS = Path("opendbc_repo") / "opendbc" / "safety" / "tests"
TEST_FILE = TESTS / "test_toyota.py"
HEADER = "| Behaviour | Existing test (class::method, file:line) | FSR |"
REQ_RE = re.compile(r"\b((?:FSR-[0-9]{2}\.[0-9]{2})|(?:(?:TSR|SWSR|HWSR|CSR)-[0-9]{3}[a-z]?)|(?:(?:AIR|SYS)-[0-9]{2,3}))\b")

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sync_requirements as sync  # noqa: E402


def reference_class(text: str) -> str:
  m = re.search(r"Reference-configuration class: `(\w+)`", text)
  if not m:
    raise ValueError(f"{UV_MD.name} §4.1: the reference-configuration class is not named")
  return m.group(1)


def methods_of(cell: str) -> list[str]:
  """Test methods named in a cell: `Class::test_x`, `test_x`, and suffixes `_y` of the previous name
  (`test_steer_req_bit_frames`, `_multi_invalid` -> test_steer_req_bit_multi_invalid)."""
  out: list[str] = []
  stem = ""
  for tok in re.findall(r"`([^`]+)`", cell):
    name = tok.split("::")[-1]
    if re.fullmatch(r"test_\w+", name):
      out.append(name)
      stem = name.rsplit("_", 1)[0]
    elif re.fullmatch(r"_[a-z]\w*", name) and stem:
      out.append(stem + name)  # every suffix extends the stem of the last full name
  return list(dict.fromkeys(out))


def links() -> list[dict]:
  text = UV_MD.read_text(encoding="utf-8")
  sec = sync._section(text, "### 4.1 opendbc safety unit tests", "\n### 4.2", UV_MD)
  if HEADER not in sec:
    raise ValueError(f"{UV_MD.name} §4.1: table {HEADER!r} not found")
  cls = reference_class(sec)
  out: list[dict] = []
  for line in sec.split(HEADER, 1)[1].splitlines()[2:]:
    if not line.startswith("|"):
      break
    behaviour, tests, reqs = sync.cells(line)
    ids = list(dict.fromkeys(REQ_RE.findall(reqs)))
    if not ids:
      continue  # no requirement named ("—"): a test of a behaviour, not a verification link
    for method in methods_of(tests):
      out.append({"test": f"{TEST_FILE.as_posix()}::{cls}::{method}", "reqs": ids, "level": "unit",
                  "environment": "host-x86", "partial": "partial" in reqs, "behaviour": behaviour,
                  "source": "WP-W-06"})
  return out


def render(items: list[dict]) -> str:
  out = ["# Test -> requirement links (WP-P-06 §5.3) for the tests the reference configuration inherits from the shared",
         "# opendbc test base. GENERATED by tools/verification_links.py from WP-W-06 §4.1, which stays the source.",
         "# Do not edit by hand: change WP-W-06 and regenerate. CI fails if this file is stale or a test does not exist.",
         "# A link says which requirement a test exercises; it is not a result (no pass/fail is recorded here).", ""]
  for it in items:
    out += [f"- test: {it['test']}", f"  reqs: {sync.flow(it['reqs'])}", f"  level: {it['level']}",
            f"  environment: {it['environment']}", f"  partial: {'true' if it['partial'] else 'false'}",
            f"  behaviour: {sync.quote(it['behaviour'])}", f"  source: {it['source']}", ""]
  return "\n".join(out)


# ---------------------------------------------------------------- does the test exist?

def _classes(path: Path) -> dict[str, ast.ClassDef]:
  tree = ast.parse(path.read_text(encoding="utf-8"))
  return {n.name: n for n in tree.body if isinstance(n, ast.ClassDef)}


def _base_name(node: ast.expr) -> str | None:
  if isinstance(node, ast.Name):
    return node.id
  if isinstance(node, ast.Attribute):  # common.CarSafetyTest
    return node.attr
  return None


def test_methods(root: Path, cls: str) -> set[str]:
  """Every test_* method the class has, its own and inherited, resolving bases in the test file and common.py."""
  classes = {**_classes(root / TESTS / "common.py"), **_classes(root / TEST_FILE)}
  if cls not in classes:
    raise ValueError(f"{TEST_FILE}: class {cls} not found")
  seen, todo, out = set(), [cls], set()
  while todo:
    name = todo.pop()
    if name in seen or name not in classes:
      continue
    seen.add(name)
    node = classes[name]
    out |= {f.name for f in node.body if isinstance(f, ast.FunctionDef) and f.name.startswith("test_")}
    todo += [b for b in (_base_name(x) for x in node.bases) if b]
  return out


def problems(root: Path = REPO) -> list[str]:
  errs = []
  current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
  items = links()
  if current != render(items):
    errs.append(f"{OUT.relative_to(REPO)} is stale; run assurance/trace/tools/verification_links.py")
  if not (root / TEST_FILE).exists():
    errs.append(f"{TEST_FILE} is not checked out (git submodule update --init opendbc_repo); the tests cannot be checked")
    return errs
  have: dict[str, set[str]] = {}
  for it in items:
    _, cls, method = it["test"].split("::")
    have.setdefault(cls, test_methods(root, cls))
    if method not in have[cls]:
      errs.append(f"{it['test']}: no such test method on {cls} or its bases (WP-W-06 §4.1)")
  return errs


def main(argv: list[str]) -> int:
  if "--check" in argv:
    errs = problems()
    for e in errs:
      print(f"FAIL: {e}")
    if not errs:
      print(f"verification links: {len(links())} links current, every test exists")
    return 1 if errs else 0
  OUT.parent.mkdir(exist_ok=True)
  OUT.write_text(render(links()), encoding="utf-8")
  print(f"wrote {OUT.relative_to(REPO)}")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
