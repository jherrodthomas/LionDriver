def main(argv: list[str]) -> int:
  check = "--check" in argv
  try:
    outputs = build()
  except FigureError as e:
    print(f"hara_figures: {e}", file=sys.stderr)
    return 1
  existing = {p.name for p in OUT_DIR.glob("fig-c03-*.svg")}
  if check:
    stale = [n for n, c in outputs.items() if not (OUT_DIR / n).exists() or (OUT_DIR / n).read_text(encoding="utf-8") != c]
    extra = sorted(existing - set(outputs))
    for n in stale:
      print(f"stale: hara/figures/{n}", file=sys.stderr)
    for n in extra:
      print(f"no longer generated: hara/figures/{n}", file=sys.stderr)
    if stale or extra:
      print("run: python3 assurance/02-concept/hara/hara_figures.py", file=sys.stderr)
      return 1
    print(f"hara_figures: {len(outputs)} figure(s) current")
    return 0
  OUT_DIR.mkdir(exist_ok=True)
  for n in sorted(existing - set(outputs)):
    (OUT_DIR / n).unlink()
  for n, c in outputs.items():
    (OUT_DIR / n).write_text(c, encoding="utf-8")
  print(f"hara_figures: wrote {len(outputs)} figure(s) to hara/figures/")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
