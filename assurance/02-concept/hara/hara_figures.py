# ---------------------------------------------------------------- helpers

def text_w(s: str, size: float, bold: bool = False) -> float:
  """Rough rendered width of s (Inter-like metrics), enough for wrapping and pill sizing."""
  w = 0.0
  for ch in s:
    if ch in "il.,:;'|!·":
      w += 0.28
    elif ch in "fjrt() -/":
      w += 0.36
    elif ch.isupper() or ch in "mwMW≥≤–—…⚠":
      w += 0.70
    elif ch.isdigit():
      w += 0.56
    else:
      w += 0.55
  return w * size * (1.06 if bold else 1.0)


def wrap(s: str, width: float, size: float, bold: bool = False) -> list[str]:
  out, line = [], ""
  for word in s.split():
    cand = word if not line else line + " " + word
    if text_w(cand, size, bold) <= width or not line:
      line = cand
    else:
      out.append(line)
      line = word
  if line:
    out.append(line)
  return out


def t(x, y, s, size=11, fill=INK, weight=None, anchor=None, extra=""):
  a = f' text-anchor="{anchor}"' if anchor else ""
  w = f' font-weight="{weight}"' if weight else ""
  return f'<text x="{x:g}" y="{y:g}" font-size="{size:g}" fill="{fill}"{w}{a}{extra}>{escape(s)}</text>'


def pill(x, y, label, fill, color="#FFFFFF", h=18, size=10, stroke=None):
  w = text_w(label, size, True) + 14
  s = f' stroke="{stroke}"' if stroke else ""
  return (f'<rect x="{x:g}" y="{y:g}" width="{w:.1f}" height="{h}" rx="{h / 2:g}" fill="{fill}"{s}/>' +
          t(x + w / 2, y + h / 2 + size * 0.36, label, size, color, 700, "middle")), w


def svg_doc(w, h, title, desc, body, defs=""):
  return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
          f'font-family="{escape(FONT)}" role="img" aria-labelledby="t d">\n'
          f'<title id="t">{escape(title)}</title>\n<desc id="d">{escape(desc)}</desc>\n'
          f'<defs>{defs}</defs>\n<rect width="{w}" height="{h}" fill="#FFFFFF"/>\n' + "\n".join(body) + "\n</svg>\n")


def header(w, title, subtitle, ref1, ref2):
  return [t(40, 44, title, 20, INK, 700), t(40, 66, subtitle, 12.5, MUTED),
          t(w - 40, 44, ref1, 11, MUTED, None, "end"), t(w - 40, 62, ref2, 11, MUTED, None, "end"),
          f'<line x1="40" y1="82" x2="{w - 40}" y2="82" stroke="{HAIR}"/>']


