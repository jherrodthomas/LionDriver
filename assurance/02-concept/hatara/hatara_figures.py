#!/usr/bin/env python3
"""Draw the HATARA figures from hatara_model.py, WP-C-03, WP-C-09 and WP-C-10.

- Figure 1 (`figures/fig-hatara-1-matrix.svg`): every WP-C-03 hazard against every WP-C-09 threat scenario. A filled
  cell is a link WP-C-09 §3 carries (a damage scenario of the threat reaches the hazard); a dashed, pulsing cell is a
  link an interaction names but §3 does not carry.
- Figure 2 (`figures/fig-hatara-2-interactions.svg`): one card per interaction: its type and direction, a safety lane
  and a security lane with an animated arrow from the side that causes the effect to the side that takes it (a joint
  for mutual reinforcement), what follows, the records it ties to, and its status (requirement statuses from WP-C-10
  §7, gap status from WP-C-09 §3).

    python3 hatara_figures.py            # regenerate the SVGs
    python3 hatara_figures.py --check    # fail if a source disagrees or an SVG is stale

Standard library only. Output is deterministic.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "hara"))
import hatara_model as hm
from hara_figures import HAIR, INK, MUTED, header, pill, svg_doc, t, text_w, wrap  # noqa: E402

ParseError = hm.ParseError
OUT = HERE / "figures"
W, M = 1320, 40
RISK = {5: "#DC2626", 4: "#F97316", 3: "#F59E0B"}
SAFE, SEC = "#2563EB", "#7C3AED"
KIND_COL = {"dep": "#0F766E", "reinf": "#16A34A", "anta": "#DC2626"}
ST_COL = {"open": "#B91C1C", "partial": "#B45309", "unverified": "#0369A1", "unconfirmed": "#475569", "done": "#15803D", "": INK}
SHORT = {  # matrix row labels; the full names are WP-C-03's, and every hazard must have one
  "H-01": "Excessive lateral motion", "H-02": "Silent loss of lateral control", "H-03": "Unintended acceleration",
  "H-04": "Excessive deceleration", "H-05": "Override or disengage prevented", "H-06": "Silent loss of deceleration",
  "H-07": "Mode confusion", "H-08": "Stock PCS/AEB suppressed", "H-09": "Unsupervised driver, control goes on",
}


def matrix(m: hm.Model) -> str:
  if sorted(SHORT) != sorted(m.hz):
    raise ParseError(f"matrix labels {sorted(SHORT)} do not match the WP-C-03 hazards {sorted(m.hz)}")
  tss = sorted(m.tara.ts, key=lambda s: int(s[3:]))
  gaps = {p: ix["id"] for ix in m.ix if ix["kind"] == "dep" for p in m.gaps(ix)}
  cw, ch, lw, x = 46, 26, 250, M
  body = header(W, "HATARA · where a threat reaches a hazard",
                "Rows: WP-C-03 hazards. Columns: WP-C-09 threat scenarios, coloured by risk. Filled: WP-C-09 §3 links them. "
                "Dashed: an interaction names the link, §3 does not carry it.", "WP-C-03 · WP-C-09 §3, §8", "hatara_model.py")
  y0 = 112
  for j, ts in enumerate(tss):
    cx, r = x + lw + j * cw, m.tara.risk[ts]["risk"]
    body.append(f'<rect x="{cx + 3}" y="{y0}" width="{cw - 6}" height="20" rx="4" fill="{RISK.get(r, "#94A3B8")}"/>')
    body.append(t(cx + cw / 2, y0 + 14, ts, 9.5, "#FFFFFF", 700, "middle"))
  y0 += 28
  for i, h in enumerate(sorted(m.hz)):
    cy = y0 + i * ch
    body.append(f'<rect x="{x}" y="{cy}" width="{lw + len(tss) * cw}" height="{ch}" fill="{"#F8FAFC" if i % 2 else "#FFFFFF"}"/>')
    body.append(f'<title>{h}: {m.hz[h]}</title>')
    body.append(t(x + 6, cy + 17, h, 10.5, MUTED, 700))
    body.append(t(x + 46, cy + 17, SHORT[h], 10.5, INK))
    for j, ts in enumerate(tss):
      cx = x + lw + j * cw
      if (h, ts) in m.links:
        body.append(f'<rect x="{cx + 8}" y="{cy + 5}" width="{cw - 16}" height="{ch - 10}" rx="3" fill="{SEC}" fill-opacity="0.8"/>')
      elif (h, ts) in gaps:
        body.append(f'<rect x="{cx + 8}" y="{cy + 5}" width="{cw - 16}" height="{ch - 10}" rx="3" fill="#FFFFFF" stroke="#D97706" '
                    f'stroke-width="1.8" stroke-dasharray="4 2"><animate attributeName="stroke-opacity" values="1;0.25;1" dur="2s" '
                    f'repeatCount="indefinite"/></rect>')
    if not any((h, ts) in m.links for ts in tss):
      note = "no damage scenario in WP-C-09" + (f" · {', '.join(sorted({gaps[p] for p in gaps if p[0] == h}))}" if any(p[0] == h for p in gaps) else "")
      body.append(t(x + lw + len(tss) * cw + 10, cy + 17, note, 10, "#B45309", 600))
  yy = y0 + len(m.hz) * ch + 24
  body.append(f'<rect x="{x}" y="{yy - 10}" width="22" height="14" rx="3" fill="{SEC}" fill-opacity="0.8"/>')
  body.append(t(x + 30, yy + 2, "WP-C-09 §3 links them: a safety goal rests on security here (conditional dependency)", 10.5, INK))
  body.append(f'<rect x="{x + 600}" y="{yy - 10}" width="22" height="14" rx="3" fill="#FFFFFF" stroke="#D97706" stroke-width="1.8" stroke-dasharray="4 2"/>')
  body.append(t(x + 630, yy + 2, "Named by an interaction, not carried by a damage scenario: the analyses disagree", 10.5, INK))
  body.append(t(W - M, yy + 30, "Generated by hatara_figures.py", 10, MUTED, None, "end"))
  n_link = sum(1 for h in m.hz for ts in tss if (h, ts) in m.links)
  desc = (f"HATARA Figure 1: {len(m.hz)} hazards against {len(tss)} threat scenarios; WP-C-09 §3 links {n_link} pairs. "
          f"Hazards with no damage scenario: {', '.join(h for h in sorted(m.hz) if not any((h, ts) in m.links for ts in tss)) or 'none'}. "
          f"Links named by an interaction but not carried: {', '.join(f'{h}/{ts} ({i})' for (h, ts), i in sorted(gaps.items())) or 'none'}.")
  return svg_doc(W, int(yy + 44), "HATARA Figure 1. Where a threat reaches a hazard", desc, body)


def card(m: hm.Model, ix: dict, x: float, y: float, w: float):
  b = [None, f"<title>{ix['id']}: {ix['title']}</title>"]
  px, yy, lw = x + 12, y + 24, w - 24
  col = KIND_COL[ix["kind"]]
  kind = hm.KINDS[ix["kind"]]
  b.append(pill(px, yy - 13, kind, "#FFFFFF", col, 18, 10, col)[0])
  b.append(t(px + text_w(kind, 10, True) + 22, yy + 1, ix["dir"], 10, MUTED, 600))
  b.append(t(px + lw, yy + 1, ix["id"], 10, MUTED, 600, "end"))
  yy += 24
  if text_w(ix["title"], 13, True) > lw:
    raise ParseError(f"{ix['id']}: title runs over one line")
  b.append(t(px, yy, ix["title"], 13, INK, 700))
  yy += 12
  lh = 44
  for k, (lab, lc, txt) in enumerate((("Safety", SAFE, ix["safety"]), ("Security", SEC, ix["security"]))):
    ly = yy + k * (lh + 10)
    b.append(f'<rect x="{px}" y="{ly}" width="{lw}" height="{lh}" rx="6" fill="{lc}" fill-opacity="0.07" stroke="{lc}" stroke-opacity="0.4"/>')
    b.append(t(px + 8, ly + 14, lab, 9, lc, 700))
    ls = wrap(txt, lw - 100, 9.5)
    if len(ls) > 3:
      raise ParseError(f"{ix['id']}: {lab.lower()} side runs over three lines")
    for i, ln in enumerate(ls):
      b.append(t(px + 62, ly + 15 + 11 * i, ln, 9.5, INK))
  top, bot, ax = yy + lh / 2, yy + lh + 10 + lh / 2, px + lw - 20
  if ix["kind"] == "reinf":
    b.append(f'<path d="M{ax} {top} L{ax} {bot}" stroke="{col}" stroke-width="2.4"/>')
    b.append(f'<circle cx="{ax}" cy="{(top + bot) / 2}" r="5" fill="{col}"><animate attributeName="r" values="4;7;4" dur="2s" repeatCount="indefinite"/></circle>')
  else:
    y1, y2 = (top, bot) if ix["dir"] == "safety → security" else (bot, top)
    b.append(f'<path d="M{ax} {y1} L{ax} {y2}" stroke="{col}" stroke-width="2" stroke-dasharray="3 3"/>')
    b.append(f'<circle cx="{ax}" cy="{y2}" r="5" fill="{col}"><animate attributeName="cy" values="{y1};{y1};{y2};{y2}" keyTimes="0;0.2;0.6;1" '
             f'dur="4s" repeatCount="indefinite"/></circle>')
  yy += 2 * lh + 10 + 22
  fl = wrap(ix["follows"], lw, 10)
  if len(fl) > 3:
    raise ParseError(f"{ix['id']}: 'what follows' runs over three lines")
  for i, ln in enumerate(fl):
    b.append(t(px, yy + 13 * i, ln, 10, INK))
  yy += 13 * len(fl) + 8
  b.append(t(px, yy, "Ties", 9.5, MUTED))
  tl = wrap(" · ".join(ix["ties"]), lw - 50, 9.5)
  if len(tl) > 2:
    raise ParseError(f"{ix['id']}: ties run over two lines")
  for i, ln in enumerate(tl):
    b.append(t(px + 50, yy + 12 * i, ln, 9.5, INK))
  yy += 12 * len(tl) + 4
  b.append(t(px, yy, "Status", 9.5, MUTED))
  for i, (s, key) in enumerate(m.status(ix)):
    if text_w(s, 9.5) > lw - 50:
      raise ParseError(f"{ix['id']}: status '{s}' too long for the card")
    b.append(t(px + 50, yy + 12 * i, s, 9.5, ST_COL[key], 600 if key else None))
  yy += 12 * len(m.status(ix)) + 6
  return b, yy - y


PW, PM = 640, 24   # phone views: 640 px wide, 24 px margins


def phone_header(title: str, subtitle: str, refs: str) -> tuple[list[str], float]:
  """Header of a phone view: the title and subtitle wrapped to the width, the sources on one line under them."""
  b, y = [], 30
  for ln in wrap(title, PW - 2 * PM, 18, True):
    b.append(t(PM, y, ln, 18, INK, 700))
    y += 23
  for ln in wrap(subtitle, PW - 2 * PM, 12):
    b.append(t(PM, y, ln, 12, MUTED))
    y += 16
  b.append(t(PM, y, refs + " · phone view", 11, MUTED))
  b.append(f'<line x1="{PM}" y1="{y + 10}" x2="{PW - PM}" y2="{y + 10}" stroke="{HAIR}"/>')
  return b, y + 30


def interactions(m: hm.Model, phone: bool = False) -> str:
  w, mx = (PW, PM) if phone else (W, M)
  cols, gap = (1, 12) if phone else (4, 16)
  cw = (w - 2 * mx - (cols - 1) * gap) / cols
  title = "HATARA · where one side's measure changes the other's risk"
  sub = ("One card per interaction of hatara_model.py: the safety side, the security side, the arrow from cause to effect, "
         "what follows, and what ties it to the analyses.")
  if phone:
    body, ly = phone_header(title, sub, "WP-C-03 · WP-C-09 · WP-C-10 · Kriaa et al. types")
  else:
    body, ly = header(W, title, sub, "WP-C-03 · WP-C-09 · WP-C-10", "Kriaa et al. types"), 92
  lx = mx
  for k, lab in hm.KINDS.items():
    body.append(pill(lx, ly, lab, "#FFFFFF", KIND_COL[k], 18, 10, KIND_COL[k])[0])
    lx += text_w(lab, 10, True) + 22
  y = ly + 32
  for r in range(0, len(m.ix), cols):
    built = [card(m, ix, mx + k * (cw + gap), y, cw) for k, ix in enumerate(m.ix[r:r + cols])]
    row_h = max(h for _, h in built)
    for k, (b, _) in enumerate(built):
      b[0] = f'<rect x="{mx + k * (cw + gap):.1f}" y="{y}" width="{cw:.1f}" height="{row_h:.0f}" rx="12" fill="#FFFFFF" stroke="{HAIR}"/>'
      body += ["<g>"] + b + ["</g>"]
    y += row_h + gap
  foot = ("Types after Kriaa et al. (conditional dependency, mutual reinforcement, antagonism; independent pairs are not "
          "listed). Requirement statuses from WP-C-10 §7; gap status from WP-C-09 §3.")
  if phone:
    for ln in wrap(foot + " Generated by hatara_figures.py.", w - 2 * mx, 10.5):
      body.append(t(mx, y + 8, ln, 10.5, MUTED))
      y += 14
  else:
    body.append(t(M, y + 8, foot, 10.5, MUTED))
    body.append(t(W - M, y + 26, "Generated by hatara_figures.py", 10, MUTED, None, "end"))
  desc = "HATARA Figure 2: " + " ".join(
    f"{ix['id']} {ix['title']} ({hm.KINDS[ix['kind']].lower()}, {ix['dir']}): {ix['follows']} Status: "
    f"{'; '.join(s for s, _ in m.status(ix))}." for ix in m.ix)
  return svg_doc(w, int(y + 40), "HATARA Figure 2. Where one side's measure changes the other's risk"
                 f"{', phone view' if phone else ''}", desc, body)


def matrix_phone(m: hm.Model) -> str:
  """Figure 1 for a phone: one row per hazard with the threat scenarios §3 links to it as chips coloured by risk, and the
  links an interaction names but §3 does not carry as dashed chips."""
  tss = sorted(m.tara.ts, key=lambda s: int(s[3:]))
  gaps = {p: ix["id"] for ix in m.ix if ix["kind"] == "dep" for p in m.gaps(ix)}
  body, y = phone_header("HATARA · where a threat reaches a hazard",
                         "One row per WP-C-03 hazard. Chips: the WP-C-09 threat scenarios §3 links to it, coloured by risk; "
                         "dashed: an interaction names the link, §3 does not carry it.", "WP-C-03 · WP-C-09 §3, §8")
  lx = PM
  for r in (5, 4, 3):
    body.append(f'<rect x="{lx}" y="{y - 12}" width="22" height="14" rx="3" fill="{RISK[r]}"/>')
    body.append(t(lx + 28, y, f"risk {r}", 10.5, INK))
    lx += 82
  y += 20
  for i, h in enumerate(sorted(m.hz)):
    linked = [ts for ts in tss if (h, ts) in m.links]
    named = [ts for ts in tss if (h, ts) in gaps]
    top = y
    body.append(t(PM, y + 16, h, 12, MUTED, 700))
    body.append(t(PM + 50, y + 16, SHORT[h], 13, INK, 600))
    cx, cy = PM + 50, y + 26
    for ts in linked + named:
      wch = text_w(ts, 10, True) + 14
      if cx + wch > PW - PM:
        cx, cy = PM + 50, cy + 24
      if ts in linked:
        body.append(f'<rect x="{cx}" y="{cy}" width="{wch:.1f}" height="18" rx="4" fill="{RISK.get(m.tara.risk[ts]["risk"], "#94A3B8")}"/>')
        body.append(t(cx + wch / 2, cy + 13, ts, 10, "#FFFFFF", 700, "middle"))
      else:
        body.append(f'<rect x="{cx}" y="{cy}" width="{wch:.1f}" height="18" rx="4" fill="#FFFFFF" stroke="#D97706" '
                    f'stroke-width="1.8" stroke-dasharray="4 2"/>')
        body.append(t(cx + wch / 2, cy + 13, ts, 10, "#B45309", 700, "middle"))
      cx += wch + 6
    if not linked:
      note = "no damage scenario in WP-C-09" + (f" · {', '.join(sorted({gaps[p] for p in gaps if p[0] == h}))}" if named else "")
      body.append(t(PM + 50, cy + 13 + (24 if named else 0), note, 10.5, "#B45309", 600))
      cy += 24 if named else 0
    y = cy + 30
    body.append(f'<line x1="{PM}" y1="{y - 6}" x2="{PW - PM}" y2="{y - 6}" stroke="{HAIR}"/>')
  for ln in wrap("Filled: WP-C-09 §3 links them, so a safety goal rests on security there. Dashed: named by an interaction, "
                 "not carried by a damage scenario; the analyses disagree. Generated by hatara_figures.py.", PW - 2 * PM, 10.5):
    y += 14
    body.append(t(PM, y, ln, 10.5, MUTED))
  n_link = sum(1 for h in m.hz for ts in tss if (h, ts) in m.links)
  desc = (f"HATARA Figure 1, phone view: {len(m.hz)} hazards, each with the threat scenarios WP-C-09 §3 links to it "
          f"({n_link} links in all). " + " ".join(
            f"{h}: {', '.join(ts for ts in tss if (h, ts) in m.links) or 'none'}"
            f"{'; named, not carried: ' + ', '.join(ts for ts in tss if (h, ts) in gaps) if any((h, ts) in gaps for ts in tss) else ''}."
            for h in sorted(m.hz)))
  return svg_doc(PW, int(y + 20), "HATARA Figure 1. Where a threat reaches a hazard, phone view", desc, body)


def build(m: hm.Model | None = None) -> dict[str, str]:
  m = m or hm.Model()
  return {"fig-hatara-1-matrix.svg": matrix(m), "fig-hatara-2-interactions.svg": interactions(m),
          "fig-hatara-1-matrix-phone.svg": matrix_phone(m), "fig-hatara-2-interactions-phone.svg": interactions(m, phone=True)}


def main(argv: list[str]) -> int:
  check = "--check" in argv
  try:
    out = build()
  except ParseError as e:
    print(f"hatara_figures: {e}", file=sys.stderr)
    return 1
  stale = []
  OUT.mkdir(exist_ok=True)
  for name, content in out.items():
    p = OUT / name
    if check:
      if not p.exists() or p.read_text(encoding="utf-8") != content:
        stale.append(name)
    else:
      p.write_text(content, encoding="utf-8")
  if stale:
    print("stale HATARA figures; run hatara_figures.py: " + ", ".join(stale), file=sys.stderr)
    return 1
  print(f"hatara_figures: {len(out)} figures {'current' if check else 'written'}")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
