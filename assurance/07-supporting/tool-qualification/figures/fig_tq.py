#!/usr/bin/env python3
"""Draw the two figures of the tool qualification folder.

- Figure 1 (`fig-tq-1-method.svg`), the method and the guards: the five steps of method.md §1, read from its table,
  with step 3 marked as the step that decides the TCL, and below them the guard catalogue (guards.yaml): each guard
  with what it catches and how the project shows it works.
- Figure 2 (`fig-tq-2-tqr32.svg`), the validation of TQR-32: every planted fault of the last run (TQR-32/results.json),
  grouped by error class, with the check that reported it, and every tool mutant with the faults that killed it.

The build fails when method.md's step table or guards.yaml changes shape, or the results name a fault or class the
catalogue does not have. Phone width; standard library and PyYAML.

    python3 fig_tq.py            # write both SVGs
    python3 fig_tq.py --check    # fail if a source changed shape or an SVG is stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
FOLDER = HERE.parent
ASSURANCE = FOLDER.parents[1]
sys.path.insert(0, str(ASSURANCE / "01-management" / "figures"))
from figkit import (INK, MUTED, FAINT, LINE, SW, SW_BG, GREEN, GREEN_BG, RED, RED_BG, SAFETY, SAFETY_BG,  # noqa: E402
                    FigureError, text, rect, path, svg, text_w, section, table, col, plain)
sys.path.insert(0, str(ASSURANCE / "trace" / "tools"))
import terms  # noqa: E402

OUT1, OUT2 = "fig-tq-1-method.svg", "fig-tq-2-tqr32.svg"
W = 640
DECIDES = "3"   # the step whose guards decide the TCL (method.md §2)


def wrap(s: str, width: float, size: float, bold: bool = False) -> list[str]:
  out, cur = [], ""
  for word in s.split():
    nxt = f"{cur} {word}".strip()
    if cur and text_w(nxt, size, bold) > width:
      out.append(cur)
      cur = word
    else:
      cur = nxt
  return out + ([cur] if cur else [])


def steps() -> list[dict]:
  md = (FOLDER / "method.md").read_text(encoding="utf-8")
  head, rows = table(section(md, "## 1. One method for any tool"), "Step")
  out = []
  for r in rows:
    m = re.match(r"(\d)\. (.+)", plain(r[col(head, "Step")]))
    if not m:
      raise FigureError(f"method.md §1: cannot read step {r[0]!r}")
    out.append({"n": m.group(1), "name": m.group(2), "q": plain(r[col(head, "Question")]),
                "out": plain(r[col(head, "Output")])})
  if [s["n"] for s in out] != ["1", "2", "3", "4", "5"]:
    raise FigureError("method.md §1 no longer has steps 1 to 5")
  return out


def guards() -> list[dict]:
  g = yaml.safe_load((FOLDER / "guards.yaml").read_text(encoding="utf-8"))
  for x in g:
    for k in ("id", "name", "catches", "shown_by", "used_by"):
      if k not in x:
        raise FigureError(f"guards.yaml {x.get('id')}: no {k}")
  return g


def footer(out: list[str], y: float, gen: str) -> float:
  extra, y = terms.svg_footer(out, 16, y, W - 32, size=10)
  out += extra
  out.append(text(W - 16, y + 6, f"Generated by {gen}", size=10, fill=FAINT, anchor="end"))
  return y + 18


def figure1() -> str:
  st, gs = steps(), guards()
  out = [text(16, 30, "Figure 1 · One method for any tool, decided by its guards", size=15, weight=700),
         text(16, 48, "method.md §1 and the guard catalogue (guards.yaml)", size=11, fill=MUTED)]
  y = 68
  for i, s in enumerate(st):
    hot = s["n"] == DECIDES
    lines = wrap(s["q"], W - 140, 10.5)
    h = 30 + 14 * len(lines)
    out.append(rect(16, y, W - 32, h, fill=SAFETY_BG if hot else "#F8FAFC", stroke=SAFETY if hot else LINE,
                    sw=1.8 if hot else 1.1, rx=9))
    out.append(text(28, y + 19, f"{s['n']}", size=15, weight=700, fill=SAFETY if hot else MUTED))
    out.append(text(48, y + 19, s["name"], size=12.5, weight=700))
    out.append(text(W - 28, y + 19, s["out"].split(" (")[0][:38], size=10, fill=SAFETY if hot else MUTED,
                    anchor="end", weight=700 if hot else ""))
    for j, ln in enumerate(lines):
      out.append(text(48, y + 35 + 14 * j, ln, size=10.5, fill=INK))
    y += h
    if i < len(st) - 1:
      out.append(path(f"M{W / 2} {y + 1} L{W / 2} {y + 11}", stroke=FAINT, sw=1.4))
      out.append(path(f"M{W / 2 - 4} {y + 7} L{W / 2} {y + 12} L{W / 2 + 4} {y + 7}", stroke=FAINT, sw=1.4))
      y += 14
  out.append(text(16, y + 20, "Step 3 decides the TCL: the guards below, not the tool's name.", size=11,
                  fill=SAFETY, weight=700))
  y += 40
  out.append(text(16, y, "The guard catalogue", size=13, weight=700))
  y += 10
  cw = (W - 32 - 10) / 2
  rows = [gs[i:i + 2] for i in range(0, len(gs), 2)]
  for row in rows:
    blocks = []
    for g in row:
      c = wrap(g["catches"], cw - 24, 10)
      p = wrap("Shown by: " + g["shown_by"], cw - 24, 9.5)
      blocks.append((g, c, p))
    h = max(44 + 13 * len(c) + 12 * len(p) for _, c, p in blocks)
    for k, (g, c, p) in enumerate(blocks):
      x = 16 + k * (cw + 10)
      out.append(rect(x, y, cw, h, fill="#FFFFFF", stroke=LINE, sw=1.1, rx=9))
      out.append(rect(x + 10, y + 9, 40, 16, fill=SW, stroke="none", rx=8))
      out.append(text(x + 30, y + 21, g["id"], size=9.5, weight=700, fill="#FFFFFF", anchor="middle"))
      out.append(text(x + 58, y + 21, g["name"], size=11.5, weight=700))
      yy = y + 40
      for ln in c:
        out.append(text(x + 12, yy, ln, size=10, fill=INK))
        yy += 13
      yy += 2
      for ln in p:
        out.append(text(x + 12, yy, ln, size=9.5, fill=SW))
        yy += 12
    y += h + 10
  y = footer(out, y + 14, "fig_tq.py from method.md and guards.yaml")
  desc = ("Five steps: " + "; ".join(f"{s['n']} {s['name']}" for s in st) + ". Guards: " +
          "; ".join(f"{g['id']} {g['name']}" for g in gs) + ".")
  return svg(W, int(y), "Figure 1. One method for any tool, decided by its guards", desc, out)


def figure2() -> str:
  r = json.loads((FOLDER / "TQR-32" / "results.json").read_text(encoding="utf-8"))
  cat = {f["id"]: f for f in yaml.safe_load((FOLDER / "TQR-32" / "faults.yaml").read_text(encoding="utf-8"))}
  for f in r["faults"]:
    if f["id"] not in cat or cat[f["id"]]["class"] != f["class"]:
      raise FigureError(f"results.json {f['id']} does not match faults.yaml; run tools/qualify.py")
  caught = sum(f["caught"] for f in r["faults"])
  killed = sum(m["killed"] for m in r["mutants"])
  out = [text(16, 30, "Figure 2 · TQR-32: the trace checker, validated", size=15, weight=700),
         text(16, 48, f"Faults planted in the real trace data ({r['items']} items, {r['links']} test links)", size=11,
              fill=MUTED)]
  y = 74
  out.append(text(16, y, f"Planted faults: {caught} of {len(r['faults'])} caught", size=13, weight=700,
                  fill=GREEN if caught == len(r["faults"]) else RED))
  y += 12
  classes: dict[str, list[dict]] = {}
  for f in r["faults"]:
    classes.setdefault(f["class"], []).append(f)
  for cls in sorted(classes, key=lambda c: int(re.match(r"EC-(\d+)", c).group(1))):
    fs = classes[cls]
    out.append(text(16, y + 16, cls, size=10.5, weight=700))
    x, yy = 200, y + 4
    for f in fs:
      lab = f["id"]
      w = text_w(lab, 9.5, True) + 14
      if x + w > W - 16:
        x, yy = 200, yy + 22
      ok = f["caught"]
      out.append(rect(x, yy, w, 17, fill=GREEN_BG if ok else RED_BG, stroke=GREEN if ok else RED, sw=1.2, rx=6))
      out.append(text(x + w / 2, yy + 12.5, lab, size=9.5, weight=700, fill=GREEN if ok else RED, anchor="middle"))
      x += w + 5
    y = yy + 24
  y += 14
  out.append(text(16, y, f"Tool mutants: {killed} of {len(r['mutants'])} killed", size=13, weight=700,
                  fill=GREEN if killed == len(r["mutants"]) else RED))
  y += 8
  out.append(text(16, y + 14, "check_trace.py broken in memory so that …", size=10, fill=MUTED))
  out.append(text(W - 16, y + 14, "killed by", size=10, fill=MUTED, anchor="end"))
  y += 22
  for m in r["mutants"]:
    lines = wrap(m["what"], W - 230, 10.5)
    by = ", ".join(m["missed"]) if m["missed"] else ("baseline fails" if m["baseline_errors"] else "survived")
    out.append(text(16, y + 13, m["id"], size=10.5, weight=700))
    for j, ln in enumerate(lines):
      out.append(text(60, y + 13 + 13 * j, ln, size=10.5, fill=INK))
    out.append(text(W - 16, y + 13, by, size=10.5, weight=700, fill=GREEN if m["killed"] else RED, anchor="end"))
    y += 8 + 13 * len(lines)
    out.append(path(f"M16 {y} L{W - 16} {y}", stroke="#E2E8F0", sw=1))
  y += 20
  for ln in wrap("Green: caught. Each fault is planted alone in a fresh copy and must be reported by the check it "
                 "belongs to, naming the planted item (TQR-32/results.md lists each report). CI reruns this on every change. Not yet accepted by the lead or reviewed.", W - 32, 10.5):
    out.append(text(16, y, ln, size=10.5, fill=MUTED))
    y += 14
  y = footer(out, y + 10, "fig_tq.py from TQR-32/results.json")
  desc = (f"{caught} of {len(r['faults'])} planted faults caught: " +
          "; ".join(f"{f['id']} {f['class']} by {f['expect']}" for f in r["faults"]) +
          f". {killed} of {len(r['mutants'])} tool mutants killed.")
  return svg(W, int(y), "Figure 2. TQR-32: the trace checker, validated", desc, out)


def build() -> dict[str, str]:
  return {OUT1: figure1(), OUT2: figure2()}


def main(argv: list[str]) -> int:
  try:
    outputs = build()
  except FigureError as e:
    print(f"fig_tq: {e}", file=sys.stderr)
    return 1
  stale = []
  for name, content in outputs.items():
    p = HERE / name
    if "--check" in argv:
      if not p.exists() or p.read_text(encoding="utf-8") != content:
        stale.append(name)
    else:
      p.write_text(content, encoding="utf-8")
  if stale:
    print(f"fig_tq: stale {', '.join(stale)}; run python3 {Path(__file__).name}", file=sys.stderr)
    return 1
  print("fig_tq: " + ("up to date" if "--check" in argv else f"wrote {', '.join(outputs)}"))
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
