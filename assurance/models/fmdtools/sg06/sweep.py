#!/usr/bin/env python3
"""SG-06 fault sweeps (tool evaluation TE-02, extended by DQ-417), compared with the WP-A-04 §7 tree.

Step P2: every failure mode alone, in each road phase; writes p2-single-faults.md.
Step P3: the minimal fault sets of up to 4 modes that give TE-06 (approach); writes p3-minimal-sets.json and
p3-joint-faults.md. `--check --order 2` checks the sets of order 1 and 2 against the JSON (the pull-request job); the
full check runs on a schedule.
Step P4: the time from the loss to the first cue for every set of the P3 diff, against the 1 s budget; writes
p4-timing.md and p4-timing.svg.

    python3 sweep.py                        # P2 page
    python3 sweep.py --check                # fail if the P2 page differs from a fresh run
    python3 sweep.py joint                  # P3: full sweep, JSON and page
    python3 sweep.py joint --check --order 2
    python3 sweep.py timing                 # P4: time to the first cue for every set of P3; page and figure
"""

import json
import sys
from multiprocessing import Pool
from pathlib import Path

import model as m

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import treediff as td  # noqa: E402

ROOT = td.ROOT
GOAL, TOP = m.EVENTS["goal"], m.EVENTS["top_event"]
OUT = HERE / "p2-single-faults.md"
P3_JSON = HERE / "p3-minimal-sets.json"
P3_OUT = HERE / "p3-joint-faults.md"
MAX_ORDER = 4
P4_OUT = HERE / "p4-timing.md"
P4_SVG = HERE / "p4-timing.svg"
HORIZON_S = 6.0
# Modes of the SoC-independent cues the tree holds latent: the siren (BE-2.14 latent) and the cancel (BE-6.06 latent)
SIRENS = {e for e, (fxn, _) in m.MODE_OF.items() if fxn == "siren"}
LATENT_CUES = SIRENS | {"BE-6.06"}
CAUSES = {x["event"] for x in m.EVENTS["modes"] if x["kind"] == "cause"}
SYNTHETIC = ("> **Synthetic (DSR-12).** Generated by [`sweep.py`](sweep.py){how} from the fmdtools model "
             "([`model.py`](model.py), [`events.yaml`](events.yaml)); do not edit by hand. No evidence credit: the "
             "results point reviewers at possible gaps in the WP-A-04 tree, and a tree changes only after a person "
             "reviews the finding.")


def fmt(v: float | None) -> str:
  return "–" if v is None else f"{v:.2f}"


def why_covered(cues: set[str]) -> str:
  """Why the model covers a set that the tree holds as giving TE-06, from the cue that came in time."""
  parts = []
  if "siren" in cues:
    parts.append("the siren sounds within the budget (heartbeat loss, engaged mismatch, or the cancel-lag guard); "
                 "the tree holds BE-2.14 latent")
  if "cluster" in cues:
    parts.append("the host's ACC cancel on the immediate disable changes the cluster cruise indicator within the "
                 "budget (TSR-303); the tree holds BE-6.06 latent")
  return "; ".join(parts) or "missing"


# ------------------------------------------------------------------------------------------------- step P2

def build() -> str:
  singles, latent = td.tree_singles(GOAL)
  phases = list(m.PHASES)
  results = {(e, ph): m.run((e,), phase=ph) for e in m.MODE_OF for ph in phases}
  model_latent = sorted(x["id"] for x in m.EVENTS["latent_in_model"])
  tree_latent = sorted(e for e in latent if e in m.MODE_OF or e in model_latent)

  out = [
    f"# {GOAL} single faults (step P2)",
    "",
    SYNTHETIC.format(how=""),
    "",
    f"Each of the {len(m.MODE_OF)} failure modes is injected alone, {m.FAULT_TICK * m.TICK:.1f} s into a run, in each "
    "road phase. Times are seconds after the injection; a cue is a delivered SoC alert, the panda siren, the cluster "
    "cruise indicator changing on the host's ACC cancel, or the driver feeling the end of ACC deceleration on a supply "
    f"loss. {TOP}: deceleration lost and no cue within {m.EVENTS['budget_s']:.1f} s.",
    "",
    "## Road phases",
    "",
    "| Phase | End of ACC deceleration felt | Source |",
    "|---|---|---|",
  ]
  for ph in phases:
    p = m.PHASES[ph]
    out.append(f"| {ph} | {'yes' if p['decel_felt'] else 'no'} | {p['source']} |")
  out += [
    "",
    "The model has no speed or gap, so a phase changes only what the driver can feel on a supply loss.",
    "",
    "## Results",
    "",
    f"Tree alone: the event gives {TOP} in the tree once its latent events (" + ", ".join(tree_latent) + ") are "
    "taken as present, with the undeveloped events named. The model holds " + ", ".join(model_latent) +
    " latent too, but BE-2.14 and BE-6.06 are modes (see the [README](../README.md)).",
    "",
    "| Event | Mode | " + " | ".join(f"{ph}: lost / cue" for ph in phases) + f" | Model {TOP} | Tree alone | Agree |",
    "|---|---|" + "---|" * len(phases) + "---|---|---|",
  ]
  diffs = []
  for e, (fxn, mode) in m.MODE_OF.items():
    cells, te_phases = [], []
    for ph in phases:
      o = results[(e, ph)]
      cue = "none" if o.cue is None else f"{fmt(o.t_cue)} {o.cue}"
      cells.append(f"{fmt(o.t_lost)} / {cue}" if o.t_lost is not None else "not lost")
      if o.top_event:
        te_phases.append(ph)
    model_te = "no" if not te_phases else ("**yes**" if len(te_phases) == len(phases) else
                                           "**" + ", ".join(te_phases) + "**")
    tree = "no" if e not in singles else ("yes" if not singles[e] else "with " + ", ".join(singles[e]))
    tree_alone = e in singles and not singles[e]
    agree = "yes"
    if bool(te_phases) != tree_alone:
      agree = "**no**"
      diffs.append((e, te_phases, singles.get(e)))
    out.append(f"| {e} | {fxn}.{mode} | " + " | ".join(cells) + f" | {model_te} | {tree} | {agree} |")

  out += ["", "## Differences from the tree", ""]
  if not diffs:
    out.append("None.")
  for e, te_phases, ext in diffs:
    if te_phases and ext:
      out.append(f"- **{e}** gives {TOP} alone in the model ({', '.join(te_phases)}); the tree needs "
                 f"{', '.join(ext)} too. The model takes no cue from the driver there: see the phase's source.")
    elif te_phases:
      out.append(f"- **{e}** gives {TOP} alone in the model ({', '.join(te_phases)}), not in the tree.")
    else:
      cues = {results[(e, ph)].cue for ph in phases if results[(e, ph)].cue}
      out.append(f"- **{e}** gives {TOP} alone in the tree, not in the model: {why_covered(cues)}.")
  out += ["", "Each difference goes to the FTA owner as a finding; step P3 does the same for joint faults.", ""]
  return "\n".join(out)


# ------------------------------------------------------------------------------------------------- step P3

def _te(events: tuple[str, ...]) -> tuple[tuple[str, ...], bool]:
  return events, m.run(events).top_event


def covering(c: frozenset[str], model: list[frozenset[str]]) -> list[frozenset[str]]:
  """Model sets that are a tree set plus only latent-cue failures: what the model needs beyond the tree."""
  return [f for f in model if c < f and (f - c) <= LATENT_CUES]


def build_joint(data: dict) -> str:
  solver, cut_sets = td.solve(GOAL)
  latent = solver.latent
  model = [frozenset(c) for c in data["sets"]]
  tree = td.effective(cut_sets, latent, data["order"])
  model_only = [c for c in model if c not in tree]
  tree_only = [c for c in tree if c not in model]
  gaps = td.tree_gaps(model, cut_sets, latent)

  out = [
    f"# {GOAL} joint faults (step P3)",
    "",
    SYNTHETIC.format(how=" `joint`") + " The sets are in [`p3-minimal-sets.json`](p3-minimal-sets.json).",
    "",
    f"Every set of 1 to {data['order']} of the {len(m.MODE_OF)} failure modes that holds a cause, injected together "
    f"in the {data['phase']} phase; supersets of a set already found are not run. Runs per order: "
    + ", ".join(f"{k + 1}: {n}" for k, n in enumerate(data["runs"])) + f" ({sum(data['runs'])} in all).",
    "",
    "The tree's side is its computed cut sets with the tree's latent events (" + ", ".join(sorted(
      e for e in latent if any(e in c for c in cut_sets))) + ") taken as present, minimised: "
    f"{len(tree)} effective sets of up to {data['order']} events. The model holds "
    + ", ".join(sorted(x["id"] for x in m.EVENTS["latent_in_model"])) + " latent too, but BE-2.14 (siren not "
    "triggered) and BE-6.06 (no ACC cancel) are modes, so the model shows where the siren or the cancel covers a set.",
    "",
    "## Summary",
    "",
    "| Result | Sets |",
    "|---|---|",
    f"| Minimal sets in the model | {len(model)} |",
    f"| Effective sets in the tree | {len(tree)} |",
    f"| Same in both | {len(model) - len(model_only)} |",
    f"| **In the model, not predicted by the tree** (possible gap in the tree) | **{len(gaps)}** |",
    f"| In the tree, not in the model | {len(tree_only)} |",
    "",
    "## In the model, not predicted by the tree",
    "",
  ]
  out += [f"None: every set that gives {TOP} in the model contains an effective set of the tree."] if not gaps else \
    [f"- {td.fset(c)}" for c in gaps]
  out += [
    "",
    "## In the tree, not in the model",
    "",
    f"| Tree effective set | Model: {TOP} needs as well | Why |",
    "|---|---|---|",
  ]
  for c in tree_only:
    ext = covering(c, model)
    if ext:
      extra = " or ".join(sorted("+".join(sorted(f - c)) for f in ext))
      needs = set().union(*(f - c for f in ext))
      if "BE-6.06" in needs:
        why = ("the ACC cancel on the immediate disable changes the cluster within the budget, and a cancel without "
               "effect gets the cancel-lag siren (TSR-516(c)); the tree holds BE-6.06 and BE-2.14 latent")
      else:
        why = "the siren sounds within the budget; the tree holds BE-2.14 latent"
    else:
      extra, why = "–", f"**not explained** within order {data['order']}: a reviewer looks at the path"
    out.append(f"| {td.fset(c)} | {extra} | {why} |")
  out += [
    "",
    "## All minimal sets of the model",
    "",
    "| Order | Set | In the tree |",
    "|---|---|---|",
  ]
  for c in model:
    if c in tree:
      where = "yes"
    elif any(t < c and (c - t) <= LATENT_CUES for t in tree_only):
      where = "with latent-cue failures in place of the tree's latent BE-2.14 or BE-6.06"
    else:
      where = "no"
    out.append(f"| {len(c)} | {td.fset(c)} | {where} |")
  out += [
    "",
    "## Limits",
    "",
    f"- One road phase ({data['phase']}). [P2](p2-single-faults.md) shows what following at a steady gap changes for "
    "single faults.",
    "- Pruning supersets assumes nothing more is learned from a superset of a set already found. A further fault can "
    "add a cue (a supply loss lets the driver feel the end of ACC deceleration), so a superset can be free of "
    f"{TOP} in the model; that does not change which sets are minimal.",
    f"- Sets above order {data['order']} are not run, so a tree set that needs both BE-6.06 and a siren failure is "
    f"explained only if it has at most {data['order'] - 2} events.",
    "",
  ]
  return "\n".join(out)


def joint(argv: list[str]) -> int:
  order = int(argv[argv.index("--order") + 1]) if "--order" in argv else MAX_ORDER
  sets, runs = td.minimal_sets(m.MODE_OF, CAUSES, _te, order)
  rel = lambda p: p.relative_to(ROOT)
  if "--check" in argv:
    data = json.loads(P3_JSON.read_text(encoding="utf-8"))
    want = [tuple(c) for c in data["sets"] if len(c) <= order]
    ok = [tuple(c) for c in sets] == want and data["runs"][:order] == runs and \
        P3_OUT.read_text(encoding="utf-8") == build_joint(data)
    if not ok:
      print(f"{rel(P3_JSON)} or {rel(P3_OUT)} is stale: run python3 {rel(Path(__file__))} joint", file=sys.stderr)
      return 1
    return 0
  if order != MAX_ORDER:
    print(f"write only from the full sweep (order {MAX_ORDER})", file=sys.stderr)
    return 2
  data = {"goal": GOAL, "phase": m.DEFAULT_PHASE, "order": order, "runs": runs, "sets": [list(c) for c in sets]}
  P3_JSON.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
  P3_OUT.write_text(build_joint(data), encoding="utf-8")
  print(f"wrote {rel(P3_JSON)} and {rel(P3_OUT)}")
  return 0


# ------------------------------------------------------------------------------------------------- step P4

def _timed(events: tuple[str, ...]) -> m.Outcome:
  return m.run(events, horizon_s=HORIZON_S)


def timing_sets() -> tuple[list[frozenset[str]], dict, set]:
  solver, cut_sets = td.solve(GOAL)
  latent = solver.latent
  data = json.loads(P3_JSON.read_text(encoding="utf-8"))
  model = [frozenset(c) for c in data["sets"]]
  tree = td.effective(cut_sets, latent, data["order"])
  sets = sorted(set(tree) | set(model), key=lambda c: (len(c), sorted(c)))
  rows = td.mcs_rows(GOAL, solver, latent)
  label = {}
  for c in sets:
    ids = sorted({r for r, e in rows if e == c or (e < c and (c - e) <= LATENT_CUES)},
                 key=lambda x: float(x.split(".")[1]))
    label[c] = ", ".join(ids) or "–"
  return sets, label, set(tree)


COLOUR = {"alert": "#2a78d6", "siren": "#6250d6", "cluster": "#c27a12", "feel": "#1baf7a"}


def figure(results: list[tuple[frozenset[str], m.Outcome]]) -> str:
  rows = sorted(results, key=lambda r: (r[1].t_cue is None, (r[1].t_cue or 0) - (r[1].t_lost or 0)))
  W, L, rh, T = 760, 250, 15, 30
  H = T + rh * len(rows) + 40
  X = lambda v: L + v / HORIZON_S * (W - L - 70)
  out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="system-ui,sans-serif" font-size="10">',
         f'<rect width="{W}" height="{H}" fill="#fcfcfb"/>',
         f'<rect x="{X(0)}" y="{T - 8}" width="{X(1) - X(0):.1f}" height="{rh * len(rows) + 8}" fill="#0ca30c" opacity="0.07"/>',
         f'<text x="{X(0) + 4}" y="{T - 12}" fill="#006300" font-weight="600">1.0 s budget ({GOAL})</text>']
  for v in range(int(HORIZON_S) + 1):
    out.append(f'<line x1="{X(v):.1f}" x2="{X(v):.1f}" y1="{T - 8}" y2="{H - 30}" stroke="#e1e0d9"/>')
    out.append(f'<text x="{X(v):.1f}" y="{H - 16}" fill="#898781" text-anchor="middle">{v} s</text>')
  for i, (c, o) in enumerate(rows):
    y = T + i * rh + rh / 2
    out.append(f'<text x="{L - 8}" y="{y + 3.5}" fill="#0b0b0b" text-anchor="end" font-family="ui-monospace,monospace" '
               f'font-size="9">{"+".join(sorted(c))}</text>')
    if o.t_cue is None:
      out.append(f'<text x="{X(HORIZON_S) + 6:.1f}" y="{y + 3.5}" fill="#d03b3b" font-weight="600">no cue</text>')
      out.append(f'<line x1="{X(0)}" x2="{X(HORIZON_S):.1f}" y1="{y}" y2="{y}" stroke="#d03b3b" stroke-dasharray="2 3"/>')
      continue
    dt = o.t_cue - (o.t_lost or 0)
    out.append(f'<line x1="{X(0)}" x2="{X(dt):.1f}" y1="{y}" y2="{y}" stroke="#c3c2b7"/>')
    out.append(f'<circle cx="{X(dt):.1f}" cy="{y}" r="4" fill="{COLOUR[o.cue]}" stroke="#fcfcfb" stroke-width="2"/>')
    out.append(f'<text x="{X(dt) + 8:.1f}" y="{y + 3.5}" fill="#52514e">{dt:.2f} s {o.cue}</text>')
  lx = L
  for k, col in COLOUR.items():
    out.append(f'<circle cx="{lx}" cy="{H - 4}" r="4" fill="{col}"/><text x="{lx + 8}" y="{H - 1}" fill="#52514e">{k}</text>')
    lx += 64
  out.append("</svg>")
  return "\n".join(out) + "\n"


def build_timing(results, label, tree) -> str:
  budget = m.EVENTS["budget_s"]
  def gap(o):
    return None if o.t_cue is None else o.t_cue - (o.t_lost or 0)
  within = [r for r in results if gap(r[1]) is not None and gap(r[1]) <= budget]
  late = [r for r in results if gap(r[1]) is not None and gap(r[1]) > budget]
  none = [r for r in results if gap(r[1]) is None]
  out = [
    f"# {GOAL} time to the first cue (step P4)",
    "",
    "> **Synthetic (DSR-12).** Generated by [`sweep.py`](sweep.py) `timing` from the fmdtools model; do not edit by hand. "
    "No evidence credit: the times are the model's inputs ([`events.yaml`](events.yaml)) combined, not measurements.",
    "",
    f"Every set of the [P3](p3-joint-faults.md) diff ({len(results)} sets: the tree's effective sets and the model's "
    f"minimal sets), injected in the {m.DEFAULT_PHASE} phase and run for {HORIZON_S:.0f} s after the injection. The "
    f"time is from the loss of deceleration to the first perceivable cue; the {GOAL} budget is {budget:.1f} s.",
    "",
    "| Result | Sets |",
    "|---|---|",
    f"| Cue within the budget | {len(within)} |",
    f"| **Cue after the budget** | **{len(late)}** |",
    f"| **No cue within {HORIZON_S:.0f} s** | **{len(none)}** |",
    "",
    "![Time from the loss to the first cue](p4-timing.svg)",
    "",
    "## Sets with a late cue or none",
    "",
    "| Set | WP-A-04 row | Tree | Lost (after the fault) | First cue (after the fault) | Over the budget by |",
    "|---|---|---|---|---|---|",
  ]
  for c, o in sorted(late + none, key=lambda r: (gap(r[1]) is None, -(gap(r[1]) or 0), sorted(r[0]))):
    g = gap(o)
    cue = "none" if o.t_cue is None else f"{o.t_cue:.2f} s {o.cue}"
    over = f"> {HORIZON_S - budget:.1f} s" if g is None else f"{g - budget:.2f} s"
    out.append(f"| {td.fset(c)} | {label[c]} | {'yes' if c in tree else 'latent-cue failure added'} | "
               f"{o.t_lost:.2f} s | {cue} | {over} |")
  out += [
    "",
    "## Sets warned within the budget",
    "",
    "These are tree sets that the model covers with a cue in time: the siren on a heartbeat loss or an engaged "
    "mismatch, or the cluster cruise change after the host's ACC cancel (P3).",
    "",
    "| Set | WP-A-04 row | Lost (after the fault) | First cue (after the fault) | Margin |",
    "|---|---|---|---|---|",
  ]
  for c, o in sorted(within, key=lambda r: (gap(r[1]), sorted(r[0]))):
    out.append(f"| {td.fset(c)} | {label[c]} | {o.t_lost:.2f} s | {o.t_cue:.2f} s {o.cue} | {budget - gap(o):.2f} s |")
  out += [
    "",
    "## The times the model uses",
    "",
    "Each late cue above comes from one of these inputs; the source names the WP-A-04 or WP-S-02 basis or the plant "
    "result. Two cue inputs exceed the budget: the 3 s soft disable before the cancel (BE-2.10, SWF-048.C1) and the "
    "5 s System Unresponsive alert after a selfdrived stop.",
    "",
    "| Input | Seconds | ≤ 1 s | Source |",
    "|---|---|---|---|",
  ]
  for k, v in m.EVENTS["timing"].items():
    out.append(f"| `{k}` | {v['s']:g} | {'yes' if v['s'] <= budget else '**no**'} | {v['source']} |")
  out.append("")
  return "\n".join(out)


def timing(argv: list[str]) -> int:
  sets, label, tree = timing_sets()
  with Pool() as pool:
    outcomes = pool.map(_timed, [tuple(sorted(c)) for c in sets], chunksize=4)
  results = list(zip(sets, outcomes))
  page, svg = build_timing(results, label, tree), figure(results)
  rel = lambda p: p.relative_to(ROOT)
  if "--check" in argv:
    if not P4_OUT.exists() or P4_OUT.read_text(encoding="utf-8") != page or P4_SVG.read_text(encoding="utf-8") != svg:
      print(f"{rel(P4_OUT)} is stale: run python3 {rel(Path(__file__))} timing", file=sys.stderr)
      return 1
    return 0
  P4_OUT.write_text(page, encoding="utf-8")
  P4_SVG.write_text(svg, encoding="utf-8")
  print(f"wrote {rel(P4_OUT)} and {rel(P4_SVG)}")
  return 0


def main(argv: list[str]) -> int:
  if argv[:1] == ["joint"]:
    return joint(argv[1:])
  if argv[:1] == ["timing"]:
    return timing(argv[1:])
  text = build()
  if "--check" in argv:
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
      print(f"{OUT.relative_to(ROOT)} is stale: run python3 {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
      return 1
    return 0
  OUT.write_text(text, encoding="utf-8")
  print(f"wrote {OUT.relative_to(ROOT)}")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
