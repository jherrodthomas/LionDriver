#!/usr/bin/env python3
"""SG-01 fault sweeps (tool evaluation TE-02, extended by DQ-417), compared with the WP-A-04 §2 tree.

Step P2: every failure mode alone, in each phase; writes p2-single-faults.md.
Step P3: the minimal fault sets of up to 3 modes that give TE-01 in any phase (the tree's effective sets have at most
3 events); writes p3-minimal-sets.json and p3-joint-faults.md. `--check --order 2` checks the sets of order 1 and 2
against the JSON (the pull-request job); the full check runs on a schedule.

There is no P4 page for SG-01: TE-01 is not a late cue. Its two timed branches, a stale torque and the stock LKA with
the item, are timed against the 0.5 s FTTI inside the model, and P2 gives the time each set reaches TE-01.

    python3 sweep.py                        # P2 page
    python3 sweep.py --check                # fail if the P2 page differs from a fresh run
    python3 sweep.py joint                  # P3: full sweep, JSON and page
    python3 sweep.py joint --check --order 2
"""

import json
import sys
from pathlib import Path

import model as m

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import treediff as td  # noqa: E402

ROOT = td.ROOT
GOAL, TOP = m.EVENTS["goal"], m.EVENTS["top_event"]
OUT = HERE / "p2-single-faults.md"
P3_JSON = HERE / "p3-minimal-sets.json"
P3_OUT = HERE / "p3-joint-faults.md"
MAX_ORDER = 3
CAUSES = {x["event"] for x in m.EVENTS["modes"] if x["kind"] == "cause"}
BRANCH = {"excess": "excessive torque not limited by the EPS (G1.1)", "unwanted": "torque the driver does not want (G1.2)",
          "stale": "stale torque held beyond the FTTI (G1.3)", "overlap": "stock LKA with the item beyond the FTTI (G1.4)"}
# Why the model and the machine-readable tree differ, by the event that decides it. Each names the model behaviour and
# its source; the tree changes only after the FTA owner reviews the finding.
WHY = {
  "BE-1.17": "the SoC reads the same stuck 0x1D2 as the envelope, so on a cancel it stays engaged and keeps commanding "
             "without BE-1.15; the WP-A-04 table notes this as \"effective 1 through DFI-10\" (MCS-01.9), the drawn tree "
             "keeps BE-1.15",
  "BE-1.13": "as BE-1.17: the stale cruise frame reaches the SoC too (DFI-10, MCS-01.4 \"effective\" single point), "
             "the drawn tree keeps BE-1.15",
  "BE-1.16": "a brake press also drops PCM cruise, so the envelope revokes on 0x1D2 (TSR-301) and the SoC disengages on "
             "it; a stuck brake frame matters only with a stuck cruise frame too",
  "BE-1.12": "one corrupted frame opens the TSR-301 engagement window, and the next genuine 0x1D2 (cruise inactive) "
             "revokes within one step; a replay that holds cruise active acts as BE-1.13",
  "BE-1.18": "a debug build has no envelope, but the SoC still gates its own command on its engagement, so the model "
             "needs a SoC fault too; the tree takes the missing envelope as the failure (configuration single point)",
}
SYNTHETIC = ("> **Synthetic (DSR-12).** Generated by [`sweep.py`](sweep.py){how} from the fmdtools model "
             "([`model.py`](model.py), [`events.yaml`](events.yaml)); do not edit by hand. No evidence credit: the "
             "results point reviewers at possible gaps in the WP-A-04 tree, and a tree changes only after a person "
             "reviews the finding.")


def why(c: frozenset[str]) -> str:
  hits = [WHY[e] for e in sorted(c) if e in WHY]
  return "; ".join(hits) or "**not explained**: a reviewer looks at the path"


# ------------------------------------------------------------------------------------------------- step P2

def build() -> str:
  singles, latent = td.tree_singles(GOAL)
  phases = list(m.PHASES)
  results = {(e, ph): m.run_phase((e,), ph) for e in m.MODE_OF for ph in phases}
  model_latent = sorted(x["id"] for x in m.EVENTS["latent_in_model"])
  tree_latent = sorted(e for e in latent if e in m.MODE_OF or e in model_latent)

  out = [
    f"# {GOAL} single faults (step P2)",
    "",
    SYNTHETIC.format(how=""),
    "",
    f"Each of the {len(m.MODE_OF)} failure modes is injected alone, {m.FAULT_TICK * m.TICK:.1f} s into a run, in each "
    f"phase. A cell gives the {TOP} branch the run reaches and when (seconds after the injection): "
    + "; ".join(f"**{k}**, {v}" for k, v in BRANCH.items()) + f". The FTTI is {m.EVENTS['budget_s']:.1f} s; torque the "
    f"driver does not want counts once it has lasted the SG-05 release time, {m.EVENTS['release_s']:.1f} s.",
    "",
    "## Phases",
    "",
    "| Phase | Item engaged at the start | Driver | Source |",
    "|---|---|---|---|",
  ]
  for ph in phases:
    p = m.PHASES[ph]
    out.append(f"| {ph} | {'yes' if p['engaged'] else 'no'} | {p['driver']} | {p['source']} |")
  out += [
    "",
    "## Results",
    "",
    f"Tree alone: the event gives {TOP} in the tree once its latent events (" + ", ".join(tree_latent) + ") are "
    "taken as present, with the undeveloped events named. The model holds " + " and ".join(model_latent) + " latent too.",
    "",
    "| Event | Mode | " + " | ".join(phases) + f" | Model {TOP} | Tree alone | Agree |",
    "|---|---|" + "---|" * len(phases) + "---|---|---|",
  ]
  diffs = []
  for e, (fxn, mode) in m.MODE_OF.items():
    cells, te_phases = [], []
    for ph in phases:
      o = results[(e, ph)]
      cells.append(f"{o.branch} {o.t:.2f}" if o.top_event else "–")
      if o.top_event:
        te_phases.append(ph)
    model_te = "no" if not te_phases else "**" + ", ".join(te_phases) + "**"
    tree = "no" if e not in singles else ("yes" if not singles[e] else "with " + ", ".join(singles[e]))
    tree_alone = e in singles and not singles[e]
    agree = "yes"
    if bool(te_phases) != tree_alone:
      agree = "**no**"
      diffs.append(e)
    out.append(f"| {e} | {fxn}.{mode} | " + " | ".join(cells) + f" | {model_te} | {tree} | {agree} |")
  out += ["", "## Differences from the tree", ""]
  out += ["None."] if not diffs else [f"- **{e}**: {why(frozenset({e}))}." for e in diffs]
  out += ["", "Each difference goes to the FTA owner as a finding; step P3 does the same for joint faults.", ""]
  return "\n".join(out)


# ------------------------------------------------------------------------------------------------- step P3

def _te(events: tuple[str, ...]) -> tuple[tuple[str, ...], bool]:
  return events, m.run(events).top_event


def build_joint(data: dict) -> str:
  solver, cut_sets = td.solve(GOAL)
  latent = solver.latent
  model = [frozenset(c) for c in data["sets"]]
  tree = td.effective(cut_sets, latent, data["order"])
  model_only = [c for c in model if c not in tree]
  tree_only = [c for c in tree if c not in model]
  gaps = td.tree_gaps(model, cut_sets, latent)
  branches = {}
  for c in model:
    branches.setdefault(data["branch"][",".join(sorted(c))], []).append(c)

  out = [
    f"# {GOAL} joint faults (step P3)",
    "",
    SYNTHETIC.format(how=" `joint`") + " The sets are in [`p3-minimal-sets.json`](p3-minimal-sets.json).",
    "",
    f"Every set of 1 to {data['order']} of the {len(m.MODE_OF)} failure modes that holds a cause, run in each phase "
    f"until one reaches {TOP}; supersets of a set already found are not run. Runs per order: "
    + ", ".join(f"{k + 1}: {n}" for k, n in enumerate(data["runs"])) + f" ({sum(data['runs'])} sets in all).",
    "",
    "The tree's side is its computed cut sets with the tree's latent events (" + ", ".join(sorted(
      e for e in latent if any(e in c for c in cut_sets))) + ") taken as present, minimised: "
    f"{len(tree)} effective sets of up to {data['order']} events.",
    "",
    "## Summary",
    "",
    "| Result | Sets |",
    "|---|---|",
    f"| Minimal sets in the model | {len(model)} |",
    f"| Effective sets in the tree | {len(tree)} |",
    f"| Same in both | {len(model) - len(model_only)} |",
    f"| **In the model, not predicted by the drawn tree** | **{len(gaps)}** |",
    f"| In the tree, not in the model | {len(tree_only)} |",
    "",
    "| Branch of the model's sets | Sets |",
    "|---|---|",
  ]
  for k, v in BRANCH.items():
    out.append(f"| {v} | {len(branches.get(k, []))} |")
  out += [
    "",
    "## In the model, not predicted by the drawn tree",
    "",
  ]
  if not gaps:
    out.append(f"None: every set that gives {TOP} in the model contains an effective set of the tree.")
  else:
    out += ["| Model set | Why |", "|---|---|"] + [f"| {td.fset(c)} | {why(c)} |" for c in gaps]
  out += [
    "",
    "## In the tree, not in the model",
    "",
    "| Tree effective set | Why |",
    "|---|---|",
  ]
  for c in tree_only:
    smaller = [f for f in model if f < c]
    if smaller:
      out.append(f"| {td.fset(c)} | the model reaches {TOP} with less: "
                 + " or ".join(td.fset(f) for f in smaller) + f"; {why(c)} |")
    else:
      out.append(f"| {td.fset(c)} | {why(c)} |")
  out += [
    "",
    "## All minimal sets of the model",
    "",
    "| Order | Set | Branch | In the tree |",
    "|---|---|---|---|",
  ]
  for c in model:
    out.append(f"| {len(c)} | {td.fset(c)} | {data['branch'][','.join(sorted(c))]} | "
               f"{'yes' if c in tree else 'no'} |")
  out += [
    "",
    "## Limits",
    "",
    "- The model has no torque magnitudes: a command is in limit, excessive, or stale. Whether a given torque is "
    "controllable is the plant's and the vehicle tests' (AOU-01R).",
    "- Pruning supersets assumes nothing more is learned from a superset of a set already found.",
    f"- Sets above order {data['order']} are not run; the tree's effective sets have at most 3 events.",
    "",
  ]
  return "\n".join(out)


def joint(argv: list[str]) -> int:
  order = int(argv[argv.index("--order") + 1]) if "--order" in argv else MAX_ORDER
  sets, runs = td.minimal_sets(m.MODE_OF, CAUSES, _te, order)
  rel = lambda p: p.relative_to(ROOT)
  if "--check" in argv:
    data = json.loads(P3_JSON.read_text(encoding="utf-8"))
    want = [tuple(c) for c in data["sets"] if len(c) <= order]
    ok = [tuple(c) for c in sets] == want and data["runs"][:order] == runs and \
        P3_OUT.read_text(encoding="utf-8") == build_joint(data)
    if not ok:
      print(f"{rel(P3_JSON)} or {rel(P3_OUT)} is stale: run python3 {rel(Path(__file__))} joint", file=sys.stderr)
      return 1
    return 0
  if order != MAX_ORDER:
    print(f"write only from the full sweep (order {MAX_ORDER})", file=sys.stderr)
    return 2
  branch = {",".join(c): m.run(c).branch for c in sets}
  data = {"goal": GOAL, "order": order, "runs": runs, "sets": [list(c) for c in sets], "branch": branch}
  P3_JSON.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
  P3_OUT.write_text(build_joint(data), encoding="utf-8")
  print(f"wrote {rel(P3_JSON)} and {rel(P3_OUT)}")
  return 0


def main(argv: list[str]) -> int:
  if argv[:1] == ["joint"]:
    return joint(argv[1:])
  text = build()
  if "--check" in argv:
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
      print(f"{OUT.relative_to(ROOT)} is stale: run python3 {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
      return 1
    return 0
  OUT.write_text(text, encoding="utf-8")
  print(f"wrote {OUT.relative_to(ROOT)}")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
