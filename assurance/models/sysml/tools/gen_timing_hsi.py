#!/usr/bin/env python3
"""Generate the timing budgets and the HSI signals of the SysML model from the work products.

  model/Timing.sysml   the FTTI budgets of WP-S-04 §3.7 as `constraint` usages of TimingBudget, one per row, named by
                       the row label (the key other tools already use, e.g. fmea_lint's ftti_ref). Each keeps its
                       cells as written (FTTI, FDTI, FRTI, margin, FHTI) and, where a cell is a plain time ("≤ 0.2 s",
                       "0.5 s", optionally followed by a note in brackets), the value in seconds; the safety goals the
                       row label names and the TSRs any cell names
  model/Signals.sysml  the safety-relevant signals S-01…S-nn of WP-S-05 §11 as `item` usages of Signal: the HSI
                       interfaces of their table, direction, owner elements (E-nn and host processes named in the Owner
                       column), integrity, validity, rate, failure reaction, ASIL, TSRs (bare numbers and ranges
                       expanded against the model) and test cases; and the hardware and software responsibilities
                       of WP-S-05 §11.4 as `item` usages of HsiResponsibility, one per interface HSI-nn: what the
                       hardware provides, what the software must do, who detects a failure, the reaction, shared
                       resources, the hardware and software owner elements, the TSRs the row names and its status,
                       with the HW resource of the §2 summary and the parts of the safety MCU (E-04a) it names

Checks H1-H5 in check_model.py hold the model to these files and the budgets to their own arithmetic.

Usage: python3 tools/gen_timing_hsi.py [--check]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_DIR = HERE.parent / "model"
ASSURANCE = HERE.parents[2]
sys.path.insert(0, str(HERE))
from gen_requirements import doc, plain, s, tables  # noqa: E402

WP_S04 = ASSURANCE / "03-system" / "WP-S-04-timing-ftti-budget.md"
WP_S05 = ASSURANCE / "03-system" / "WP-S-05-hsi-specification.md"
OUT = {"timing": MODEL_DIR / "Timing.sysml", "signals": MODEL_DIR / "Signals.sysml"}
HEADER = "// GENERATED by assurance/models/sysml/tools/gen_timing_hsi.py from the work products. Do not edit;\n" \
         "// change the work product and regenerate (README §7).\n"
BUDGET_HEAD = ["SG / fault class", "FTTI", "FDTI budget", "FRTI budget", "Margin", "FHTI (FDTI + FRTI)"]
SIGNAL_HEAD = ["ID", "Signal", "Dir", "Owner (HW / SW)", "Type / bits", "Range, scale, units", "Integrity",
               "Validity / liveness", "Rate / max age", "Failure reaction", "TSR", "ASIL", "Tests"]
RESP_HEAD = ["HSI", "Hardware provides", "Software must", "Failure detected by", "Reaction", "Shared with", "HW owner",
             "SW owner", "Status"]
STATUS = ("in place", "partial", "missing")
TIME_RE = re.compile(r"^(?:[≤≥<>]\s*)?(\d+(?:\.\d+)?)\s*(ms|s)\b\s*(.*)$")


class TimingError(ValueError):
  pass


def seconds(cell: str) -> float | None:
  """A cell that is one time, possibly with a bracketed note, in seconds; None for anything else."""
  m = TIME_RE.match(plain(cell))
  if not m:
    return None
  rest = m.group(3).strip()
  if rest and not (rest.startswith("(") and not rest.startswith("(+")):
    return None
  v = float(m.group(1))
  return v / 1000 if m.group(2) == "ms" else v


def num(v: float | None) -> str:
  return "" if v is None else f"{v:g}"


def str_list(items: list[str]) -> str:
  return "(" + ", ".join(s(x) for x in items) + ")" if items else '""'


def goals_of(label: str) -> list[str]:
  out = []
  for m in re.finditer(r"SG-(\d\d)(?!\d)((?:/\d\d)*)", label):
    for n in [m.group(1), *re.findall(r"\d\d", m.group(2))]:
      if f"SG-{n}" not in out:
        out.append(f"SG-{n}")
  return out


def budgets() -> list[dict]:
  rows = None
  for heading, head, rs in tables(WP_S04):
    if heading.startswith("3.7 ") and head == BUDGET_HEAD:
      rows = rs
  if not rows:
    raise TimingError(f"WP-S-04 §3.7 has no table with columns {BUDGET_HEAD}")
  out = []
  for r in rows:
    c = dict(zip(BUDGET_HEAD, r))
    label = plain(c["SG / fault class"])
    goals = goals_of(label)
    if not goals:
      raise TimingError(f"WP-S-04 §3.7 row {label!r} names no safety goal")
    tsr = sorted({x for v in r for x in re.findall(r"TSR-\d{3}", v)})
    out.append({"label": label, "goals": goals, "tsr": tsr,
                **{k: c[h] for k, h in (("ftti", "FTTI"), ("fdti", "FDTI budget"), ("frti", "FRTI budget"),
                                         ("margin", "Margin"), ("fhti", "FHTI (FDTI + FRTI)"))}})
  return out


CODE_HEAD = ["#", "Mechanism", "Code", "Derivation", "Worst-case time"]
REACTION_HEAD = ["Fault class", "Budget", "Baseline", "Verdict", "Required change", "TSR"]
VERDICTS = ("met", "design", "partly", "not", "verify")


def code_times() -> list[dict]:
  """The code-derived detection and reaction times T-nn of WP-S-04 §4."""
  for heading, head, rows in tables(WP_S04):
    if heading.startswith("4. ") and head == CODE_HEAD:
      out = []
      for r in rows:
        c = dict(zip(CODE_HEAD, r))
        if not re.fullmatch(r"T-\d\d[a-z]?", c["#"]):
          raise TimingError(f"WP-S-04 §4: {c['#']!r} is not a time ID T-nn")
        out.append({"id": c["#"], "mechanism": plain(c["Mechanism"]), "code": c["Code"], "derivation": c["Derivation"],
                    "worst": c["Worst-case time"]})
      return out
  raise TimingError(f"WP-S-04 §4 has no table with columns {CODE_HEAD}")


def reactions() -> list[dict]:
  """The fault classes of WP-S-04 §5: budget, baseline time, the code-derived times it cites, the latest verdict as
  WP-S-04 Figure 5-3 sorts it (fig_s04_verdicts.VERDICT, held to the Verdict cell by a quoted phrase), TSRs."""
  sys.path.insert(0, str(ASSURANCE / "03-system" / "figures"))
  import fig_s04_verdicts as fv
  try:
    sorted_rows = {r["name"]: r for r in fv.parse(WP_S04.read_text(encoding="utf-8"))}
  except fv.VerdictError as e:
    raise TimingError(f"WP-S-04 §5: {e}") from e
  for heading, head, rows in tables(WP_S04):
    if heading.startswith("5. ") and head == REACTION_HEAD:
      out = []
      for r in rows:
        c = dict(zip(REACTION_HEAD, r))
        name = plain(re.sub(r"\s*\(added [^)]*\)", "", c["Fault class"]))
        sr = sorted_rows.get(name)
        if sr is None:
          raise TimingError(f"WP-S-04 §5 row {name!r} is not sorted by fig_s04_verdicts")
        times = list(dict.fromkeys(re.findall(r"\bT-\d\d[a-z]?\b", plain(c["Baseline"] + " " + c["Verdict"]))))
        out.append({"name": name, "budget": plain(c["Budget"]), "baseline": plain(c["Baseline"]), "verdict": sr["verdict"],
                    "latest": sr["says"], "change": plain(c["Required change"]), "times": times,
                    "tsr": expand_numbers(re.sub(r"TSR-", "", c["TSR"]), "TSR")})
      return out
  raise TimingError(f"WP-S-04 §5 has no table with columns {REACTION_HEAD}")


def timing_sysml() -> str:
  out = [HEADER, "package LionDriverTiming {",
         "    doc /* The FTTI budgets of WP-S-04 §3.7, one constraint per row, named by the row label. The cells are kept as",
         "           written; a cell that is one time is also given in seconds, which check H2 adds up. Then the",
         "           code-derived times T-nn of §4 and the fault reaction times of §5, which check H6 holds together. */", "",
         "    private import ScalarValues::*;", "",
         "    constraint def TimingBudget {",
         "        doc /* Fault tolerant time interval of a safety goal and fault class, split into detection (FDTI) and reaction",
         "               (FRTI) budgets with the margin left; FHTI = FDTI + FRTI (ISO 26262-1 3.61-3.63). */"]
  for a in ("ftti", "fdti", "frti", "margin", "fhti"):
    out += [f"        attribute {a} : String;", f"        attribute {a}Seconds : Real[0..1];"]
  out += ["        attribute goals : String[1..*];", "        attribute tsr : String[0..*];", "    }", ""]
  for i, b in enumerate(budgets(), 1):
    out += [f"    constraint <'{b['label']}'> budget_{i:02d} : TimingBudget {{", f"        doc /* {doc(b['label'])} */"]
    for a in ("ftti", "fdti", "frti", "margin", "fhti"):
      out.append(f"        :>> {a} = {s(b[a])};")
      v = seconds(b[a])
      if v is not None:
        out.append(f"        :>> {a}Seconds = {num(v)};")
    out += [f"        :>> goals = {str_list(b['goals'])};", f"        :>> tsr = {str_list(b['tsr'])};", "    }"]
  out += ["", "    item def CodeDerivedTime {",
          "        doc /* A detection or reaction time derived from the code (WP-S-04 §4): the mechanism, where it is, how the",
          "               time follows from the code, and the worst case. Nothing here is measured. */",
          "        attribute mechanism : String;", "        attribute code : String;", "        attribute derivation : String;",
          "        attribute worstCase : String;", "    }", ""]
  for t in code_times():
    out += [f"    item <'{t['id']}'> {t['id'].lower().replace('-', '_')} : CodeDerivedTime {{", f"        doc /* {doc(t['mechanism'])} */",
            f"        :>> mechanism = {s(t['mechanism'])};", f"        :>> code = {s(t['code'])};",
            f"        :>> derivation = {s(t['derivation'])};", f"        :>> worstCase = {s(t['worst'])};", "    }"]
  out += ["", "    constraint def FaultReactionTime {",
          "        doc /* The time from a fault to the item's reaction shall not exceed its budget (WP-S-04 §5): time <= budget.",
          "               The time is bound to the code-derived times it cites; verdict is met, design (met by design in the",
          "               reference build), partly, not or verify (no derived time yet). */",
          "        attribute budget : String;", "        attribute budgetSeconds : Real[0..1];", "        attribute baseline : String;",
          "        attribute latest : String;", "        attribute verdict : String;", "        attribute change : String;",
          "        attribute times : String[0..*];", "        attribute tsr : String[0..*];", "    }", ""]
  for i, r in enumerate(reactions(), 1):
    out += [f"    constraint <'{r['name']}'> reaction_{i:02d} : FaultReactionTime {{", f"        doc /* {doc(r['name'])} */",
            f"        :>> budget = {s(r['budget'])};"]
    v = seconds(r["budget"])
    if v is not None:
      out.append(f"        :>> budgetSeconds = {num(v)};")
    out += [f"        :>> baseline = {s(r['baseline'])};", f"        :>> latest = {s(r['latest'])};",
            f"        :>> verdict = {s(r['verdict'])};", f"        :>> change = {s(r['change'])};",
            f"        :>> times = {str_list(r['times'])};", f"        :>> tsr = {str_list(r['tsr'])};", "    }"]
  out.append("}")
  return "\n".join(out) + "\n"


def expand_numbers(cell: str, prefix: str) -> list[str]:
  """'105, 108…109' -> ['TSR-105', 'TSR-108', 'TSR-109'] for prefix 'TSR'; ranges written a…b or a–b."""
  out = []
  text = re.sub(r"\([^)]*\)", "", plain(cell))
  for lo, hi in re.findall(r"(?<![\w-])(\d{3}[a-z]?)(?:\s*[…–]\s*(\d{3}))?(?![\w])", text):
    if hi:
      out += [f"{prefix}-{n}" for n in range(int(lo[:3]), int(hi) + 1)]
    else:
      out.append(f"{prefix}-{lo}")
  return list(dict.fromkeys(out))


def tests_of(cell: str) -> list[str]:
  out = []
  for kind, lo, hi in re.findall(r"VS-([A-Z]+)-(\d{2})(?:\s*[…–]\s*(\d{2}))?", plain(cell)):
    out += [f"VS-{kind}-{n:02d}" for n in range(int(lo), int(hi or lo) + 1)]
  return list(dict.fromkeys(out))


def owners_of(cell: str) -> list[str]:
  """Element identifiers the Owner column names: E-nn[a-z] and host processes written host `x` (or `x`/`y`)."""
  text = cell
  out = re.findall(r"\bE-\d\d[a-z]?\b", text)
  for m in re.finditer(r"\bhost ((?:`[^`]+`\s*(?:/|,|and)?\s*)+)", text):
    out += [f"host.{x}" for x in re.findall(r"`([^`]+)`", m.group(1))]
  return list(dict.fromkeys(out))


def signals() -> list[dict]:
  out = []
  for heading, head, rows in tables(WP_S05):
    m = re.match(r"(11\.\d) (.*?) \((HSI-\d\d)(?:…(\d\d))?\)$", heading)
    if not m or head != SIGNAL_HEAD:
      continue
    lo, hi = int(m.group(3)[4:]), int(m.group(4) or m.group(3)[4:])
    hsi = [f"HSI-{n:02d}" for n in range(lo, hi + 1)]
    for r in rows:
      c = dict(zip(SIGNAL_HEAD, r))
      if not re.fullmatch(r"S-\d\d", c["ID"]):
        continue
      out.append({"id": c["ID"], "name": plain(c["Signal"]), "group": m.group(2), "hsi": hsi, "dir": c["Dir"],
                  "owner": c["Owner (HW / SW)"], "owners": owners_of(c["Owner (HW / SW)"]), "type": c["Type / bits"],
                  "range": c["Range, scale, units"], "integrity": c["Integrity"], "validity": c["Validity / liveness"],
                  "rate": c["Rate / max age"], "reaction": c["Failure reaction"], "tsrText": c["TSR"],
                  "tsr": expand_numbers(c["TSR"], "TSR"), "asil": c["ASIL"], "tests": tests_of(c["Tests"])})
  if not out:
    raise TimingError(f"WP-S-05 §11 has no signal table with columns {SIGNAL_HEAD}")
  return out


def responsibilities() -> list[dict]:
  rows = None
  for heading, head, rs in tables(WP_S05):
    if heading.startswith("11.4 ") and head == RESP_HEAD:
      rows = rs
  if not rows:
    raise TimingError(f"WP-S-05 §11.4 has no table with columns {RESP_HEAD}")
  out = []
  for r in rows:
    c = dict(zip(RESP_HEAD, r))
    if not re.fullmatch(r"HSI-\d\d", c["HSI"]):
      raise TimingError(f"WP-S-05 §11.4: {c['HSI']!r} is not an interface ID HSI-nn")
    status = plain(c["Status"])
    if status not in STATUS:
      raise TimingError(f"WP-S-05 §11.4 {c['HSI']}: status {status!r} is not one of {', '.join(STATUS)}")
    refs = re.findall(r"TSR-(\d{3}(?:\s*(?:…|,)\s*\d{3})*)", plain(" ".join(r)))
    tsr = expand_numbers(", ".join(refs), "TSR")
    out.append({"id": c["HSI"], "hw": c["Hardware provides"], "sw": c["Software must"], "detect": c["Failure detected by"],
                "reaction": c["Reaction"], "shared": c["Shared with"], "hwOwnerText": c["HW owner"],
                "swOwnerText": c["SW owner"], "hwOwners": owners_of(c["HW owner"]), "swOwners": owners_of(c["SW owner"]),
                "tsr": tsr, "status": status})
  return out


# The parts of the safety MCU hardware (E-04a in LionDriverArchitecture) that a resource of WP-S-05 §2 names, by the
# words of its interface name and HW resource cells, in the order the HW resource cell names them.
RESOURCE_PARTS = [(r"\bSPI4\b", "spi4"), (r"\b(SRAM|[Ff]lash|RAMECC)", "memories"), (r"\bFDCAN", "fdcanPeripherals"),
                  (r"\bGPIO", "gpio"), (r"\bADC", "adc"), (r"\bIWDG", "iwdg1"), (r"\b(NVIC|MPU|DTS|Cortex)", "core"),
                  (r"\b(RCC|CSS)\b", "clock"), (r"\b(DAC|codec)\b", "sirenPath"), (r"\b[Ss]upply\b", "supply")]


def summary() -> dict[str, dict]:
  """HSI-nn -> its row of the WP-S-05 §2 summary table: interface name, HW resource and the parts of E-04a it uses."""
  for heading, head, rows in tables(WP_S05):
    if heading.startswith("2. ") and head[:3] == ["HSI", "Interface", "HW resource"]:
      out = {}
      for r in rows:
        if not re.fullmatch(r"HSI-\d\d", r[0]):
          continue
        res = plain(r[2])
        pos = {}
        for rx, p in RESOURCE_PARTS:
          m_ = re.search(rx, res)
          if m_:
            pos[p] = m_.start()
          elif re.search(rx, plain(r[1])):
            pos[p] = len(res) + 1
        parts = sorted(pos, key=pos.get)  # the first is the resource the cell names first
        if res not in ("—", "-", "") and not parts:
          raise TimingError(f"WP-S-05 §2 {r[0]}: HW resource {res!r} names no part of the safety MCU; extend RESOURCE_PARTS")
        out[r[0]] = {"name": plain(r[1]), "resource": res, "parts": parts}
      return out
  raise TimingError("WP-S-05 §2 has no interface summary table with columns HSI, Interface, HW resource")


def interfaces() -> dict[str, str]:
  """HSI-nn -> interface name from the WP-S-05 §2 summary table."""
  return {k: v["name"] for k, v in summary().items()}


def signals_sysml() -> str:
  attrs = [("group", "group"), ("hsi", "hsi"), ("direction", "dir"), ("ownerText", "owner"), ("owners", "owners"),
           ("dataType", "type"), ("valueRange", "range"), ("integrity", "integrity"), ("validity", "validity"),
           ("rate", "rate"), ("reaction", "reaction"), ("tsrText", "tsrText"), ("tsr", "tsr"), ("asil", "asil"),
           ("tests", "tests")]
  lists = {"hsi", "owners", "tsr", "tests"}
  out = [HEADER, "package LionDriverSignals {",
         "    doc /* The safety-relevant signals of WP-S-05 §11 that cross the hardware-software interfaces and the item",
         "           boundary, one item each, with the elements that own them, the TSRs they serve and the cases that test",
         "           them. */", "",
         "    private import ScalarValues::*;", "",
         "    item def Signal {", "        doc /* A signal across an HSI or the item boundary (WP-S-05 §11). */"]
  for a, _ in attrs:
    out.append(f"        attribute {a} : String{'[0..*]' if a in lists else ''};")
  out += ["    }", ""]
  for sg in signals():
    out += [f"    item <'{sg['id']}'> {sg['id'].lower().replace('-', '_')} : Signal {{", f"        doc /* {doc(sg['name'])} */"]
    for a, k in attrs:
      out.append(f"        :>> {a} = {str_list(sg[k]) if a in lists else s(sg[k])};")
    out.append("    }")
  rattrs = [("hardware", "hw"), ("software", "sw"), ("detection", "detect"), ("reaction", "reaction"),
            ("shared", "shared"), ("hwOwnerText", "hwOwnerText"), ("swOwnerText", "swOwnerText"),
            ("hwOwners", "hwOwners"), ("swOwners", "swOwners"), ("tsr", "tsr"), ("status", "status")]
  rattrs += [("hwResource", "resource"), ("hwParts", "parts")]
  rlists = {"hwOwners", "swOwners", "tsr", "hwParts"}
  names = interfaces()
  rows = summary()
  out += ["", "    item def HsiResponsibility {",
          "        doc /* What the hardware and the software each provide and must do at one interface HSI-nn, who detects",
          "               a failure of the other side and how the item reacts (WP-S-05 §11.4). */"]
  for a, _ in rattrs:
    out.append(f"        attribute {a} : String{'[0..*]' if a in rlists else ''};")
  out += ["    }", ""]
  for r in responsibilities():
    r = {**r, "resource": rows.get(r["id"], {}).get("resource", ""), "parts": rows.get(r["id"], {}).get("parts", [])}
    out += [f"    item <'{r['id']}'> {r['id'].lower().replace('-', '_')} : HsiResponsibility {{",
            f"        doc /* {doc(names.get(r['id'], r['id']))} */"]
    for a, k in rattrs:
      out.append(f"        :>> {a} = {str_list(r[k]) if a in rlists else s(r[k])};")
    out.append("    }")
  out.append("}")
  return "\n".join(out) + "\n"


def build() -> dict[str, str]:
  return {"timing": timing_sysml(), "signals": signals_sysml()}


def main(argv: list[str]) -> int:
  try:
    texts = build()
  except TimingError as e:
    print(f"gen_timing_hsi: {e}")
    return 1
  if "--check" in argv:
    stale = [OUT[k].name for k, t in texts.items() if not OUT[k].exists() or OUT[k].read_text(encoding="utf-8") != t]
    if stale:
      print("FAIL out of date (run tools/gen_timing_hsi.py):", ", ".join(stale))
      return 1
    print("gen_timing_hsi: Timing and Signals match WP-S-04 and WP-S-05")
    return 0
  for k, t in texts.items():
    OUT[k].write_text(t, encoding="utf-8")
  print("gen_timing_hsi: wrote " + ", ".join(OUT[k].name for k in texts))
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
