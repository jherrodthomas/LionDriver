#!/usr/bin/env python3
"""Generate the requirement, satisfy and verify parts of the SysML model from the work products.

The work products stay the documents of record (README §2, SY-04). This tool copies them into the model so
that the model can relate requirements to the architecture and to the verification cases:

  model/Requirements.sysml   safety goals, FSRs and TSRs (assurance/trace/items), system requirements
                             (WP-S-01 §2–§9) and cybersecurity requirements (WP-S-07 §4) as `requirement`
                             usages, and the parent links of the trace data as `#derivation` connections
  model/Satisfaction.sysml   `satisfy` relationships from each requirement's allocation: `allocated_to` of
                             the trace data, WP-S-01 §10.1, the Alloc column of WP-S-07 §4
  model/Needs.sysml          stakeholders and actors (WP-S-01 §1.2) as part definitions, stakeholder needs (§1.3)
                             as `requirement` usages with their stakeholders, `#derivation` connections from each need
                             to the SYS requirements and safety goals that refine it, and the use cases (§1.4) as
                             `use case` usages with their actors, an objective that requires their needs, and a
                             `perform` of each function they use
  model/Verification.sysml   every test case of a specification table (first header cell "ID", row ID VS-…)
                             as a `verification` usage that verifies the modelled requirements it names

Usage: python3 tools/gen_requirements.py [--check]
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_DIR = HERE.parent / "model"
ASSURANCE = HERE.parents[2]
REPO = ASSURANCE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ASSURANCE / "trace" / "tools"))
import check_model  # noqa: E402
import sysml_lite  # noqa: E402
import trace_map as tm  # noqa: E402

WP_S01 = ASSURANCE / "03-system" / "WP-S-01-system-requirements.md"
WP_S07 = ASSURANCE / "03-system" / "WP-S-07-cybersecurity-requirements-architecture.md"
ARCH_FILES = ["LionDriverLibrary.sysml", "Mechanisms.sysml", "Functions.sysml", "Architecture.sysml"]
OUT = {"req": MODEL_DIR / "Requirements.sysml", "sat": MODEL_DIR / "Satisfaction.sysml", "ver": MODEL_DIR / "Verification.sysml",
       "needs": MODEL_DIR / "Needs.sysml"}
TRACE_KINDS = {"safety-goal": "SafetyGoal", "fsr": "FunctionalSafetyRequirement", "tsr": "TechnicalSafetyRequirement"}
MODELLED = ("SG", "FSR", "TSR", "SYS", "CSR")
# WP-S-07 §4 Alloc column: FW and SoC are elements; ENV (release environment) and USR (owner, service) are not
CSR_ALLOC = {"FW": "E-03", "SoC": "SoC"}
NON_ELEMENT = {"EXT", "OPS", "ENV", "USR"}
ITEM_PATH = "context.ldsda"
HEADER = "// GENERATED by assurance/models/sysml/tools/gen_requirements.py from the work products. Do not edit;\n" \
         "// change the work product and regenerate (README §7).\n"


# ---------------------------------------------------------------- helpers

def usage_name(ident: str) -> str:
  return re.sub(r"[^a-z0-9]+", "_", ident.lower()).strip("_")


def plain(md: str) -> str:
  md = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", md)
  md = md.replace("`", "").replace("**", "").replace("\\|", "|")
  return " ".join(md.split())


def doc(text: str) -> str:
  return plain(text).replace("*/", "* /")


def s(v) -> str:
  return '"' + plain(str(v)).replace("\\", "\\\\").replace('"', '\\"') + '"'


def sort_key(ident: str):
  return [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", ident)]


def tables(path: Path) -> list[tuple[str, list[str], list[list[str]]]]:
  """(heading, header cells, rows) for every table in a Markdown file."""
  out, heading, header, rows = [], "", None, []
  lines = path.read_text(encoding="utf-8").splitlines()
  for i, ln in enumerate(lines):
    if ln.startswith("#"):
      heading = ln.lstrip("# ").strip()
    if ln.startswith("|"):
      if header is None:
        if i + 1 < len(lines) and tm.SEP_RE.match(lines[i + 1]):
          header, rows = tm.split_row(ln), []
        continue
      if tm.SEP_RE.match(ln):
        continue
      rows.append(tm.split_row(ln))
    elif header is not None:
      out.append((heading, header, rows))
      header = None
  if header is not None:
    out.append((heading, header, rows))
  return out


# ---------------------------------------------------------------- sources

def system_requirements() -> list[dict]:
  out = []
  for heading, head, rows in tables(WP_S01):
    m = re.match(r"\d+\. (F-\d\d(?: / F-\d\d)?)", heading)
    if not m or head[:2] != ["ID", "Requirement"]:
      continue
    col = {h: i for i, h in enumerate(head)}
    for r in rows:
      if re.fullmatch(r"SYS-\d{3}", r[0]):
        out.append({"id": r[0], "text": r[col["Requirement"]], "function": m.group(1).replace(" / ", ", "),
                    "reqType": r[col["Type"]], "target": r[col["Target / criterion"]], "verification": r[col["Verif"]],
                    "source": "WP-S-01"})
  alloc = {}
  for heading, head, rows in tables(WP_S01):
    if heading.startswith("10.1") and head == ["SYS", "Allocated to"]:
      alloc = {r[0]: r[1] for r in rows}
  for r in out:
    r["allocation"] = alloc.get(r["id"], "")
  return out


def cyber_requirements() -> list[dict]:
  out = []
  for heading, head, rows in tables(WP_S07):
    m = re.match(r"4\.\d+ (CSR-C-\d\d)", heading)
    if not m or head[:3] != ["ID", "Statement", "Alloc"]:
      continue
    col = {h: i for i, h in enumerate(head)}
    for r in rows:
      if re.fullmatch(r"CSR-\d{3}", r[0]):
        out.append({"id": r[0], "text": r[1], "group": m.group(1), "allocation": r[2],
                    "safetyRelation": r[col.get("Safety relation", 3)], "verification": r[col.get("Verif", 4)], "source": "WP-S-07"})
  return out


def trace_requirements() -> list[dict]:
  out = []
  for iid, it in tm.load_items().items():
    if it["kind"] in TRACE_KINDS and it.get("status") != "withdrawn":
      parents = it.get("parents") or []
      if isinstance(parents, str):
        parents = re.findall(r"[A-Z]+-[0-9.]+[a-z]?", parents)
      out.append({"id": iid, "def": TRACE_KINDS[it["kind"]], "text": it.get("text", ""), "asil": it.get("asil", ""),
                  "allocation": it.get("allocated_to", ""), "verification": it.get("verification", ""),
                  "mechanism": it.get("mechanism", ""), "timing": it.get("timing", "") or it.get("ftti_text", ""),
                  "safeState": it.get("safe_state", ""), "parents": parents, "source": it.get("source", "")})
  return out


def verification_cases(known: set[str]) -> list[dict]:
  """Every specification row VS-… with the IDs it names (ranges expanded as in the trace map)."""
  cases: dict[str, dict] = {}
  for path in sorted(ASSURANCE.rglob("*.md")):
    if "maps" in path.parts or "models" in path.parts:
      continue
    wp = re.match(r"(WP-[A-Z]-\d\d)", path.name)
    lines = path.read_text(encoding="utf-8").splitlines()
    header, section = None, ""
    for i, line in enumerate(lines):
      if line.startswith("#"):
        hm = re.match(r"#+\s+(\d+(?:\.\d+)*)", line)
        section = f"§{hm.group(1)}" if hm else section
      if line.startswith("|") and i + 1 < len(lines) and tm.SEP_RE.match(lines[i + 1]):
        header = tm.split_row(line)
        continue
      m = tm.TEST_ROW_RE.match(line)
      if not m or not header or header[0] != "ID":
        continue
      cells = tm.split_row(line)
      refs: set[str] = set()
      for h, cell in zip(header[1:], cells[1:], strict=False):
        refs |= tm.refs_in(cell, tm.header_kind(h), known)
      cid = m.group(1)
      c = cases.setdefault(cid, {"id": cid, "title": plain(cells[1]) if len(cells) > 1 else "",
                                 "spec": f"{wp.group(1) if wp else path.stem} {section}".strip(), "refs": set()})
      c["refs"] |= refs
      if "Step" in header:  # WP-S-08: the integration steps a case runs at
        c["steps"] = re.findall(r"I-\d", cells[header.index("Step")])
  return sorted(cases.values(), key=lambda c: sort_key(c["id"]))


def _ids(cell: str) -> list[str]:
  return [x.strip() for x in plain(cell).split(",") if x.strip()]


def camel(words: str, upper: bool) -> str:
  parts = re.findall(r"[A-Za-z0-9]+", words)
  out = "".join(w[:1].upper() + w[1:] for w in parts)
  return out if upper else out[:1].lower() + out[1:]


def stakeholder_needs() -> tuple[list[dict], list[dict], list[dict]]:
  """(stakeholders and actors of §1.2, needs of §1.3, use cases of §1.4) of WP-S-01."""
  found = {}
  for heading, head, rows in tables(WP_S01):
    for sec, want in (("1.2", ["Stakeholder", "Kind", "Who"]),
                      ("1.3", ["ID", "Stakeholder", "Need", "Refined by", "Source"]),
                      ("1.4", ["ID", "Use case", "Actors", "Goal and main flow", "Functions", "Needs"])):
      if heading.startswith(sec + " "):
        if head != want:
          raise SystemExit(f"WP-S-01 §{sec}: header {head}, expected {want}")
        found[sec] = rows
  missing = [s for s in ("1.2", "1.3", "1.4") if s not in found]
  if missing:
    raise SystemExit(f"WP-S-01 has no table in §{', §'.join(missing)}")
  people = [{"name": plain(r[0]), "kinds": _ids(r[1]), "who": r[2]} for r in found["1.2"]]
  needs = [{"id": r[0], "stakeholders": _ids(r[1]), "text": r[2], "refined": _ids(r[3]), "source": r[4]}
           for r in found["1.3"] if re.fullmatch(r"SN-\d\d", r[0])]
  cases = [{"id": r[0], "title": plain(r[1]), "actors": _ids(r[2]), "goal": r[3], "functions": _ids(r[4]),
            "needs": _ids(r[5])} for r in found["1.4"] if re.fullmatch(r"UC-\d\d", r[0])]
  return people, needs, cases


# ---------------------------------------------------------------- allocation

def resolve(m: sysml_lite.Model, req: dict, units: dict) -> tuple[list[str], list[str]]:
  """(element paths, tokens that name no element) for a requirement's allocation text."""
  text = str(req.get("allocation") or "")
  if req["id"].startswith("SG-"):
    return [ITEM_PATH], []  # a safety goal is a requirement on the item as a whole
  if req["id"].startswith("SYS-"):
    tokens = re.findall(r"`([^`]+)`", text)
  elif req["id"].startswith("CSR-"):
    tokens = [CSR_ALLOC.get(t.strip(), t.strip()) for t in text.split(";") if t.strip()]
  else:
    tokens, _, _ = check_model.resolve_allocation(m, text, units)
  paths, missing = [], []
  for t in tokens:
    if t in NON_ELEMENT:
      continue
    e = m.find(t)
    if e is None:
      named = [x for x in m.elements.values() if x.kind == "part" and x.name == t]
      e = named[0] if len(named) == 1 else None
    if e is None and t in units:
      e = m.elements.get(units[t][0]) if units[t] else None
    if e is None:
      missing.append(t)
    elif e.path not in paths:
      paths.append(e.path)
  return paths, missing


# ---------------------------------------------------------------- writers

DEFS = """    requirement def LionDriverRequirement {
        doc /* Common attributes: the work product the requirement is copied from, and its allocation text as written there. */
        attribute workProduct : String;
        attribute allocText : String;
    }
    requirement def SafetyGoal :> LionDriverRequirement {
        doc /* Safety goal of the HARA (WP-C-03 §6). */
        attribute asil : String;
        attribute safeState : String;
        attribute ftti : String;
    }
    requirement def FunctionalSafetyRequirement :> LionDriverRequirement {
        doc /* Functional safety requirement of the FSC (WP-C-04 §5). */
        attribute asil : String;
        attribute verifMethod : String;
    }
    requirement def TechnicalSafetyRequirement :> LionDriverRequirement {
        doc /* Technical safety requirement (WP-S-02, WP-S-06 for TSR-8xx). */
        attribute asil : String;
        attribute mechanism : String;
        attribute timing : String;
        attribute verifMethod : String;
    }
    requirement def SystemRequirement :> LionDriverRequirement {
        doc /* Functional and performance requirement of the intended functionality (WP-S-01 §2–§9). */
        attribute functionId : String;
        attribute reqType : String;
        attribute target : String;
        attribute verifMethod : String;
    }
    requirement def CybersecurityRequirement :> LionDriverRequirement {
        doc /* Detailed cybersecurity requirement (WP-S-07 §4). */
        attribute group : String;
        attribute safetyRelation : String;
        attribute verifMethod : String;
    }
"""
ATTRS = {"SafetyGoal": ["asil", "safeState", "timing:ftti"], "FunctionalSafetyRequirement": ["asil", "verification:verifMethod"],
         "TechnicalSafetyRequirement": ["asil", "mechanism", "timing", "verification:verifMethod"],
         "SystemRequirement": ["function:functionId", "reqType", "target", "verification:verifMethod"],
         "CybersecurityRequirement": ["group", "safetyRelation", "verification:verifMethod"]}


def build() -> dict[str, str]:
  m = sysml_lite.load([MODEL_DIR / f for f in ARCH_FILES])
  units: dict[str, list[str]] = defaultdict(list)
  for e in m.elements.values():
    u = e.meta.get("Unit")
    if u:
      units[u["id"]].append(e.path)
  reqs = trace_requirements()
  for r in system_requirements():
    reqs.append({**r, "def": "SystemRequirement"})
  for r in cyber_requirements():
    reqs.append({**r, "def": "CybersecurityRequirement"})
  reqs.sort(key=lambda r: (MODELLED.index(r["id"].split("-")[0]), sort_key(r["id"])))
  ids = {r["id"] for r in reqs}
  dup = sorted({r["id"] for r in reqs if sum(1 for x in reqs if x["id"] == r["id"]) > 1})
  if dup:
    raise SystemExit(f"requirement IDs defined twice: {', '.join(dup)}")

  # Requirements.sysml
  out = [HEADER, "package LionDriverRequirements {",
         "    doc /* Requirements copied from the work products; see tools/gen_requirements.py. */", "",
         "    private import ScalarValues::*;", "    private import RequirementDerivation::*;", "", DEFS]
  derivations = []
  for r in reqs:
    lines = [f"    requirement <'{r['id']}'> {usage_name(r['id'])} : {r['def']} {{", f"        doc /* {doc(r['text'])} */",
             f"        :>> workProduct = {s(r['source'])};", f"        :>> allocText = {s(r.get('allocation', ''))};"]
    for a in ATTRS[r["def"]]:
      key, _, attr = a.partition(":")
      attr = attr or key
      lines.append(f"        :>> {attr} = {s(r.get(key, ''))};")
    out += lines + ["    }"]
    for p in r.get("parents", []):
      if p in ids:
        derivations.append((p, r["id"]))
  out.append("")
  out.append("    // derivation: each requirement from its parents in the trace data")
  for orig, der in derivations:
    out += ["    #derivation connection {", f"        end #original ::> {usage_name(orig)};",
            f"        end #derive ::> {usage_name(der)};", "    }"]
  out.append("}")
  req_text = "\n".join(out) + "\n"

  # Satisfaction.sysml
  out = [HEADER, "package LionDriverSatisfaction {",
         "    doc /* Each requirement satisfied by the elements its allocation names. Allocations to EXT, OPS, ENV and USR,",
         "           and text that names no element, give no satisfy relationship; check R2 reports them. */", "",
         "    private import LionDriverRequirements::*;", "    private import LionDriverArchitecture::*;", ""]
  for r in reqs:
    paths, _ = resolve(m, r, units)
    for p in paths:
      out.append(f"    satisfy {usage_name(r['id'])} by {p};")
  out.append("}")
  sat_text = "\n".join(out) + "\n"

  # Verification.sysml
  known = set().union(*tm.build().ids.values())
  cases = verification_cases(known)
  out = [HEADER, "package LionDriverVerification {",
         "    doc /* Test cases of the specification tables. Each verifies the modelled requirements (SG, FSR, TSR, SYS, CSR) it names. */", "",
         "    private import ScalarValues::*;", "    private import LionDriverRequirements::*;", "",
         "    verification def VerificationCase {", "        attribute spec : String;", "        attribute level : String;",
         "        attribute names : String;", "        attribute steps : String[0..*];", "    }"]
  for c in cases:
    vrefs = sorted((x for x in c["refs"] if x in ids), key=lambda x: (MODELLED.index(x.split("-")[0]), sort_key(x)))
    other = sorted(x for x in c["refs"] if x not in ids)
    out += [f"    verification <'{c['id']}'> {usage_name(c['id'])} : VerificationCase {{", f"        doc /* {doc(c['title'])} */",
            f"        :>> spec = {s(c['spec'])};", f"        :>> level = {s(c['id'].rsplit('-', 1)[0])};",
            f"        :>> names = {s(', '.join(other))};"]
    if c.get("steps"):
      out.append(f"        :>> steps = ({', '.join(s(x) for x in c['steps'])});")
    if vrefs:
      out.append("        objective {")
      out += [f"            verify LionDriverRequirements::{usage_name(x)};" for x in vrefs]
      out.append("        }")
    out.append("    }")
  out.append("}")
  ver_text = "\n".join(out) + "\n"
  return {"req": req_text, "sat": sat_text, "ver": ver_text, "needs": needs_sysml(m, ids)}


def needs_sysml(m: sysml_lite.Model, ids: set[str]) -> str:
  people, needs, cases = stakeholder_needs()
  defs = {p["name"].lower(): camel(p["name"], True) for p in people}
  fn_names = {f.short: f.name for f in m.functions.values()}

  def person(name: str, where: str) -> str:
    if name.lower() not in defs:
      raise SystemExit(f"WP-S-01 {where} names {name!r}, which is not in §1.2")
    return defs[name.lower()]

  out = [HEADER, "package LionDriverNeeds {",
         "    doc /* Stakeholders, stakeholder needs and use cases of WP-S-01 §1.2–§1.4 (ASPICE SYS.1). Each need is refined",
         "           by the SYS requirements and safety goals named in its row, written as a derivation from the need; each",
         "           use case serves the needs its objective requires and performs the functions of WP-C-01 §2.1 it uses. */", "",
         "    private import ScalarValues::*;", "    private import RequirementDerivation::*;", "    private import LionDriverLibrary::*;",
         "    private import LionDriverArchitecture::*;", "    private import LionDriverFunctions::*;",
         "    private import LionDriverRequirements::*;", "", "    // stakeholders and actors (§1.2)"]
  for p in people:
    base = "Person" if "stakeholder" in p["kinds"] else "ExternalElement"
    out += [f"    part def {defs[p['name'].lower()]} :> {base} {{ doc /* {doc(p['who'])} */ }}"]
  out += ["", "    requirement def StakeholderNeed {",
          "        doc /* A need of one or more stakeholders (WP-S-01 §1.3), in their words rather than as a requirement. */",
          "        subject ldsda : LdSda;", "        attribute workProduct : String;", "        attribute source : String;", "    }", "",
          "    // stakeholder needs (§1.3)"]
  derivations = []
  for n in needs:
    out += [f"    requirement <'{n['id']}'> {usage_name(n['id'])} : StakeholderNeed {{", f"        doc /* {doc(n['text'])} */",
            "        subject :>> ldsda;"]
    out += [f"        stakeholder {camel(x, False)} : {person(x, n['id'])};" for x in n["stakeholders"]]
    out += ['        :>> workProduct = "WP-S-01";', f"        :>> source = {s(n['source'])};", "    }"]
    for r in n["refined"]:
      if r not in ids:
        raise SystemExit(f"WP-S-01 {n['id']} is refined by {r}, which is not a modelled requirement")
      derivations.append((n["id"], r))
  out += ["", "    // refinement of each need by system requirements and safety goals"]
  for orig, der in derivations:
    out += ["    #derivation connection {", f"        end #original ::> {usage_name(orig)};",
            f"        end #derive ::> {usage_name(der)};", "    }"]
  need_ids = {n["id"] for n in needs}
  out += ["", "    use case def ItemUseCase {", "        doc /* A use of LD-SDA, its subject, by its actors (WP-S-01 §1.4). */",
          "        subject ldsda : LdSda;", "    }", "", "    // use cases (§1.4)"]
  for c in cases:
    out += [f"    use case <'{c['id']}'> {usage_name(c['id'])} : ItemUseCase {{", f"        doc /* {doc(c['title'])} */",
            "        subject :>> ldsda;"]
    out += [f"        actor {camel(a, False)} : {person(a, c['id'])};" for a in c["actors"]]
    out += ["        objective {", f"            doc /* {doc(c['goal'])} */"]
    for n in c["needs"]:
      if n not in need_ids:
        raise SystemExit(f"WP-S-01 {c['id']} serves {n}, which is not a need of §1.3")
      out.append(f"            require {usage_name(n)};")
    out.append("        }")
    for f in c["functions"]:
      if f not in fn_names:
        raise SystemExit(f"WP-S-01 {c['id']} uses {f}, which is not a function of the model")
      out.append(f"        perform {fn_names[f]};")
    out.append("    }")
  out.append("}")
  return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
  texts = build()
  if "--check" in argv:
    stale = [OUT[k].name for k, t in texts.items() if not OUT[k].exists() or OUT[k].read_text(encoding="utf-8") != t]
    if stale:
      print("FAIL out of date (run tools/gen_requirements.py):", ", ".join(stale))
      return 1
    print("gen_requirements: Requirements, Satisfaction and Verification match the work products")
    return 0
  for k, t in texts.items():
    OUT[k].write_text(t, encoding="utf-8")
  print("gen_requirements: wrote " + ", ".join(OUT[k].name for k in texts))
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
