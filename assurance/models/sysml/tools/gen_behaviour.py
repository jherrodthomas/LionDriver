#!/usr/bin/env python3
"""Generate the behaviour records of the SysML model from the documents of record.

  model/StateRecords.sysml  the state-machine records of assurance/05-software/state-machines (WP-W-05 §5) as SysML v2
                            `state def`s: every state, the initial state, and every record transition with its event
                            (trigger), guard (condition), action (effect), build, SWSRs, gap and code reference as `@RecordTransition` metadata. A record
                            transition from `any` or from a list of states becomes one transition per source state; `to:
                            same` is a self-transition; `to: m` (the requested safety mode) goes to every state its guard
                            names, or to every state when the guard names none. The machine names the software units that
                            run it (`@StateRecord`), which check B2 holds to the elements of the architecture.
  model/Sequences.sysml     the start-up and engagement sequence of WP-S-03 §4.1 (Table 4-1 and its lifelines) as an
                            `occurrence def`: one lifeline part per lifeline with the element it stands for, one `message`
                            per step with its phase, condition, state after, status, records and code as `@SequenceStep`
                            metadata, and the steps in order as successions.

Usage: python3 tools/gen_behaviour.py [--check]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_DIR = HERE.parent / "model"
ASSURANCE = HERE.parents[2]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ASSURANCE / "trace" / "tools"))
import check_state_machines as csm  # noqa: E402
from gen_requirements import doc, plain, s, tables  # noqa: E402

WP_S03 = ASSURANCE / "03-system" / "WP-S-03-technical-safety-concept-architecture.md"
OUT = {"states": MODEL_DIR / "StateRecords.sysml", "sequences": MODEL_DIR / "Sequences.sysml"}
HEADER = "// GENERATED by assurance/models/sysml/tools/gen_behaviour.py from the documents of record. Do not edit;\n" \
         "// change the record and regenerate (README §7).\n"
STEP_HEAD = ["Step", "Phase", "From", "To", "Message or action", "Condition", "State after", "Status", "Records", "Code"]
STATUSES = ("as inherited", "required, in the reference build", "required, not implemented")


class BehaviourError(ValueError):
  pass


def ident(text: str) -> str:
  out = re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_")
  return out if out[:1].isalpha() else "s_" + out


def str_list(v) -> str:
  items = [str(x) for x in (v if isinstance(v, list) else [v] if v not in (None, "") else [])]
  return "(" + ", ".join(s(x) for x in items) + ")" if items else '""'


def states_named(text: str, states: list[str]) -> list[str]:
  return [st for st in states if re.search(rf"(?<![A-Za-z0-9_]){re.escape(st)}(?![A-Za-z0-9_])", text)]


def expand(rec: dict, t: dict) -> list[tuple[str, str]]:
  """(source, target) pairs of a record transition."""
  states = rec["states"]
  src = str(t["from"])
  sources = states if src == "any" else [x.strip() for x in src.split(",")]
  for x in sources:
    if x not in states:
      raise BehaviourError(f"{rec['machine']} {t['id']}: source {x!r} is not a state")
  dst = str(t["to"])
  pairs = []
  for a in sources:
    if dst == "same":
      targets = [a]
    elif dst == "m":
      targets = states_named(str(t.get("guard", "")), states) or states
    elif dst in states:
      targets = [dst]
    else:
      raise BehaviourError(f"{rec['machine']} {t['id']}: target {dst!r} is not a state")
    pairs += [(a, b) for b in targets]
  return pairs


def state_records() -> str:
  recs = [csm.load(p) for p in sorted(csm.SM_DIR.glob("*.yaml"))]
  out = [HEADER, "package LionDriverStateRecords {",
         "    doc /* The state-machine records of WP-W-05 §5 (assurance/05-software/state-machines), one state def each.",
         "           The records stay the source; check B1 holds this file to them. */", "",
         "    private import ScalarValues::*;", "",
         "    metadata def StateRecord {", "        attribute file : String;", "        attribute units : String[1..*];", "    }",
         "    metadata def RecordTransition {", "        attribute id : String;", "        attribute trigger : String;",
         "        attribute condition : String;", "        attribute effect : String;", "        attribute build : String;",
         "        attribute swsr : String[0..*];", "        attribute gap : String;", "        attribute code : String;", "    }"]
  for rec in recs:
    path = next(p for p in sorted(csm.SM_DIR.glob("*.yaml")) if csm.load(p)["machine"] == rec["machine"])
    out += ["", f"    state def <'{rec['machine']}'> {ident(rec['title']).title().replace('_', '')} {{",
            f"        doc /* {doc(rec['title'])} */",
            f"        @StateRecord {{ file = {s(path.relative_to(ASSURANCE).as_posix())}; units = {str_list(rec['units'])}; }}",
            f"        entry; then {rec['initial']};"]
    out += [f"        state {st};" for st in rec["states"]]
    for t in rec["transitions"]:
      pairs = expand(rec, t)
      for a, b in pairs:
        name = t["id"].lower() + ("" if len(pairs) == 1 else f"_{a.lower()}_{b.lower()}")
        out += [f"        transition {ident(name)} first {a} then {b} {{",
                f"            doc /* {doc(t['id'] + ': ' + str(t.get('event', '')))} */",
                f"            @RecordTransition {{ id = {s(t['id'])}; trigger = {s(t.get('event', ''))}; condition = {s(t.get('guard', ''))}; "
                f"effect = {s(t.get('action', ''))}; build = {s(t.get('build', ''))}; swsr = {str_list(t.get('swsr') or [])}; "
                f"gap = {s(t.get('gap', ''))}; code = {s(t.get('code', ''))}; }}", "        }"]
    out.append("    }")
  out.append("}")
  return "\n".join(out) + "\n"


def startup_tables() -> tuple[list[list[str]], list[list[str]]]:
  lifelines = steps = None
  for heading, head, rows in tables(WP_S03):
    if not heading.startswith("4.1 "):
      continue
    if head == ["Lifeline", "Element"]:
      lifelines = rows
    elif head == STEP_HEAD:
      steps = rows
  if lifelines is None or steps is None:
    raise BehaviourError(f"WP-S-03 §4.1 needs a lifeline table and Table 4-1 with columns {STEP_HEAD}")
  return lifelines, steps


def sequences() -> str:
  lifelines, steps = startup_tables()
  names = {plain(r[0]): ident(plain(r[0])).lower() for r in lifelines}
  out = [HEADER, "package LionDriverSequences {",
         "    doc /* Sequences of WP-S-03 §4: the start-up and engagement sequence of §4.1 (Table 4-1). Each lifeline stands",
         "           for an element of the architecture; each step is a message, the steps in order. */", "",
         "    private import ScalarValues::*;", "",
         "    part def Lifeline {", "        doc /* A participant in a sequence; element is the identifier of the model element it stands for. */",
         "        attribute element : String;", "    }",
         "    metadata def SequenceStep {", "        attribute phase : String;", "        attribute condition : String;",
         "        attribute stateAfter : String;", "        attribute status : String;", "        attribute records : String[0..*];",
         "        attribute code : String;", "    }", "",
         "    occurrence def <'SEQ-START'> StartupEngagement {",
         "        doc /* Start-up and engagement (WP-S-03 §4.1, Table 4-1) */"]
  for r in lifelines:
    out.append(f"        part {names[plain(r[0])]} : Lifeline {{ doc /* {doc(r[0])} */ :>> element = {s(re.sub(r'`', '', r[1]))}; }}")
  prev = None
  for r in steps:
    c = dict(zip(STEP_HEAD, r))
    sid = c["Step"]
    if not re.fullmatch(r"ST-\d\d", sid):
      raise BehaviourError(f"WP-S-03 Table 4-1: step ID {sid!r} is not ST-nn")
    for col in ("From", "To"):
      if plain(c[col]) not in names:
        raise BehaviourError(f"WP-S-03 Table 4-1 {sid}: {col} {c[col]!r} is not a lifeline")
    if plain(c["Status"]) not in STATUSES:
      raise BehaviourError(f"WP-S-03 Table 4-1 {sid}: status {c['Status']!r} is not one of {STATUSES}")
    records = [x.strip() for x in plain(c["Records"]).split(",") if x.strip()]
    name = ident(sid).lower()
    out += [f"        message <'{sid}'> {name} from {names[plain(c['From'])]} to {names[plain(c['To'])]} {{",
            f"            doc /* {doc(c['Message or action'])} */",
            f"            @SequenceStep {{ phase = {s(c['Phase'])}; condition = {s(c['Condition'])}; stateAfter = {s(c['State after'])}; "
            f"status = {s(c['Status'])}; records = {str_list(records)}; code = {s(c['Code'])}; }}", "        }"]
    if prev:
      out.append(f"        first {prev} then {name};")
    prev = name
  out += ["    }", "}"]
  return "\n".join(out) + "\n"


def build() -> dict[str, str]:
  return {"states": state_records(), "sequences": sequences()}


def main(argv: list[str]) -> int:
  try:
    texts = build()
  except BehaviourError as e:
    print(f"gen_behaviour: {e}")
    return 1
  if "--check" in argv:
    stale = [OUT[k].name for k, t in texts.items() if not OUT[k].exists() or OUT[k].read_text(encoding="utf-8") != t]
    if stale:
      print("FAIL out of date (run tools/gen_behaviour.py):", ", ".join(stale))
      return 1
    print("gen_behaviour: StateRecords and Sequences match the records")
    return 0
  for k, t in texts.items():
    OUT[k].write_text(t, encoding="utf-8")
  print("gen_behaviour: wrote " + ", ".join(OUT[k].name for k in texts))
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
