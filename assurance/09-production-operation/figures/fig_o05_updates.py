def box(x, y, w, lines_text: str, cls: str, chips=(), title: str = "", tag: str = "") -> tuple[list[str], float]:
  """A card: optional bold title (and a small right-hand tag), wrapped text, then status chips stacked. Returns its height."""
  inner, yy, out = w - 24, y + 24, []
  if title:
    out.append(T(x + 12, yy, title, "tb"))
    if tag:
      out.append(T(x + w - 12, yy, tag, "t2", "end"))
    yy += 21
  if lines_text:
    b, yy = para(x + 12, yy, lines_text, inner, "t")
    out += b
  yy -= 6
  for s, c in chips:
    cb, _ = chip(x + 12, yy, s, c)
    out += cb
    yy += 26
  h = yy - y + (10 if chips else 6)
  return [R(x, y, w, h, cls)] + out, h


# ---------------------------------------------------------------- sources

ROW = re.compile(r"^\| (CSR-12\d) \| (.+?) \| .*\| ([^|]+?) \|\s*$", re.M)
STATUS = (("Not implemented", "open"), ("Not met", "open"), ("Partial", "partial"), ("Mechanism exists", "unverified"),
          ("Implemented, not verified", "unverified"), ("Verified", "done"))


def csr_status(cell: str) -> tuple[str, str]:
  """(barrier key, the document's own words) for an evidence cell; the latest dated '**YYYY-MM-DD: …**' status wins."""
  dated = re.findall(r"\*\*\d{4}-\d\d-\d\d: ([^*]+)\*\*", cell)
  s = (dated[-1] if dated else cell).strip()
  for lead, key in STATUS:
    if s.startswith(lead):
      return key, lead
  raise FigureError(f"unknown evidence status {s[:40]!r}; map it in STATUS")


def load() -> dict:
  docs = {k: p.read_text(encoding="utf-8") for k, p in DOCS.items()}
  sec = re.search(r"^### 4\.12 .*?(?=^### )", docs["S07"], re.M | re.S)
  if not sec:
    raise FigureError("WP-S-07 §4.12 (CSR-C-12 software updates) not found")
  csr = {m[1]: dict(text=m[2], status=csr_status(m[3])) for m in ROW.finditer(sec.group(0))}
  if sorted(csr) != [f"CSR-12{i}" for i in range(1, 7)]:
    raise FigureError(f"WP-S-07 §4.12 lists {sorted(csr)}, the figures draw CSR-121…CSR-126")
  G = fg.load()
  states = [G.csr[r]["status"] for r in G.under("CSG-07")]
  return dict(docs=docs, csr=csr, csg07=G.csg["CSG-07"], csg07_barrier=fg.barrier(states))


