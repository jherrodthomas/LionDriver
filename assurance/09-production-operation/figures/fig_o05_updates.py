  b += rb
  b.append(sr.P(f"M{xs + ws},{fmt((g0 + g1) / 2)} L{xr - 2},{fmt((g0 + g1) / 2)}", "arrb", "ab"))
  # a failure while installing, starting or confirming
  f_top = mids[3][0]
  fb, fh = box(xr, f_top, wr, "Falls back to one of these", "badbox", (), "A step fails")
  b += fb
