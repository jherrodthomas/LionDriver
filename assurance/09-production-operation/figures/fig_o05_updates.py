def panel(D, x, y, w, p) -> tuple[list[str], float]:
  title, ref, entry, start, end, gate, req, effect = p
  key, words = D["csr"][req]["status"]
  through = key in ("open", "partial")
  out = [T(x + 12, y + 24, title, "tb"), T(x + 12, y + 44, ref, "t2")]
  nw, ny, nh = 100, y + 74, 40
  gap = (w - 24 - len(NODES) * nw) / (len(NODES) - 1)
  nx = {k: x + 12 + i * (nw + gap) for i, (k, _) in enumerate(NODES)}
  for (k0, _), (k1, _) in zip(NODES, NODES[1:]):
    out.append(el("line", None, x1=fmt(nx[k0] + nw), y1=fmt(ny + nh / 2), x2=fmt(nx[k1]), y2=fmt(ny + nh / 2), class_="link"))
  for k, label in NODES:
    cls = "entry" if k == entry else ("badbox" if through and k == end else "model")
    out += [R(nx[k], ny, nw, nh, cls, rx=6), T(nx[k] + nw / 2, ny + 25, label, "t2b", "middle")]
  out.append(T(nx[entry] + nw / 2, ny - 7, "entry", "t2", "middle"))
  # the barrier sits where its control does: at the device's door, or at the key when the key is the control
  bx = nx[gate] + nw + gap / 2 if gate == start != end else nx[gate] - gap / 2
  cy = ny + nh + 16
  if start != end:  # the threat runs from where it starts to the device and stops at a built barrier
    stop = nx[end] + nw / 2 if through else bx - 8
    x0 = nx[start] + nw / 2
    out.append(sr.P(f"M{fmt(x0)},{fmt(cy)} L{fmt(stop)},{fmt(cy)}", "path" if through else "pathok", "ab" if through else "ap"))
  else:  # the threat is in the device itself: a fault or interruption during the install
    out.append(sr.P(f"M{fmt(nx[end] + 18)},{fmt(cy)} L{fmt(nx[end] + nw - 18)},{fmt(cy)}", "path" if through else "pathok",
                    "ab" if through else "ap"))
  if key != "open":  # drawn as built: absent while open, dashed while partial or unverified, solid when verified
    out.append(R(bx - 4, ny - 4, 8, nh + 28, f"gate-{key}", rx=2))
  yy = cy + 30
  sb, cw = chip(x + 12, yy - 15, f"{req} · {words}", STATE_CHIP[key])
