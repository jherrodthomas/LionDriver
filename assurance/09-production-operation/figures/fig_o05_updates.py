# ---------------------------------------------------------------- build and check

FORBIDDEN = ("UpdaterTargetBranch", "DisableUpdates", "FETCH_HEAD", "agnos.json", ".py:", "git checkout")


def build(D=None) -> dict[str, str]:
  D = D or load()
  for r, want in DRAWN.items():
    if (now := D["csr"][r]["status"][0]) != want:
      raise FigureError(f"{r} is now '{now}', the figures were drawn for '{want}'; redraw them and update DRAWN")
  if D["csg07_barrier"] != "open":
    raise FigureError(f"CSG-07's barrier is now '{D['csg07_barrier']}'; Figure 6-1 'today' and 6-2 were drawn for no control")
  out = {"fig-o05-6-1-update-path.svg": fig_path(D), "fig-o05-6-3-update-states.svg": fig_states(D),
         "fig-o05-6-3-update-states-still.svg": fig_states(D, animate=False), "fig-o05-6-2-update-attacks.svg": fig_attacks(D)}
  for name, s in out.items():
    drawn = re.sub(r"<desc .*?</desc>|<title .*?</title>", "", s, flags=re.S)
    if bad := [f for f in FORBIDDEN if f in drawn]:
      raise FigureError(f"{name} draws {bad}: no branch, key, command, file or code line on the figure")
  return out


def problems(D) -> list[str]:
  text = {k: norm(v) for k, v in D["docs"].items()}
  return [f"{name}: source text no longer in {DOCS[d].name}: {s!r}" for name, srcs in SRC.items() for d, s in srcs
          if norm(s) not in text[d]]


def main(argv: list[str]) -> int:
  try:
    D = load()
    out = build(D)
  except (FigureError, fg.ParseError) as e:
    print(f"fig_o05_updates: {e}", file=sys.stderr)
    return 1
  errs = problems(D)
  if "--check" in argv:
    errs += [f"{n} is stale; run {GEN}" for n, s in out.items()
             if not (HERE / n).exists() or (HERE / n).read_text(encoding="utf-8") != s]
  else:
    for n, s in out.items():
      (HERE / n).write_text(s, encoding="utf-8")
  for e in errs:
    print(f"error: {e}", file=sys.stderr)
  if not errs:
    print(f"fig_o05_updates: {len(out)} figures {'current' if '--check' in argv else 'written'}, sources found")
  return 1 if errs else 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
