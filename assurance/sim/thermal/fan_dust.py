#!/usr/bin/env python3
"""Dust in the fan (physics plan round 3, study 15; WP-C-06 TC-21, WP-H-01 HWSR-509a).

The MCU study (`mcu_heat.py`) has the fan at 100 % or stalled. Between the two, dust slowly clogs the fan and its
fins. Here the fan face's conductance runs from as built to stalled (natural convection only), steady at the end of
a long drive, in the same box model. For each step: the cabin air at which the SoC reaches the host's 96 °C limit,
the MCU's junction at that moment, and the cabin air at which the MCU's junction would reach its own limit if the
host did not stop. Writes `../results/fan-dust.json` and `.md`.

    python3 fan_dust.py --figures
    python3 fan_dust.py --check

How fast a fan clogs is not modelled: the study gives the cost of each step, not when it comes. Estimated inputs
until T1; synthetic (DSR-12), design aid, no evidence credit (DQ-413).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from mcu_heat import crossing, fan_still_scale  # noqa: E402
from thermal_pilot import PARAMS, bands, build, compare, refs  # noqa: E402

OUT_JSON = HERE.parent / "results" / "fan-dust.json"
OUT_MD = HERE.parent / "results" / "fan-dust.md"
LEFT = (1.0, 0.8, 0.6, 0.4, 0.3, 0.2, 0.1, 0.05, 0.0)   # share of the fan's cooling left above natural convection
AIR = (30.0, 50.0)                                       # steady conduction is linear in the cabin air: two suffice


def run(p: dict) -> dict:
  mc = p["mcu"]
  limit = bands()["comma 3X"]["overheated_above"]
  rise_hi = mc["die_power"]["high"] * mc["theta_jb"]["high"]      # as mcu_heat.py: the band's two ends
  rise_lo = mc["die_power"]["low"] * mc["theta_jb"]["low"]
  tj = mc["tj_max"]["industrial"]
  still = fan_still_scale(p)
  out = {"about": "Synthetic (DSR-12), design aid, no evidence credit (DQ-413). Estimated inputs until T1.",
         "soc_limit": limit, "tj_max": tj, "still_scale": round(still, 4), "steps": []}
  for f in LEFT:
    m = build(p, {"fan_conductance": still + f * (1.0 - still)})
    soc, mcu = [], []
    for a in AIR:
      T = m.steady(refs(p, a))
      soc.append(float(m.region_max("soc")(T)))
      mcu.append(float(m.region_mean("mcu")(T)))
    a_soc = crossing(list(AIR), soc, limit)
    blk = float(np.polyval(np.polyfit(AIR, mcu, 1), a_soc))
    a_mcu = crossing(list(AIR), list(np.array(mcu) + rise_hi), tj)
    out["steps"].append({"cooling_left": f, "air_at_soc_limit": round(a_soc, 2), "mcu_block_then": round(blk, 2),
                         "tj_then": [round(blk + rise_lo, 2), round(blk + rise_hi, 2)],
                         "air_at_mcu_limit": round(a_mcu, 2), "soc_above_air": round(soc[0] - AIR[0], 2)})
  s = out["steps"]
  out["host_first_everywhere"] = all(x["air_at_soc_limit"] < x["air_at_mcu_limit"] for x in s)
  out["soc_limit_air_lost_k"] = round(s[0]["air_at_soc_limit"] - s[-1]["air_at_soc_limit"], 2)
  half = next(x for x in s if x["cooling_left"] == 0.4)
  out["half_of_loss_by"] = round(1 - next(x["cooling_left"] for x in s
                                          if s[0]["air_at_soc_limit"] - x["air_at_soc_limit"]
                                          >= out["soc_limit_air_lost_k"] / 2), 2)
  out["at_40_percent"] = half
  return out


def markdown(r: dict, p: dict) -> str:
  s = r["steps"]
  L = [
    "# Dust in the fan: the device and the MCU as the fan clogs",
    "",
    "> **Synthetic data (DSR-12). Design aid, no evidence credit (DQ-413).** Generated by "
    "[`thermal/fan_dust.py`](../thermal/fan_dust.py) from the device heat model's [`params.yaml`](../thermal/params.yaml); "
    "do not edit by hand. **The device's inputs are estimates** until T1.",
    "",
    "The fan face's cooling runs from as built (100 %) to stalled (0 %, natural convection only), steady at the end "
    "of a long drive, the windshield 15 K above the cabin air and the sun on the device, as the MCU study "
    f"([`mcu-heat.md`](mcu-heat.md)). The host stops when the SoC passes {r['soc_limit']:.0f} °C; the MCU's junction "
    f"limit is {r['tj_max']:.0f} °C (industrial part), its junction taken with the hottest package.",
    "",
    "| Fan cooling left | Cabin air when the SoC reaches its limit | MCU junction then | Cabin air at which the MCU "
    "would reach its limit |",
    "|---|---|---|---|",
  ]
  for x in s:
    L.append(f"| {100 * x['cooling_left']:.0f} % | {x['air_at_soc_limit']:.1f} °C | {x['tj_then'][0]:.0f}–"
             f"{x['tj_then'][1]:.0f} °C | {x['air_at_mcu_limit']:.1f} °C |")
  h = r["at_40_percent"]
  L += ["", "## What this shows (generated)", "",
        f"- **The device loses {r['soc_limit_air_lost_k']:.0f} K of cabin air** between a clean fan and a stalled one: "
        f"the SoC reaches its limit at {s[0]['air_at_soc_limit']:.0f} °C clean and {s[-1]['air_at_soc_limit']:.0f} °C "
        "stalled.",
        f"- **Most of the loss comes late.** Half of it is gone only once {100 * r['half_of_loss_by']:.0f} % of the "
        f"cooling is lost; with 40 % left the limit is reached at {h['air_at_soc_limit']:.0f} °C. A fan that still "
        "turns keeps most of its value, so a stalled-fan check (HWSR-509a) catches the case that matters most.",
        ("- **The host still stops first** at every step: the SoC reaches its limit at a lower cabin air than the MCU's "
         "junction would reach its own, so the MCU stays in range while the host runs its thermal policy."
         if r["host_first_everywhere"] else
         "- **At some steps the MCU would reach its limit before the host stops**: TSR-509 has to act on its own."),
        "- For WP-O-03 (maintenance): a dusty fan is worth a note in the user information; the device's fan speed "
        "and temperatures in its own logs show it before it stalls.",
        ""]
  return "\n".join(L)


def main(argv):
  ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  ap.add_argument("--check", action="store_true")
  ap.add_argument("--figures", action="store_true")
  a = ap.parse_args(argv[1:])
  p = yaml.safe_load(PARAMS.read_text(encoding="utf-8"))
  r = run(p)
  md = markdown(r, p)
  if a.check:
    errs = compare(r, json.loads(OUT_JSON.read_text(encoding="utf-8")))
    if not errs and OUT_MD.read_text(encoding="utf-8") != md:
      errs.append(f"{OUT_MD.name} is stale")
    for e in errs[:20]:
      print("FAIL", e)
    print("fan dust:", "OK" if not errs else f"{len(errs)} difference(s)")
    return 1 if errs else 0
  OUT_JSON.write_text(json.dumps(r, indent=1) + "\n", encoding="utf-8")
  OUT_MD.write_text(md, encoding="utf-8")
  print("wrote", OUT_JSON.name, OUT_MD.name, [(x["cooling_left"], x["air_at_soc_limit"], x["air_at_mcu_limit"]) for x in r["steps"]])
  if a.figures:
    import figures
    figures.fan_dust_figure(p, r, HERE / "figures")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv))
