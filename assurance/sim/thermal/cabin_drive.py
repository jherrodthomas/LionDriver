#!/usr/bin/env python3
"""The device heat model on the cabin's own temperatures: parked in the sun (device off), then driving (device on).

Takes the air at the mount and the windshield temperature, minute by minute, from the cabin heat soak
(`../results/cabin-soak.json`, written by `../weather/cabin_soak.py`) instead of the constant cabin temperature of
`thermal_pilot.py`. While parked the board is off and the fan stands still (natural convection on its face); while
driving the board runs and the fan is at 100 %. Writes `../results/cabin-device.json` and `.md`.

    python3 cabin_drive.py           # results (and with --figures the figure)
    python3 cabin_drive.py --check   # CI: fail if a fresh run differs from the committed results

Every input is an estimate until T1 and the logger (DQ-412). Synthetic (DSR-12), design aid, no evidence credit.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from thermal_pilot import PARAMS, bands, build, compare  # noqa: E402

CABIN = HERE.parent / "results" / "cabin-soak.json"
OUT_JSON = HERE.parent / "results" / "cabin-device.json"
OUT_MD = HERE.parent / "results" / "cabin-device.md"
NAMES = {"hot_july": "Hot July day, AC on", "hot_july_ac_off": "Hot July day, AC off (fan, fresh air)",
         "mild_april": "Mild April day, AC on"}


def run(p: dict) -> dict:
  cabin = json.loads(CABIN.read_text(encoding="utf-8"))
  limit = bands()["comma 3X"]["overheated_above"]
  dt = p["drive"]["step"]
  out = {"about": "Synthetic (DSR-12), design aid, no evidence credit. Estimated inputs; clear sky.",
         "limit_used": limit, "scenarios": {}}
  for name, d in cabin["scenarios"].items():
    tm = np.array(d["t_min"]) * 60.0
    t_drive = d["drive_starts_min"] * 60.0
    series = {"air": np.array(d["mount"]), "glass": np.array(d["glass"])}
    def refs_from(offset, tm=tm, series=series):
      return lambda dt_s: {k: float(np.interp(offset + dt_s, tm, v)) for k, v in series.items()}
    m = build(p)
    fan = next(f for f in m.box.faces if f.name == "fan")
    still = p["boundaries"]["rear"]["h"]
    phases = [
      {"duration": t_drive, "refs": refs_from(0.0), "q_scale": 0.0, "flux_scale": 1.0, "h": {fan.name: still}},
      {"duration": tm[-1] - t_drive, "refs": refs_from(t_drive), "q_scale": 1.0, "flux_scale": 1.0},
    ]
    t, y, _ = m.transient_phases(phases, dt, float(series["air"][0]), [m.region_max("soc"), m.region_mean("mcu")])
    drive = t >= t_drive
    soc = y[:, 0]
    over = drive & (soc > limit)
    first = float(t[over][0] / 60 - t_drive / 60) if over.any() else None
    out["scenarios"][name] = {
      "t_min": [round(v / 60, 1) for v in t], "soc": [round(float(v), 2) for v in soc],
      "mcu": [round(float(v), 2) for v in y[:, 1]], "mount": [round(float(np.interp(v, tm, series["air"])), 2) for v in t],
      "drive_starts_min": round(t_drive / 60, 1),
      "soc_at_drive_start": round(float(np.interp(t_drive, t, soc)), 1),
      "soc_peak_driving": round(float(soc[drive].max()), 1),
      "mcu_peak": round(float(y[:, 1].max()), 1),
      "overheat_minutes": round(float(over.sum() * dt / 60), 0),
      "first_overheat_min_into_drive": None if first is None else round(first, 1)}
  return out


def markdown(r: dict) -> str:
  lim = r["limit_used"]
  L = [
    "# The device on the cabin's own temperatures: parked in the sun, then driving",
    "",
    "> **Synthetic data (DSR-12). Design aid, no evidence credit (DQ-413).** Generated by "
    "[`thermal/cabin_drive.py`](../thermal/cabin_drive.py) from the cabin heat soak "
    "([`cabin-soak.md`](cabin-soak.md)) and the device heat model ([`thermal-pilot.md`](thermal-pilot.md)); do not "
    "edit by hand. **Every input is an estimate** until the device is measured (T1) and the logger reads the mount "
    "(DQ-412).",
    "",
    f"Parked 12:00–14:00 with the board off and the fan still, then driving 14:00–15:00 with the board on and the fan "
    f"at 100 %. The air at the mount and the windshield follow the cabin model minute by minute. Limit: SoC above "
    f"{lim:.0f} °C (comma 3X, `hardwared.py`).",
    "",
    "| Day | SoC when the drive starts | SoC peak while driving | Minutes above the limit | First overheat | panda MCU peak |",
    "|---|---|---|---|---|---|",
  ]
  for k, d in r["scenarios"].items():
    f = "—" if d["first_overheat_min_into_drive"] is None else f"{d['first_overheat_min_into_drive']:.0f} min into the drive"
    L.append(f"| {NAMES.get(k, k)} | {d['soc_at_drive_start']:.0f} °C | {d['soc_peak_driving']:.0f} °C | "
             f"{d['overheat_minutes']:.0f} | {f} | {d['mcu_peak']:.0f} °C |")
  hot, off = r["scenarios"]["hot_july"], r["scenarios"]["hot_july_ac_off"]
  def verdict(d):
    return ("overheats" if d["overheat_minutes"] > 0 else "stays below the limit")
  L += ["", "## What this shows (generated)", "",
        f"- On a hot July day with the AC on, the device {verdict(hot)}: the SoC peaks at "
        f"{hot['soc_peak_driving']:.0f} °C while driving.",
        f"- With the AC off, it {verdict(off)}"
        + ("" if off["overheat_minutes"] == 0 else
           f" for {off['overheat_minutes']:.0f} min, from {off['first_overheat_min_into_drive']:.0f} min into the drive")
        + f"; the SoC peaks at {off['soc_peak_driving']:.0f} °C.",
        "- The pilot holds the mount air at one temperature for the whole hour; here it starts hot from the parking "
        "and falls with the AC, or slowly without it. Both rest on estimates until T1 and the logger.", ""]
  return "\n".join(L)


def main(argv):
  ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  ap.add_argument("--check", action="store_true")
  ap.add_argument("--figures", action="store_true")
  a = ap.parse_args(argv[1:])
  p = yaml.safe_load(PARAMS.read_text(encoding="utf-8"))
  r = run(p)
  md = markdown(r)
  if a.check:
    errs = compare(r, json.loads(OUT_JSON.read_text(encoding="utf-8")))
    if not errs and OUT_MD.read_text(encoding="utf-8") != md:
      errs.append(f"{OUT_MD.name} is stale: run cabin_drive.py")
    for e in errs[:20]:
      print("FAIL", e)
    print("cabin drive:", "OK" if not errs else f"{len(errs)} difference(s)")
    return 1 if errs else 0
  OUT_JSON.write_text(json.dumps(r, separators=(",", ":")) + "\n", encoding="utf-8")
  OUT_MD.write_text(md, encoding="utf-8")
  print("wrote", OUT_JSON.name, OUT_MD.name,
        {k: (v["soc_at_drive_start"], v["soc_peak_driving"], v["overheat_minutes"]) for k, v in r["scenarios"].items()})
  if a.figures:
    import figures
    figures.cabin_figure(r, HERE / "figures" / "fig-th-5-cabin-drive.webp")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv))
