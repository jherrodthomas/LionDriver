#!/usr/bin/env python3
"""Engaged mismatch (WP-A-04 MCS-02.9): selfdrived stops while controlsd, card and pandad run on.

The SoC keeps sending its heartbeat, but once selfdriveState is stale pandad reports openpilot not engaged
(`pandad.cc`, `allAliveAndValid`), and controlsd drops latActive on the same stale input (TSR-602), so the LKA frames
keep arriving with no torque request. The panda's TX-arrival check (TSR-408) is satisfied by those frames; what
revokes authority is the 1 Hz engaged-mismatch check of `panda/board/main.c` (three ticks in a row), which sounds no
siren. openpilot's own warning comes from soundd once selfdriveState has been missing for SELFDRIVE_STATE_TIMEOUT.

The fmdtools SG-02 model took 3.0 s to the revocation and a siren 0.21 s after it, neither measured. This study runs
the case on three highway roads at the eight phases of the panda's 8 Hz tick against the stop, and writes
`../results/engaged-mismatch.md`.

    python3 engaged_mismatch.py            # run 24 cases, write the table
    python3 engaged_mismatch.py --check    # CI: fail if the committed table differs from a fresh run

Synthetic (DSR-12), no evidence credit: the host processes, driver, EPS and roads are the plant's stated assumptions.
"""

from __future__ import annotations

import dataclasses
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
sys.path.insert(0, str(HERE))

import cases  # noqa: E402
import simulate  # noqa: E402

OUT_MD = SIM / "results" / "engaged-mismatch.md"

ROADS = [  # (label, road, lateral push in m/s²)
  ("straight, 2 % crown (0.2 m/s² push, [straight-drift.md](straight-drift.md))", "straight", 0.2),
  ("curve inside the ODD (1.5 m/s²)", "curve", 0.0),
  ("curve at the ODD bound R_ODD (2.5 m/s²)", "curve-odd-bound", 0.0),
]
PHASES = [i * 0.125 for i in range(8)]   # s: the stop against the panda's 8 Hz tick, which also sets its 1 Hz tick
SPEED_KPH = 110.0
ALERT = "openpilot alert (selfdrive timeout)"


def t_stop(road: str, phase: float) -> float:
  """At curve entry, as in the silent-stall study and the HE-07.1 scene, or at 6 s on the straight, plus the phase."""
  if road == "straight":
    return 6.0 + phase
  return simulate.make_road(road, SPEED_KPH / 3.6).curve_start / (SPEED_KPH / 3.6) + phase


def runs() -> list[dict]:
  base = {c.id: c for c in cases.all_cases()}["F-04b"]
  out = []
  for label, road, push in ROADS:
    for phase in PHASES:
      case = dataclasses.replace(base, id="MCS-02.9", fault="selfdrived_stop", road=road, speed_kph=SPEED_KPH,
                                 t_fault=t_stop(road, phase), duration=8.0, ay_disturbance=push)
      r = simulate.simulate(case)
      m, ev = r.metrics, r.metrics["events"]
      first = lambda p: next((v for k, v in ev.items() if k.startswith(p)), None)  # noqa: E731
      out.append({"road": label, "road_key": road, "phase": phase, "torque_off": first("EPS LKA torque below"),
                  "revoke": first("authority revoked"), "siren": first("panda siren"), "alert": first(ALERT),
                  "cue": first("driver cue"), "cue_kind": next((k[len("driver cue ("):-1] for k in ev
                                                               if k.startswith("driver cue")), None),
                  "corr": first("driver correction"), "t_line": m["t_line"], "t_narrow": m["t_narrow"],
                  "max_dev": abs(m["max_dev"])})
  return out


def span(vals, unit=" s"):
  if all(v is None for v in vals):
    return "—"
  if any(v is None for v in vals):
    return "partly"
  lo, hi = f"{min(vals):.2f}", f"{max(vals):.2f}"
  return f"{lo}{unit}" if lo == hi else f"{lo}–{hi}{unit}"


def table(rs: list[dict]) -> str:
  lines = [
    "# Engaged mismatch: selfdrived stops, the heartbeat goes on",
    "",
    "> **Synthetic data (DSR-12).** Generated by [`plant/engaged_mismatch.py`](../plant/engaged_mismatch.py); do not "
    "edit by hand. The real panda safety code of the reference build runs in the loop, with the 1 Hz engaged-mismatch "
    "check of `panda/board/main.c`; openpilot on the SoC is modelled from its code (`host_stale_s`, and soundd's "
    f"SELFDRIVE_STATE_TIMEOUT of {simulate.SELFDRIVE_STATE_TIMEOUT:g} s). Driver, EPS and roads are the plant's "
    "stated assumptions ([plant-results.md](plant-results.md)). **No evidence credit** (DQ-139). Asked for by fmdtools "
    "SG-02 (WP-A-04 MCS-02.9), whose model took 3.0 s to the revocation and a siren 0.21 s after it.",
    "",
    f"selfdrived stops at {SPEED_KPH:.0f} km/h, at curve entry as in [silent-stall.md](silent-stall.md); controlsd, card and pandad run on. "
    f"Times are seconds from the stop; each row spans the {len(PHASES)} phases of the stop against the panda's 8 Hz "
    "tick (0–0.875 s), which also sets its 1 Hz tick. The driver reacts 1.5 s after the first cue: the siren, "
    "openpilot's alert, or a drift of 0.2 m.",
    "",
    "| Road | Authority revoked | Panda siren | openpilot alert | Driver cue | "
    "Correction starts | Body on the lane line, 3.0 / 3.7 m lane | Peak drift |",
    "|---|---|---|---|---|---|---|---|",
  ]
  for label, _, _ in ROADS:
    g = [r for r in rs if r["road"] == label]
    kinds = sorted({r["cue_kind"] for r in g if r["cue_kind"]})
    cue = f"{' / '.join(kinds)} at {span([r['cue'] for r in g])}" if kinds else "—"
    lines.append(f"| {label} | {span([r['revoke'] for r in g])} | "
                 f"{span([r['siren'] for r in g])} | {span([r['alert'] for r in g])} | {cue} | "
                 f"{span([r['corr'] for r in g])} | {span([r['t_narrow'] for r in g])} / "
                 f"{span([r['t_line'] for r in g])} | {span([r['max_dev'] for r in g], ' m')} |")
  rev = [r["revoke"] for r in rs]
  torque = [r["torque_off"] for r in rs if r["road_key"] == "straight"]
  lines += [
    "",
    "**What this shows** (generated from the rows above):",
    "",
    f"- The item stops steering at {simulate.ASSUMPTIONS['host_stale_s'][0]:g} s, when controlsd drops latActive on "
    f"the stale selfdriveState; on the straight, where it was holding against the crown, the EPS torque is below 5 % "
    f"at {span(torque)}. Its frames keep arriving with no torque request, so the TX-arrival check (TSR-408) does not revoke.",
    f"- The panda revokes authority at {span(rev)} after the stop, on the third 1 Hz tick that sees the heartbeat "
    "report not engaged. That revocation sounds no siren"
    + (" in any run" if all(r["siren"] is None for r in rs) else "") + ": TSR-516(b) lists the heartbeat \"not "
    "engaged\" trigger (TSR-307(a)) as not implemented.",
    f"- The first warning is openpilot's own alert at {span([r['alert'] for r in rs])}, from soundd on the SoC, "
    "which depends on the SoC that has just partly failed. "
    + ("On every road the drift reaches the driver first." if all(r["cue_kind"] == "drift" for r in rs) else
       "On some roads the alert is the first cue."),
    "- For the fmdtools model: the revocation time stands near its 3.0 s, but the 0.21 s siren after it does not "
    "exist in the reference build; the steering ends at about 0.1 s, long before the revocation.",
  ]
  return "\n".join(lines) + "\n"


def build() -> dict[Path, str]:
  return {OUT_MD: table(runs())}


def main(argv: list[str]) -> int:
  out = build()
  if "--check" in argv:
    stale = [p for p, c in out.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
    for p in stale:
      print(f"stale: {p.relative_to(SIM.parent)}", file=sys.stderr)
    if not stale:
      print(f"engaged_mismatch: {len(out)} file(s) current")
    return 1 if stale else 0
  for p, c in out.items():
    p.write_text(c, encoding="utf-8")
  print(f"wrote {len(out)} file(s)")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
