#!/usr/bin/env python3
"""Silent assist loss on a straight: how long the drift alone takes to reach the lane line.

The fmdtools SG-02 model (TE-02 step P2) assumes that on a straight the end of LKA torque gives the driver nothing to
feel, so a silent loss there (a 12 V supply loss of the item: no siren can sound) would be benign. On a straight the
plant drifts only when something pushes the car sideways, so this study adds a steady lateral push (`ay_disturbance`)
standing in for a road crown, bank or crosswind (TC-15, WP-V-03 KS-02: bank 2-6 %, about 0.2-0.6 m/s²), and runs the
loss with the panda siren muted (`whatif_silent_panda`), the driver cued only by the drift.

Two stand-ins for the silent loss: F-04b (commands stop, the EPS releases LKA torque 30 ms later) and F-07 (EPS fault,
assist lost). It writes `../results/straight-drift.md`.

    python3 straight_drift.py            # run 30 cases, write the table
    python3 straight_drift.py --check    # CI: fail if the committed table differs from a fresh run

Synthetic (DSR-12), no evidence credit: the push, driver, EPS and road are the plant's stated assumptions. L1: the
push is added as the driver's input is, with no tyre self-aligning torque and no hands on the wheel resisting it.
"""

from __future__ import annotations

import dataclasses
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
sys.path.insert(0, str(HERE))

import cases  # noqa: E402
import simulate  # noqa: E402

OUT_MD = SIM / "results" / "straight-drift.md"

FAULTS = [("F-04b", "commands stop, EPS releases"), ("F-07", "EPS fault, assist lost")]
PUSHES = [0.0, 0.1, 0.2, 0.4, 0.6]   # m/s²; g x cross slope: 0.2 is about a 2 % crown, 0.6 a 6 % bank
SPEEDS = [80.0, 95.0, 110.0]         # km/h, ODD-H up to 110 km/h (DQ-260)
T_FAULT, DURATION = 6.0, 8.0


def runs() -> list[dict]:
  by_id = {c.id: c for c in cases.all_cases()}
  out = []
  for fid, _ in FAULTS:
    for push in PUSHES:
      for kph in SPEEDS:
        case = dataclasses.replace(by_id[fid], road="straight", t_fault=T_FAULT, duration=DURATION, speed_kph=kph,
                                   ay_disturbance=push)
        r = simulate.simulate(case, {"whatif_silent_panda": 1.0})
        m, ev = r.metrics, r.metrics["events"]
        first = lambda p: next((v for k, v in ev.items() if k.startswith(p)), None)  # noqa: E731
        out.append({"fault": fid, "push": push, "kph": kph, "siren": first("panda siren"), "cue": first("driver cue"),
                    "corr": first("driver correction"), "t_line": m["t_line"], "t_narrow": m["t_narrow"],
                    "max_dev": abs(m["max_dev"]), "e0": abs(r.e0)})
  return out


def span(vals, unit=" s"):
  if any(v is None for v in vals):
    return "never" if all(v is None for v in vals) else "partly"
  lo, hi = f"{min(vals):.2f}", f"{max(vals):.2f}"
  return f"{lo}{unit}" if lo == hi else f"{lo}–{hi}{unit}"


def table(rs: list[dict]) -> str:
  lines = [
    "# Silent assist loss on a straight: time from the drift to the lane line",
    "",
    "> **Synthetic data (DSR-12).** Generated by [`plant/straight_drift.py`](../plant/straight_drift.py); do not edit "
    "by hand. The real panda safety code of the reference build runs in the loop with its siren muted (what-if "
    "`whatif_silent_panda`), because a 12 V supply loss of the item leaves nothing to sound it. Driver, EPS and road "
    "are the plant's stated assumptions ([plant-results.md](plant-results.md)). **No evidence credit** (DQ-139). "
    "Asked for by fmdtools SG-02 (TE-02 step P2, MCS-02.7).",
    "",
    "Straight road, 3.7 m and 3.0 m lanes, loss at t = 6 s, 8 s run. Times are seconds from the loss. The driver "
    "notices a drift of 0.2 m and corrects 1.5 s later (`driver_lat_cue_m`, `driver_t_r_s`). Each row spans "
    f"{', '.join(f'{v:.0f}' for v in SPEEDS)} km/h.",
    "",
    "**Assumption: the lateral push.** On a straight the plant drifts only when something pushes the car sideways. "
    "The push is a steady lateral acceleration standing in for a road crown, bank or crosswind (TC-15; WP-V-03 KS-02 "
    "names banks of 2–6 %): g × cross slope, so 0.2 m/s² is about a 2 % crown and 0.6 m/s² a 6 % bank. It builds up "
    "over 2–4 s, while the item still holds the lane, and stays on after the loss. Against the push the item holds "
    "the car off the lane centre (offset at the loss); the driver notices a drift of 0.2 m from that offset, while "
    "the lane line is reached from the offset, so with a strong push the line can come first.",
    "",
    "**Caveat: fidelity L1.** The push is added as the driver's input is: no tyre self-aligning torque and no hands "
    "on the wheel resist it, so the drift here is an upper bound on what a real car does with the same push. Real "
    "values come from the EPS and vehicle measurements (WP-S-04 M-02) and the driver study (WP-C-08).",
    "",
  ]
  for fid, desc in FAULTS:
    lines += [f"## {fid} ({desc})", "",
              "| Lateral push | Offset at the loss | Driver notices the drift | Correction starts | Body on the lane line, 3.0 m lane | "
              "Body on the lane line, 3.7 m lane | Peak drift after the loss |",
              "|---|---|---|---|---|---|---|"]
    for push in PUSHES:
      g = [r for r in rs if r["fault"] == fid and r["push"] == push]
      lines.append(f"| {push:.1f} m/s² | {span([r['e0'] for r in g], ' m')} | {span([r['cue'] for r in g])} | {span([r['corr'] for r in g])} | "
                   f"{span([r['t_narrow'] for r in g])} | {span([r['t_line'] for r in g])} | "
                   f"{span([r['max_dev'] for r in g], ' m')} |")
    lines.append("")

  def before_correction(r):
    return r["t_narrow"] is not None and r["corr"] is not None and r["t_narrow"] < r["corr"]

  pushed = [r for r in rs if r["push"] > 0]
  diff = max(abs((a["t_narrow"] or 0) - (b["t_narrow"] or 0)) for a in rs if a["fault"] == FAULTS[0][0]
             for b in rs if b["fault"] == FAULTS[1][0] and (b["push"], b["kph"]) == (a["push"], a["kph"]))
  calm = [r for r in rs if r["push"] == 0]
  crown = [r for r in rs if r["push"] == 0.2]
  lines += [
    "**What this shows** (generated from the rows above):",
    "",
    f"- With no push the car keeps its lane (peak drift {max(r['max_dev'] for r in calm):.2f} m): the model has "
    "nothing to drift it, which is an assumption about the road, not a property of the item.",
    f"- With any push from {min(r['push'] for r in pushed):.1f} m/s² the body reaches the 3.0 m lane line before the "
    f"driver's correction starts in {sum(map(before_correction, pushed))} of {len(pushed)} runs.",
    f"- At about a 2 % crown (0.2 m/s²) the 3.0 m lane line is reached at {span([r['t_narrow'] for r in crown])}, the "
    f"correction starts at {span([r['corr'] for r in crown])}.",
    f"- The two stand-ins agree to within {diff:.2f} s on the time to the 3.0 m lane line; speed barely matters, "
    "because a constant push drifts the car by time, not by distance.",
    "- So the straight case is benign only if nothing pushes the car sideways at all; the finding for MCS-02.7 "
    "stands (forwarded to the FTA owner).",
  ]
  return "\n".join(lines) + "\n"


def build() -> dict[Path, str]:
  return {OUT_MD: table(runs())}


def main(argv: list[str]) -> int:
  out = build()
  if "--check" in argv:
    stale = [p for p, c in out.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
    for p in stale:
      print(f"stale: {p.relative_to(SIM.parent)}", file=sys.stderr)
    if not stale:
      print(f"straight_drift: {len(out)} file(s) current")
    return 1 if stale else 0
  for p, c in out.items():
    p.write_text(c, encoding="utf-8")
  print(f"wrote {len(out)} file(s)")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
