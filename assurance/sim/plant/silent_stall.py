#!/usr/bin/env python3
"""Silent SoC stall: what the driver gets when the panda revokes steering without a siren, and what a siren would change.

In a full SoC stall (case F-04b) the reference build revokes authority about 0.04 s after the last command frame
(WP-S-04 T-34) and sounds no siren: the heartbeat check that would sound it does not fire once authority is revoked.
openpilot cannot alert either, because it is the part that stalled. The driver's only cue is the drift.

This study runs F-04b on three highway roads twice: as built, and with the what-if assumption `whatif_siren_on_revoke`
(the panda also sounds the siren at its next 8 Hz tick after revoking). It writes the comparison table
(`../results/silent-stall.md`), its figure (`../results/silent-stall.svg`), and the same figure in the decision
register's style (`assurance/01-management/decisions/figures/dq-404.svg`, question DQ-404).

    python3 silent_stall.py            # run 6 cases (about 5 s), write the table and figures
    python3 silent_stall.py --check    # CI: fail if the committed outputs differ from a fresh run

Synthetic (DSR-12), no evidence credit: the driver, EPS and road are the plant's stated assumptions.
"""

from __future__ import annotations

import dataclasses
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
sys.path.insert(0, str(HERE))

import cases  # noqa: E402
import simulate  # noqa: E402

OUT_MD = SIM / "results" / "silent-stall.md"
OUT_SVG = SIM / "results" / "silent-stall.svg"
OUT_DQ = SIM.parent / "01-management" / "decisions" / "figures" / "dq-404.svg"

ROADS = [  # (label, road, t_fault: None = at curve entry)
  ("straight", "straight", 6.0),
  ("curve inside the ODD (1.5 m/s²)", "curve", None),
  ("curve at the ODD bound R_ODD (2.5 m/s²)", "curve-odd-bound", None),
]
VARIANTS = [("as built", 0.0), ("what-if: siren on revocation", 1.0)]
FIGURE_ROAD = "curve-odd-bound"


def runs() -> list[dict]:
  base = {c.id: c for c in cases.all_cases()}["F-04b"]
  out = []
  for label, road, t_fault in ROADS:
    case = dataclasses.replace(base, road=road, t_fault=t_fault)
    for vlabel, flag in VARIANTS:
      r = simulate.simulate(case, {"whatif_siren_on_revoke": flag})
      m, ev = r.metrics, r.metrics["events"]
      first = lambda p: next((v for k, v in ev.items() if k.startswith(p)), None)  # noqa: E731
      cue_kind = next((k[len("driver cue ("):-1] for k in ev if k.startswith("driver cue")), None)
      out.append({"road": label, "road_key": road, "variant": vlabel, "flag": flag, "revoke": first("authority revoked"),
                   "siren": first("panda siren"), "cue": first("driver cue"), "cue_kind": cue_kind,
                   "corr": first("driver correction"), "t_line": m["t_line"], "t_narrow": m["t_narrow"],
                   "max_dev": abs(m["max_dev"]),
                   "trace": [(t - r.t0, e - r.e0) for t, e in zip(r.t, r.e_y)]})
  return out


def f(v, unit=" s"):
  return "—" if v is None else f"{v:.2f}{unit}"


def table(rs: list[dict]) -> str:
  lines = [
    "# Silent SoC stall: as built and with a siren on revocation",
    "",
    "> **Synthetic data (DSR-12).** Generated by [`plant/silent_stall.py`](../plant/silent_stall.py); do not edit by hand. "
    "The real panda safety code of the reference build runs in the loop; the what-if row adds a siren the reference "
    "build does not have. Driver, EPS and roads are the plant's stated assumptions ([plant-results.md](plant-results.md)). "
    "**No evidence credit** (DQ-139). The question it informs is DQ-404 in the "
    "[decision register](../../01-management/decisions/register.yaml).",
    "",
    "Case F-04b (SoC stall: heartbeat and commands stop) at 110 km/h, 3.7 m lane, EPS-release assumption. Times are "
    "seconds from the stall. In the curves the stall happens at curve entry, as in the HE-07.1 scene.",
    "",
    "| Road | Panda | Revoked | Siren | Driver cue | Correction starts | Body on the lane line, 3.0 / 3.7 m lane | Peak offset |",
    "|---|---|---|---|---|---|---|---|",
  ]
  for r in rs:
    cue = f"{r['cue_kind']} at {f(r['cue'])}" if r["cue"] is not None else "—"
    lines.append(f"| {r['road']} | {r['variant']} | {f(r['revoke'])} | {f(r['siren'])} | {cue} | {f(r['corr'])} | "
                 f"{f(r['t_narrow'])} / {f(r['t_line'])} | {r['max_dev']:.2f} m |")
  lines += ["", "**What changes with a siren on revocation** (generated from the rows above):", ""]

  def line(r):
    return "not reached" if r["t_line"] is None else f"reached at {r['t_line']:.2f} s"

  for road in dict.fromkeys(r["road"] for r in rs):
    a, b = [r for r in rs if r["road"] == road]
    if a["corr"] is None and a["max_dev"] < 0.05:
      lines.append(f"- {road}: the car keeps its lane either way (peak offset {a['max_dev']:.2f} m); the siren only "
                   f"tells the driver at {f(b['siren'])} that steering has stopped.")
      continue
    lines.append(f"- {road}: correction from {f(a['corr'])} to {f(b['corr'])}; peak offset {a['max_dev']:.2f} m to "
                 f"{b['max_dev']:.2f} m; 3.7 m lane line {line(a)} as built, {line(b)} with the siren.")
  return "\n".join(lines) + "\n"


def figure(rs: list[dict], standalone: bool) -> str:
  """Offset against time at the ODD curve bound, both variants. Register style (page classes) or standalone."""
  a, b = [r for r in rs if r["road_key"] == FIGURE_ROAD]
  W, H = 640, 352
  x0, x1, y0, y1 = 56, 616, 46, 250
  t_min, t_max = -0.5, 5.0
  lo = -(max(a["max_dev"], b["max_dev"]) // 1 + 1)
  hi = 1.0

  def X(t):
    return x0 + (t - t_min) / (t_max - t_min) * (x1 - x0)

  def Y(e):
    return y0 + (hi - e) / (hi - lo) * (y1 - y0)

  def path(trace):
    pts = [(t, e) for t, e in trace if t_min <= t <= t_max][::5]
    return "M" + " L".join(f"{X(t):.1f},{Y(e):.1f}" for t, e in pts)

  out = []
  if standalone:
    out.append(f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" '
               'aria-labelledby="t">')
    out.append("<style>svg{--ink:#0b0b0b;--muted:#52514e;--line:#d6d5d0;--bad:#e34948;--accent:#2a78d6;--bg:#ffffff;"
               "font-family:-apple-system,'Segoe UI',Helvetica,Arial,sans-serif}"
               "@media (prefers-color-scheme: dark){svg{--ink:#f0efec;--muted:#c3c2b7;--line:#3a3936;--bad:#e66767;"
               "--accent:#3987e5;--bg:#1a1a19}}"
               ".s-ink{fill:var(--ink)} .s-muted{fill:var(--muted)} .s-bad{fill:var(--bad)} .s-acc{fill:var(--accent)}</style>")
    out.append(f'<rect width="{W}" height="{H}" style="fill:var(--bg)"/>')
  else:
    out.append(f'<svg viewBox="0 0 {W} {H}" role="img" aria-labelledby="dq404t">')
  tid = "t" if standalone else "dq404t"
  out.append(f'<title id="{tid}">SoC stall at the ODD curve bound: lateral offset as built (no siren, driver cue is '
             f'the drift, correction at {a["corr"]:.2f} s, peak {a["max_dev"]:.1f} m) and with a siren on revocation '
             f'(correction at {b["corr"]:.2f} s, peak {b["max_dev"]:.1f} m)</title>')
  out.append('<text x="0" y="14" class="s-muted" font-size="12" font-weight="600" letter-spacing=".06em">'
             'SOC STALL IN A CURVE AT R_ODD, 110 KM/H · SYNTHETIC, NO EVIDENCE CREDIT</text>')
  step = 2 if hi - lo > 6 else 1
  e = 0
  while e >= lo:
    out.append(f'<line x1="{x0}" y1="{Y(e):.1f}" x2="{x1}" y2="{Y(e):.1f}" stroke="var(--line)" stroke-width="1"/>')
    out.append(f'<text x="{x0 - 8}" y="{Y(e) + 4:.1f}" text-anchor="end" class="s-muted" font-size="11">{e}</text>')
    e -= step
  for t in range(0, int(t_max) + 1):
    out.append(f'<text x="{X(t):.1f}" y="{y1 + 16}" text-anchor="middle" class="s-muted" font-size="11">{t} s</text>')
  out.append(f'<text x="{x0}" y="{y0 - 10}" class="s-muted" font-size="11">lateral offset (m), negative = toward the '
             'outside of the curve</text>')
  thr = -0.96
  out.append(f'<line x1="{x0}" y1="{Y(thr):.1f}" x2="{x1}" y2="{Y(thr):.1f}" stroke="var(--bad)" stroke-width="1.2" '
             'stroke-dasharray="5 4"/>')
  out.append(f'<text x="{x0 + 4}" y="{Y(thr) + 14:.1f}" class="s-bad" font-size="11">body on the lane '
             'line (3.7 m lane)</text>')
  out.append(f'<path d="{path(a["trace"])}" fill="none" stroke="var(--bad)" stroke-width="2.4"/>')
  out.append(f'<path d="{path(b["trace"])}" fill="none" stroke="var(--accent)" stroke-width="2.4"/>')
  for r, col in ((a, "var(--bad)"), (b, "var(--accent)")):
    for t in (r["cue"], r["corr"]):
      ey = min(r["trace"], key=lambda p: abs(p[0] - t))[1]
      out.append(f'<circle cx="{X(t):.1f}" cy="{Y(ey):.1f}" r="4.5" fill="{col}"/>')
  ly = y1 + 40
  out.append(f'<line x1="{x0}" y1="{ly - 4}" x2="{x0 + 24}" y2="{ly - 4}" stroke="var(--bad)" stroke-width="3"/>')
  out.append(f'<text x="{x0 + 32}" y="{ly}" class="s-ink" font-size="12.5">As built: no siren; cue is the drift at '
             f'{a["cue"]:.2f} s, correction from {a["corr"]:.2f} s, peak {a["max_dev"]:.1f} m</text>')
  out.append(f'<line x1="{x0}" y1="{ly + 20}" x2="{x0 + 24}" y2="{ly + 20}" stroke="var(--accent)" stroke-width="3"/>')
  out.append(f'<text x="{x0 + 32}" y="{ly + 24}" class="s-ink" font-size="12.5">Siren on revocation: siren at '
             f'{b["siren"]:.2f} s, correction from {b["corr"]:.2f} s, peak {b["max_dev"]:.1f} m</text>')
  out.append(f'<text x="{x0 + 32}" y="{ly + 42}" class="s-muted" font-size="11">Dots: driver cue, then correction. '
             'Plant run F-04b, real panda code; driver reacts 1.5 s after the cue.</text>')
  out.append("</svg>")
  return "\n".join(out) + "\n"


def build() -> dict[Path, str]:
  rs = runs()
  return {OUT_MD: table(rs), OUT_SVG: figure(rs, True), OUT_DQ: figure(rs, False)}


def main(argv: list[str]) -> int:
  out = build()
  if "--check" in argv:
    stale = [p for p, c in out.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
    for p in stale:
      print(f"stale: {p.relative_to(SIM.parent)}", file=sys.stderr)
    if not stale:
      print(f"silent_stall: {len(out)} file(s) current")
    return 1 if stale else 0
  for p, c in out.items():
    p.write_text(c, encoding="utf-8")
  print(f"wrote {len(out)} file(s)")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
