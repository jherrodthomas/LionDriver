#!/usr/bin/env python3
"""A stopped car ahead (physics plan round 3, study 11; WP-C-06 TC-08, WP-V-03 KS-05).

At highway speed openpilot takes a lead only from the driving model: radard matches a radar track to the model's lead
when the model's probability passes 0.5, and uses a radar track on its own only below 4 m/s and within 25 m
(`radard.py`, read here). So a stopped car ahead becomes a lead when the model sees it. This study sizes the car in
the model's input (the narrow road camera's frame at 910 px focal length, the wide one's at 455 px, `model.py`) at
each distance, and sets the distance at which it spans 32, 20 and 10 px against the distance needed to stop: by the
item at its −3.5 m/s², and by the driver alone (an unwarned 2.5 s or an attentive 1.5 s, then full braking, dry or
wet with 3 mm of tread). Writes `../results/stopped-car.json` and `.md`.

    python3 stopped_car.py --figures
    python3 stopped_car.py --check

What the model actually detects at a given size is learned, not geometry: this gives the size it has to work with,
not whether it does. The item does not stop for a stopped car it has not taken as a lead (WP-C-02 F-02); the driver
and the stock PCS do. Synthetic (DSR-12), design aid, no evidence credit.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import wet_braking as wb  # noqa: E402
import wet_curves as wc  # noqa: E402

SIM = HERE.parent
ROOT = SIM.parents[1]
MODEL = ROOT / "openpilot" / "common" / "transformations" / "model.py"
RADARD = ROOT / "openpilot" / "selfdrive" / "controls" / "radard.py"
OUT_JSON = SIM / "results" / "stopped-car.json"
OUT_MD = SIM / "results" / "stopped-car.md"


def code() -> dict:
  """The model's input focal lengths and radard's lead rules, read from openpilot; stops if a rule has moved."""
  m = MODEL.read_text(encoding="utf-8")
  r = RADARD.read_text(encoding="utf-8")
  for line in (r"if len\(tracks\) > 0 and ready and lead_prob > \.5:",
               r"elif \(track is None\) and ready and \(lead_prob > \.5\):",
               r"return abs\(self\.yRel\) < 1\.0 and \(v_ego < V_EGO_STATIONARY\) and \(0\.75 < self\.dRel < 25\)"):
    if not re.search(line, r):
      raise SystemExit(f"radard changed: {line!r} not found; review stopped_car.py")
  def num(pat, txt):
    g = re.search(pat, txt)
    if not g:
      raise SystemExit(f"openpilot changed: no match for {pat!r}; review stopped_car.py")
    return float(g.group(1))
  return {"narrow_fl_px": num(r"medmodel_fl = ([\d.]+)", m),
          "wide_fl_px": num(r"sbigmodel_fl = ([\d.]+)", m),
          "model_input_px": [int(num(r"MEDMODEL_INPUT_SIZE = \((\d+)", m)), int(num(r"MEDMODEL_INPUT_SIZE = \(\d+, (\d+)\)", m))],
          "lead_prob_min": 0.5, "radar_alone_below_mps": num(r"V_EGO_STATIONARY = ([\d.]+)", r),
          "radar_alone_within_m": 25.0}


def run(p: dict) -> dict:
  s = p["stopped_car"]
  c = code()
  v = s["speed_kph"]
  w = s["car_rear_m"]["width"]
  depth = float(wb.water(p, [p["curves"]["rain_mm_h"]["value"]])[0])
  mu_wet = wc.mu_odd(p, v, depth)
  mu_dry = wc.mu_odd(p, v, 0.0)
  a_item = -wb.accel_min()
  t_drv = s["driver_reaction_s"]
  stop = {"item": wb.stop_m(v, a_item, p["braking"]["reaction_s"]["value"]),
          "driver_attentive_dry": wb.stop_m(v, mu_dry * 9.81, t_drv["low"]),
          "driver_unwarned_dry": wb.stop_m(v, mu_dry * 9.81, t_drv["value"]),
          "driver_unwarned_wet": wb.stop_m(v, mu_wet * 9.81, t_drv["value"])}
  at = {}
  for frame, fl in (("narrow", c["narrow_fl_px"]), ("wide", c["wide_fl_px"])):
    at[frame] = {str(n): round(fl * w / n, 1) for n in s["sizes_px"]}
  size_at_stop = {frame: {k: round(fl * w / d, 1) for k, d in stop.items()}
                  for frame, fl in (("narrow", c["narrow_fl_px"]), ("wide", c["wide_fl_px"]))}
  return {"about": "Synthetic (DSR-12), design aid, no evidence credit. Geometry of the model's input; what the model "
                   "detects is learned, not computed here.",
          "code": c, "speed_kph": v, "mu": {"dry_3mm": round(mu_dry, 3), "wet_3mm": round(mu_wet, 3)},
          "stop_m": {k: round(d, 1) for k, d in stop.items()},
          "distance_at_px": at, "px_at_stop": size_at_stop,
          "seconds_at_px": {f: {n: round(d / (v / 3.6), 2) for n, d in at[f].items()} for f in at}}


def markdown(r: dict, p: dict) -> str:
  c = r["code"]
  s = p["stopped_car"]
  st, px = r["stop_m"], r["px_at_stop"]
  L = [
    "# A stopped car ahead: how big it is when the driving model has to see it",
    "",
    "> **Synthetic data (DSR-12). Design aid, no evidence credit (DQ-413).** Generated by "
    "[`weather/stopped_car.py`](../weather/stopped_car.py) with the model's input intrinsics and radard's lead rules "
    "read from openpilot; do not edit by hand. What the model detects at a given size is learned, not computed: this "
    "is the size it has to work with.",
    "",
    f"At highway speed a stopped car becomes the lead only when the driving model reports it with probability above "
    f"{c['lead_prob_min']:.1f}; radar alone counts only below {c['radar_alone_below_mps']:.0f} m/s and within "
    f"{c['radar_alone_within_m']:.0f} m (`radard.py`). The model sees the narrow road camera at "
    f"{c['narrow_fl_px']:.0f} px focal length and the wide one at {c['wide_fl_px']:.0f} px, in "
    f"{c['model_input_px'][0]} × {c['model_input_px'][1]} px frames (`model.py`). A car's rear is "
    f"{s['car_rear_m']['width']:.1f} m wide.",
    "",
    f"| Car's width in the model's input | Narrow frame: distance (time at {r['speed_kph']:.0f} km/h) | Wide frame |",
    "|---|---|---|",
  ]
  for n in map(str, s["sizes_px"]):
    L.append(f"| {n} px | {r['distance_at_px']['narrow'][n]:.0f} m ({r['seconds_at_px']['narrow'][n]:.1f} s) | "
             f"{r['distance_at_px']['wide'][n]:.0f} m ({r['seconds_at_px']['wide'][n]:.1f} s) |")
  names = {"item": "the item at −3.5 m/s² (0.5 s to act)",
           "driver_attentive_dry": "an attentive driver (1.5 s), full braking, dry",
           "driver_unwarned_dry": "an unwarned driver (2.5 s), full braking, dry",
           "driver_unwarned_wet": "an unwarned driver (2.5 s), full braking, wet, 3 mm"}
  L += ["", "| To stop from 110 km/h | Distance | The car's width then, narrow / wide frame |", "|---|---|---|"]
  for k, nm in names.items():
    L.append(f"| {nm} | {st[k]:.0f} m | {px['narrow'][k]:.0f} / {px['wide'][k]:.0f} px |")
  L += ["", "## What this shows (generated)", "",
        f"- **For the item to stop on its own** at −3.5 m/s², the model has to take the stopped car as a lead by "
        f"{st['item']:.0f} m, where it is **{px['narrow']['item']:.0f} px wide** in the narrow frame: well under "
        f"the {s['small_object_px']['value']} × {s['small_object_px']['value']} px below which MS COCO counts an object "
        "as small, the size range where detectors do worst.",
        f"- **For the driver**, an unwarned 2.5 s plus full braking needs {st['driver_unwarned_dry']:.0f} m dry and "
        f"{st['driver_unwarned_wet']:.0f} m wet with 3 mm of tread; the car is {px['narrow']['driver_unwarned_wet']:.0f} px "
        "wide at the wet distance. The driver's own eyes do the work there; the model's output does not.",
        f"- The car reaches {s['small_object_px']['value']} px in the narrow frame only at "
        f"{r['distance_at_px']['narrow'][str(s['small_object_px']['value'])]:.0f} m, "
        f"{r['seconds_at_px']['narrow'][str(s['small_object_px']['value'])]:.1f} s away: "
        + ("closer than every stopping distance above. For the item to stop, the model has to act on a car smaller "
           "than that; a driver's eyes resolve far more." if all(d > r["distance_at_px"]["narrow"][str(s["small_object_px"]["value"])] for d in st.values())
           else "inside some of the stopping distances above."),
        "- For KS-05: test the stopped car from 200 m and more, so the drive covers the distance where the model must "
        "decide; logs of `radarState` and `modelV2` leads show at what range it does (T1).",
        ""]
  return "\n".join(L)


def main(argv):
  ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  ap.add_argument("--check", action="store_true")
  ap.add_argument("--figures", action="store_true")
  a = ap.parse_args(argv[1:])
  p = yaml.safe_load((HERE / "params.yaml").read_text(encoding="utf-8"))
  r = run(p)
  md = markdown(r, p)
  if a.check:
    from sun_glare import compare
    errs = compare(r, json.loads(OUT_JSON.read_text(encoding="utf-8")))
    if not errs and OUT_MD.read_text(encoding="utf-8") != md:
      errs.append(f"{OUT_MD.name} is stale")
    for e in errs[:20]:
      print("FAIL", e)
    print("stopped car:", "OK" if not errs else f"{len(errs)} difference(s)")
    return 1 if errs else 0
  OUT_JSON.write_text(json.dumps(r, indent=1) + "\n", encoding="utf-8")
  OUT_MD.write_text(md, encoding="utf-8")
  print("wrote", OUT_JSON.name, OUT_MD.name, r["code"], r["stop_m"], r["px_at_stop"], r["distance_at_px"])
  if a.figures:
    import fig_weather
    fig_weather.stopped_car_figures(p, r, HERE / "figures")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv))
