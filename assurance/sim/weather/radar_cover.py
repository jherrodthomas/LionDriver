#!/usr/bin/env python3
"""Water, ice and slush on the radar cover (physics plan round 4, study 27; WP-C-06 TC-03, TC-04).

The stock radar looks out through the bumper's emblem. A layer of water, ice or slush on it is a lossy dielectric at
77 GHz. Its permittivity: liquid water from ITU-R P.840-9's double-Debye model; ice nearly lossless (ε′ 3.15); slush by
Birchak's mixing rule. A layer of thickness d in air passes |t|² of the power, with t the thin-film transmission
(both faces' reflections and the loss inside, at normal incidence). The radar's signal goes through twice, so the
two-way loss is |t|⁴, and for the same detection threshold the range falls to |t| of its dry value (radar equation,
range ∝ power^¼). Writes `../results/radar-cover.json` and `.md`.

    python3 radar_cover.py --figures
    python3 radar_cover.py --check

The cover itself (its material and thickness, T1) is left out: the layer is taken in air, which ignores how it
detunes a cover built to pass 77 GHz. What uses the radar: openpilot at highway speed only to confirm the model's lead
(radard, the stopped-car study), and the stock PCS, the backstop the night, curve and stopped-car studies lean on.
Synthetic (DSR-12), design aid, no evidence credit (DQ-413).
"""

from __future__ import annotations

import argparse
import cmath
import json
import math
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
OUT_JSON = SIM / "results" / "radar-cover.json"
OUT_MD = SIM / "results" / "radar-cover.md"
C = 299_792_458.0


def water_eps(f_ghz: float, t_c: float) -> complex:
  """Liquid water, ITU-R P.840-9 eqs. 4–10; returned as ε′ − jε″."""
  th = 300.0 / (t_c + 273.15)
  e0 = 77.66 + 103.3 * (th - 1)
  e1 = 0.0671 * e0
  e2 = 3.52
  fp = 20.20 - 146 * (th - 1) + 316 * (th - 1) ** 2
  fs = 39.8 * fp
  re = (e0 - e1) / (1 + (f_ghz / fp) ** 2) + (e1 - e2) / (1 + (f_ghz / fs) ** 2) + e2
  im = f_ghz * (e0 - e1) / (fp * (1 + (f_ghz / fp) ** 2)) + f_ghz * (e1 - e2) / (fs * (1 + (f_ghz / fs) ** 2))
  return complex(re, -im)


def birchak(parts: list[tuple[float, complex]]) -> complex:
  """√ε = Σ vᵢ √εᵢ (volume fractions summing to one)."""
  return sum(v * cmath.sqrt(e) for v, e in parts) ** 2


def transmission(eps: complex, d_m: float, f_ghz: float) -> complex:
  """Amplitude transmission of a layer of permittivity eps and thickness d in air, normal incidence."""
  n = cmath.sqrt(eps)
  if n.imag > 0:
    n = n.conjugate()                     # the lossy root for ε′ − jε″ with e^{+jωt}: n = n′ − jκ
  r12 = (1 - n) / (1 + n)
  r23 = (n - 1) / (n + 1)
  t12, t23 = 2 / (1 + n), 2 * n / (n + 1)
  delta = 2 * math.pi * f_ghz * 1e9 / C * n * d_m
  ph = cmath.exp(-1j * delta)
  return t12 * t23 * ph / (1 + r12 * r23 * ph * ph)


def case(eps: complex, d_mm: float, f: float) -> dict:
  t = abs(transmission(eps, d_mm / 1000, f))
  n = cmath.sqrt(eps)
  absorbed = 2 * 8.686 * 2 * math.pi * f * 1e9 / C * abs(n.imag) * d_mm / 1000     # two-way, absorption alone
  return {"thickness_mm": d_mm, "two_way_db": round(-40 * math.log10(t), 2), "range_kept": round(t, 3),
          "absorbed_db": round(absorbed, 2)}


def run(p: dict) -> dict:
  rc = p["radar_cover"]
  f = rc["frequency_ghz"]["value"]
  ice = complex(rc["ice_permittivity"]["real"], -rc["ice_permittivity"]["imag"])
  th = rc["thickness_mm"]
  out = {"about": "Synthetic (DSR-12), design aid, no evidence credit. Water from ITU-R P.840-9; ice estimated; "
                  "slush by Birchak's rule; a layer in air.", "frequency_ghz": f, "permittivity": {}, "layers": {}}
  for t_c in rc["water_temp_c"]["value"]:
    e = water_eps(f, t_c)
    out["permittivity"][f"water_{t_c:g}C"] = [round(e.real, 3), round(-e.imag, 3)]
    out["layers"][f"water_{t_c:g}C"] = [case(e, d, f) for d in th["water"]]
  out["permittivity"]["ice"] = [ice.real, -ice.imag]
  out["layers"]["ice"] = [case(ice, d, f) for d in th["ice"]]
  w0 = water_eps(f, 0.0)
  for v in rc["slush_water_fraction"]["value"]:
    e = birchak([(v, w0), (1 - v, ice)])
    out["permittivity"][f"slush_{v:g}"] = [round(e.real, 3), round(-e.imag, 3)]
    out["layers"][f"slush_{v:g}"] = [case(e, d, f) for d in th["slush"]]
  n = cmath.sqrt(w0)
  out["water_db_per_mm_one_way"] = round(8.686 * 2 * math.pi * f * 1e9 / C * abs(n.imag) / 1000, 2)
  return out


def markdown(r: dict, p: dict) -> str:
  L = [
    "# Water, ice and slush on the radar cover: what the stock radar loses",
    "",
    "> **Synthetic data (DSR-12). Design aid, no evidence credit (DQ-413).** Generated by "
    "[`weather/radar_cover.py`](../weather/radar_cover.py); water's permittivity from ITU-R P.840-9, ice estimated, "
    "slush by Birchak's mixing rule; do not edit by hand. The layer is taken in air: the cover itself (T1) is left out.",
    "",
    f"At {r['frequency_ghz']:g} GHz liquid water has a permittivity of {r['permittivity']['water_0C'][0]:.1f} − "
    f"j{r['permittivity']['water_0C'][1]:.1f} near freezing and {r['permittivity']['water_20C'][0]:.1f} − "
    f"j{r['permittivity']['water_20C'][1]:.1f} at 20 °C: inside it the wave loses about "
    f"{r['water_db_per_mm_one_way']:.0f} dB per millimetre each way. Ice ({r['permittivity']['ice'][0]:.2f}) hardly "
    "absorbs. The radar's signal crosses the layer twice; its range falls to the share of the amplitude that gets "
    "through.",
    "",
    "| Layer | Thickness | Two-way loss | Range kept |",
    "|---|---|---|---|",
  ]
  names = {"water_0C": "water, 0 °C", "water_20C": "water, 20 °C", "ice": "ice",
           "slush_0.2": "slush, 20 % water", "slush_0.5": "slush, 50 % water"}
  for k, nm in names.items():
    for x in r["layers"][k]:
      L.append(f"| {nm} | {x['thickness_mm']:g} mm | {x['two_way_db']:.1f} dB | {100 * x['range_kept']:.0f} % |")
  w = {x["thickness_mm"]: x for x in r["layers"]["water_0C"]}
  ice = {x["thickness_mm"]: x for x in r["layers"]["ice"]}
  s5 = {x["thickness_mm"]: x for x in r["layers"]["slush_0.5"]}
  L += ["", "## What this shows (generated)", "",
        f"- **A rain film costs range fast.** A tenth of a millimetre of water takes {w[0.1]['two_way_db']:.0f} dB both ways "
        f"and leaves {100 * w[0.1]['range_kept']:.0f} % of the range; half a millimetre {w[0.5]['two_way_db']:.0f} dB and "
        f"{100 * w[0.5]['range_kept']:.0f} %. At a tenth of a millimetre absorption is {w[0.1]['absorbed_db']:.0f} dB of it; "
        "the rest is the film's reflection, which a thin layer of so high a permittivity already has.",
        f"- **Clear ice is nearly transparent.** {ice[5.0]['thickness_mm']:g} mm of it costs {ice[5.0]['two_way_db']:.1f} dB "
        f"({100 * ice[5.0]['range_kept']:.0f} % of the range); its reflections, not its loss, set that.",
        f"- **Slush is between, and the water in it decides.** Wet slush 2 mm thick takes {s5[2.0]['two_way_db']:.0f} dB "
        f"({100 * s5[2.0]['range_kept']:.0f} %).",
        "- **What depends on the radar:** at highway speed openpilot takes a lead only from the driving model and uses "
        "the radar to confirm it (the stopped-car study), so a wet cover weakens the radar's part, not the lead. The stock "
        "PCS is different: it is the backstop the night, curve and stopped-car studies leave to the car, and it brakes on "
        "this radar. A wet or slushy emblem shortens its reach, and this study cannot say when the car notices.",
        "- For KS-15 and the owner's information: test the PCS backstop in rain with spray; tell the driver that slush on "
        "the emblem can blind the radar the car's emergency braking relies on. The cover's material (T1) moves the thin-film "
        "numbers, not the trend.",
        ""]
  return "\n".join(L)


def main(argv):
  ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  ap.add_argument("--check", action="store_true")
  ap.add_argument("--figures", action="store_true")
  a = ap.parse_args(argv[1:])
  p = yaml.safe_load((HERE / "params.yaml").read_text(encoding="utf-8"))
  r = run(p)
  md = markdown(r, p)
  sys.path.insert(0, str(HERE))
  if a.check:
    from sun_glare import compare
    errs = compare(r, json.loads(OUT_JSON.read_text(encoding="utf-8")))
    if not errs and OUT_MD.read_text(encoding="utf-8") != md:
      errs.append(f"{OUT_MD.name} is stale")
    for e in errs[:20]:
      print("FAIL", e)
    print("radar cover:", "OK" if not errs else f"{len(errs)} difference(s)")
    return 1 if errs else 0
  OUT_JSON.write_text(json.dumps(r, indent=1) + "\n", encoding="utf-8")
  OUT_MD.write_text(md, encoding="utf-8")
  print("wrote", OUT_JSON.name, OUT_MD.name)
  if a.figures:
    import fig_weather
    fig_weather.radar_cover_figures(p, r, HERE / "figures")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv))
