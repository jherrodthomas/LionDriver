#!/usr/bin/env python3
"""Fog (physics plan round 3, study 17; WP-C-06 TC-04): how far the road camera sees in fog.

Fog is outside the ODD (WP-C-02); this gives the visibility at which the exit has to come. Koschmieder's law: an object
seen against the horizon through fog keeps the contrast C0·exp(−σd), with σ = ln(20)/V for a meteorological optical
range V (WMO, 5 %). An object seen against the road instead (a lane line) loses contrast faster, because the fog's
airlight is brighter than the road: C = C0 / (1 + (L_sky/L_road)(exp(σd) − 1)). The camera is taken to see an object
while its contrast stays above a threshold of 2–5 %. For each visibility: the distance at which a stopped car and the
lane lines are seen, against the distances to stop (study 11) and a 2 s preview of the lines. Writes
`../results/fog-visibility.json` and `.md`.

    python3 fog_visibility.py --figures
    python3 fog_visibility.py --check

The truck-spray half of the plan's study 17 is not built: no quantitative spray source was found (physics plan round 3
§3). Synthetic (DSR-12), design aid, no evidence credit.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
STOPPED = SIM / "results" / "stopped-car.json"
OUT_JSON = SIM / "results" / "fog-visibility.json"
OUT_MD = SIM / "results" / "fog-visibility.md"


def sigma(v_m: float, mor_contrast: float = 0.05) -> float:
  """Extinction coefficient (1/m) for a meteorological optical range v_m."""
  return math.log(1 / mor_contrast) / v_m


def against_sky(c0: float, threshold: float, v_m: float, mor: float = 0.05) -> float:
  """Distance at which an object of inherent contrast c0 against the horizon falls to the threshold."""
  return max(math.log(c0 / threshold), 0.0) / sigma(v_m, mor)


def against_road(c0: float, threshold: float, v_m: float, sky_to_road: float, mor: float = 0.05) -> float:
  """Distance at which a line of contrast c0 against the road falls to the threshold under the fog's airlight."""
  if c0 <= threshold:
    return 0.0
  return math.log(1 + (c0 / threshold - 1) / sky_to_road) / sigma(v_m, mor)


def run(p: dict) -> dict:
  f = p["fog_visibility"]
  stop = json.loads(STOPPED.read_text(encoding="utf-8"))["stop_m"]
  v_ego = p["stopped_car"]["speed_kph"] / 3.6
  mor = f["mor_contrast"]["value"]
  th = f["camera_threshold"]
  rows = []
  for V in f["visibilities_m"]:
    rows.append({"visibility_m": V,
                 "car_m": [round(against_sky(f["car_contrast"][k], th[t], V, mor), 1)
                           for k, t in (("low", "value"), ("value", "low"))],
                 "line_m": [round(against_road(f["line_contrast"]["value"], th[t], V, f["sky_to_road"][s], mor), 1)
                            for s, t in (("high", "value"), ("low", "low"))],
                 "line_nominal_m": round(against_road(f["line_contrast"]["value"], th["value"], V,
                                                      f["sky_to_road"]["value"], mor), 1)})
  def need_v(dist, which, idx):
    # the visibility at which the seen distance equals `dist` (seen distance is proportional to V)
    r0 = rows[-1]
    return round(dist * r0["visibility_m"] / r0[which][idx], 1)
  preview = f["preview_s"]["value"] * v_ego
  return {"about": "Synthetic (DSR-12), design aid, no evidence credit. Koschmieder's law; assumed camera threshold.",
          "rows": rows, "stop_m": stop, "preview_m": round(preview, 1),
          "visibility_needed_m": {
            "car_item": [need_v(stop["item"], "car_m", 1), need_v(stop["item"], "car_m", 0)],
            "car_driver_wet": [need_v(stop["driver_unwarned_wet"], "car_m", 1), need_v(stop["driver_unwarned_wet"], "car_m", 0)],
            "lines_preview": [need_v(preview, "line_m", 1), need_v(preview, "line_m", 0)],
            "lines_preview_nominal": round(preview * rows[-1]["visibility_m"] / rows[-1]["line_nominal_m"], 1)},
          "dense_fog_m": f["dense_fog_m"]["value"], "odd_visibility_m": f["odd_visibility_m"]["value"]}


def markdown(r: dict, p: dict) -> str:
  f = p["fog_visibility"]
  n = r["visibility_needed_m"]
  L = [
    "# Fog: how far the road camera sees",
    "",
    "> **Synthetic data (DSR-12). Design aid, no evidence credit (DQ-413).** Generated by "
    "[`weather/fog_visibility.py`](../weather/fog_visibility.py); do not edit by hand. Koschmieder's law; the contrast "
    "openpilot's model needs is not known, so it is a band (2–5 %).",
    "",
    "Visibility is the meteorological optical range (WMO, 5 % contrast). A stopped car is seen against the fog-lit "
    f"horizon (inherent contrast {f['car_contrast']['low']:.1f}–{f['car_contrast']['value']:.1f}); the lane lines against the "
    f"road (contrast {f['line_contrast']['value']:.1f}, NCHRP 20-102(06)), where the fog's airlight is "
    f"{f['sky_to_road']['low']:.0f}–{f['sky_to_road']['high']:.0f} times the road's own luminance.",
    "",
    "| Visibility | Stopped car seen at | Lane lines seen at |",
    "|---|---|---|",
  ]
  for row in r["rows"]:
    L.append(f"| {row['visibility_m']} m | {row['car_m'][0]:.0f}–{row['car_m'][1]:.0f} m | "
             f"{row['line_m'][0]:.0f}–{row['line_m'][1]:.0f} m |")
  s = r["stop_m"]
  L += ["", "## What this shows (generated)", "",
        f"- **For the item to stop for a stopped car** at −3.5 m/s² ({s['item']:.0f} m), the camera has to see it that far: "
        f"visibility of at least {n['car_item'][0]:.0f}–{n['car_item'][1]:.0f} m. An unwarned driver stopping on a wet road "
        f"({s['driver_unwarned_wet']:.0f} m) needs {n['car_driver_wet'][0]:.0f}–{n['car_driver_wet'][1]:.0f} m.",
        f"- **The lane lines go first.** Seen against the road through the fog's airlight, they fade much sooner than a car "
        f"against the sky: a {r['preview_m']:.0f} m preview (2 s at 110 km/h) needs a visibility of "
        f"{n['lines_preview'][0]:.0f}–{n['lines_preview'][1]:.0f} m.",
        f"- **Against the ODD's bound of {r['odd_visibility_m']:.0f} m** (WP-C-02): the item's own stop needs at most "
        f"{n['car_item'][1]:.0f} m of visibility, "
        + ("inside the bound." if n["car_item"][1] <= r["odd_visibility_m"] else "more than the bound.")
        + f" The lines need {n['lines_preview_nominal']:.0f} m with the nominal inputs (5 % threshold, airlight "
        f"{f['sky_to_road']['value']:.0f} times the road) and up to {n['lines_preview'][1]:.0f} m at the cautious end: "
        + ("the bound has margin for the lines too." if n["lines_preview"][1] <= r["odd_visibility_m"] else
           "the 200 m bound is about right nominally and short at the cautious end. The camera's real contrast threshold, "
           "from local logs in fog, decides whether it needs to move; until then this is a margin to watch, not a "
           "reason to change it."),
        "- Not covered: truck spray (no quantitative source), the road camera's own exposure in fog, and the model's real "
        "contrast threshold, which local logs in fog would show.",
        ""]
  return "\n".join(L)


def main(argv):
  ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  ap.add_argument("--check", action="store_true")
  ap.add_argument("--figures", action="store_true")
  a = ap.parse_args(argv[1:])
  p = yaml.safe_load((HERE / "params.yaml").read_text(encoding="utf-8"))
  r = run(p)
  md = markdown(r, p)
  if a.check:
    from sun_glare import compare
    errs = compare(r, json.loads(OUT_JSON.read_text(encoding="utf-8")))
    if not errs and OUT_MD.read_text(encoding="utf-8") != md:
      errs.append(f"{OUT_MD.name} is stale")
    for e in errs[:20]:
      print("FAIL", e)
    print("fog visibility:", "OK" if not errs else f"{len(errs)} difference(s)")
    return 1 if errs else 0
  OUT_JSON.write_text(json.dumps(r, indent=1) + "\n", encoding="utf-8")
  OUT_MD.write_text(md, encoding="utf-8")
  print("wrote", OUT_JSON.name, OUT_MD.name, r["visibility_needed_m"])
  if a.figures:
    import fig_weather
    fig_weather.fog_visibility_figures(p, r, HERE / "figures")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv))
