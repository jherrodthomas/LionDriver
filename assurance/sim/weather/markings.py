#!/usr/bin/env python3
"""Lane markings at night in rain (physics plan round 3, study 16; WP-C-06 TC-05, TC-03, WP-V-03 KS-03, KS-15).

Under the car's own low beams a line and the road beside it are lit alike, so their luminances stand in the ratio of
their retroreflectivities (RL, mcd/m²/lx). Oncoming headlights add a veil of scattered light over the whole image
(the headlight study, `headlights.py`), which lifts both and lowers the ratio; on a wet road, which returns far less
of the light, the same veil weighs more. The contrast ratio (line + veil) / (road + veil) is set against what a
machine-vision system needed in NCHRP Project 20-102(06): 2.5 at night dry, 3.0 with oncoming glare, 2.1 wet. For
each case: the contrast a line at the US minimum (and better) gives, and the line RL needed. Writes
`../results/markings.json` and `.md`.

    python3 markings.py --figures
    python3 markings.py --check

The NCHRP thresholds are a Mobileye camera's on a closed course, not openpilot's model; the line and road RL are
measured at 30 m geometry, not the road camera's. Synthetic (DSR-12), design aid, no evidence credit.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
HEADLIGHTS = SIM / "results" / "headlights.json"
OUT_JSON = SIM / "results" / "markings.json"
OUT_MD = SIM / "results" / "markings.md"


def ratio(rl_line: float, rl_road: float, veil: float = 0.0) -> float:
  """Contrast ratio of a line to the road when both carry a veil `veil` (in units of the road's own luminance)."""
  return (rl_line + veil * rl_road) / (rl_road * (1.0 + veil))


def rl_needed(k: float, rl_road: float, veil: float = 0.0) -> float:
  """Line RL that reaches contrast ratio k over a road of rl_road with the veil: k·RL_road + (k − 1)·veil·RL_road."""
  return rl_road * (k + (k - 1.0) * veil)


def run(p: dict) -> dict:
  m = p["markings"]
  hl = json.loads(HEADLIGHTS.read_text(encoding="utf-8"))["cases"]
  pd_, pw = m["pavement_rl"]["dry"], m["pavement_rl"]["wet"]
  req = m["required_ratio"]
  out = {"about": "Synthetic (DSR-12), design aid, no evidence credit. NCHRP 20-102(06) thresholds (a Mobileye camera, "
                  "closed course); the headlight study's veil.",
         "pavement_rl": {"dry": pd_, "wet": pw}, "no_glare": {}, "glare": {}}
  for name, rl in m["line_rl"]["dry"].items():
    if isinstance(rl, float):
      out["no_glare"][f"dry_{name}"] = {"rl": rl, "ratio": round(ratio(rl, pd_), 2), "needed": req["dry"]}
  for name, rl in m["line_rl"]["wet"].items():
    if isinstance(rl, float):
      out["no_glare"][f"wet_{name}"] = {"rl": rl, "ratio": round(ratio(rl, pw), 2), "needed": req["wet"]}
  out["rl_needed_no_glare"] = {"dry": round(rl_needed(req["dry"], pd_), 1), "wet": round(rl_needed(req["wet"], pw), 1)}
  for road, off, beam in m["glare_cases"]:
    for scatter in ("low", "value", "high"):
      key = f"{road}-{off:g}-{beam}-{scatter}"
      v_dry = hl[key]["veil_ratio_max"]                    # the veil over a dry road's own luminance, at its worst
      v_wet = v_dry * pd_ / pw                              # a wet road returns less of the light: the veil weighs more
      out["glare"][key] = {
        "veil_dry": v_dry, "veil_wet": round(v_wet, 3),
        "dry_fhwa_min_ratio": round(ratio(m["line_rl"]["dry"]["fhwa_min"], pd_, v_dry), 2),
        "dry_rl_needed": round(rl_needed(req["dry_glare"], pd_, v_dry), 1),
        "wet_good_ratio": round(ratio(m["line_rl"]["wet"]["good"], pw, v_wet), 2),
        "wet_rl_needed": round(rl_needed(req["wet"], pw, v_wet), 1)}
  return out


GLARE_NAMES = {"divided-8-low": "Oncoming low beams across an 8 m median", "divided-8-high": "Undipped high beams across an 8 m median",
               "undivided-3.7-high": "Undipped high beams, undivided road (outside the ODD)"}


def markdown(r: dict, p: dict) -> str:
  m = p["markings"]
  req = m["required_ratio"]
  ng = r["no_glare"]
  L = [
    "# Lane markings at night in rain: the contrast the camera gets",
    "",
    "> **Synthetic data (DSR-12). Design aid, no evidence credit (DQ-413).** Generated by "
    "[`weather/markings.py`](../weather/markings.py) from NCHRP Project 20-102(06) and the headlight study's veil "
    "([`headlights.md`](headlights.md)); do not edit by hand. The thresholds are a Mobileye camera's on a closed course, "
    "not openpilot's model.",
    "",
    f"Under the car's own low beams the line-to-road contrast ratio is the ratio of their retroreflectivities. The "
    f"pavement returns {r['pavement_rl']['dry']:.1f} mcd/m²/lx dry and {r['pavement_rl']['wet']:.0f} wet. A machine-vision "
    f"system detected every marking above a ratio of {req['dry']:.1f} at night dry, {req['dry_glare']:.1f} with oncoming "
    f"glare and {req['wet']:.1f} wet (NCHRP 20-102(06)).",
    "",
    "## Without glare",
    "",
    "| Line | RL, mcd/m²/lx | Contrast ratio | Needed |",
    "|---|---|---|---|",
  ]
  names = {"dry_fhwa_min": "Dry, at the US minimum (MUTCD)", "dry_fhwa_70mph": "Dry, at the 70 mph recommendation",
           "dry_good": "Dry, a good marking", "wet_low": "Wet, NCHRP's lowest adequate", "wet_robust": "Wet, NCHRP's robust",
           "wet_good": "Wet, a good marking"}
  for k, nm in names.items():
    c = ng[k]
    L.append(f"| {nm} | {c['rl']:.0f} | {c['ratio']:.1f} | {c['needed']:.1f} |")
  L += ["", "The report rounds: its 4 mcd/m²/lx wet line on its 2 mcd/m²/lx pavement is the ratio of 2.1 it found adequate.",
        "", "## With oncoming glare (the veil at its worst while the lamps are in the frame)", "",
        "| Glare | Scatter 1 / 3 / 10 % | Dry, a line at the US minimum: ratio (needs 3.0) | Dry line RL needed | "
        "Wet, a good marking: ratio (needs 2.1) | Wet line RL needed |",
        "|---|---|---|---|---|---|"]
  for gk, nm in GLARE_NAMES.items():
    cs = [r["glare"][f"{gk}-{s}"] for s in ("low", "value", "high")]
    L.append(f"| {nm} | " + "1 / 3 / 10 % | "
             + " / ".join(f"{c['dry_fhwa_min_ratio']:.1f}" for c in cs) + " | "
             + " / ".join(f"{c['dry_rl_needed']:.0f}" for c in cs) + " | "
             + " / ".join(f"{c['wet_good_ratio']:.1f}" for c in cs) + " | "
             + " / ".join(f"{c['wet_rl_needed']:.0f}" for c in cs) + " |")
  lo = r["glare"]["divided-8-low-value"]
  hi = r["glare"]["divided-8-high-value"]
  hi10 = r["glare"]["divided-8-high-high"]
  L += ["", "## What this shows (generated)", "",
        f"- **Dry, no glare:** a line at the US minimum of {m['line_rl']['dry']['fhwa_min']:.0f} mcd/m²/lx gives a ratio of "
        f"{ng['dry_fhwa_min']['ratio']:.1f}, above the {req['dry']:.1f} the camera needed; the minimum is enough.",
        f"- **Dry, oncoming glare:** low beams across a median barely move it ({lo['dry_fhwa_min_ratio']:.1f}). An undipped "
        f"high beam across an 8 m median drops it to {hi['dry_fhwa_min_ratio']:.1f} with 3 % scatter and "
        f"{hi10['dry_fhwa_min_ratio']:.1f} with 10 %; a line then needs {hi['dry_rl_needed']:.0f}–"
        f"{hi10['dry_rl_needed']:.0f} mcd/m²/lx, more than the US minimum.",
        f"- **Wet:** the road returns so little light that a wet line needs only {r['rl_needed_no_glare']['wet']:.0f} "
        f"mcd/m²/lx without glare. But the same glare weighs about {r['pavement_rl']['dry'] / r['pavement_rl']['wet']:.0f} "
        f"times more over a wet road: with an undipped high beam across the median a wet line needs "
        f"{hi['wet_rl_needed']:.0f}–{hi10['wet_rl_needed']:.0f} mcd/m²/lx, and even a good marking's "
        f"{m['line_rl']['wet']['good']:.0f} gives {hi['wet_good_ratio']:.1f}–{hi10['wet_good_ratio']:.1f}.",
        "- The MUTCD sets no wet level, so a road can meet the US minimum and still lose its lines to the camera in rain "
        "with oncoming high beams.",
        "- For KS-03 and KS-15: test worn lines at night in rain, with an oncoming car on high beam across the median. "
        "The ODD's light-rain bound (WP-C-02) keeps rain in.",
        ""]
  return "\n".join(L)


def main(argv):
  ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  ap.add_argument("--check", action="store_true")
  ap.add_argument("--figures", action="store_true")
  a = ap.parse_args(argv[1:])
  p = yaml.safe_load((HERE / "params.yaml").read_text(encoding="utf-8"))
  r = run(p)
  md = markdown(r, p)
  if a.check:
    from sun_glare import compare
    errs = compare(r, json.loads(OUT_JSON.read_text(encoding="utf-8")))
    if not errs and OUT_MD.read_text(encoding="utf-8") != md:
      errs.append(f"{OUT_MD.name} is stale")
    for e in errs[:20]:
      print("FAIL", e)
    print("markings:", "OK" if not errs else f"{len(errs)} difference(s)")
    return 1 if errs else 0
  OUT_JSON.write_text(json.dumps(r, indent=1) + "\n", encoding="utf-8")
  OUT_MD.write_text(md, encoding="utf-8")
  print("wrote", OUT_JSON.name, OUT_MD.name, r["no_glare"], r["rl_needed_no_glare"])
  if a.figures:
    import fig_weather
    fig_weather.markings_figures(p, r, HERE / "figures")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv))
