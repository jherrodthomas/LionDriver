#!/usr/bin/env python3
"""Curves on a wet road (physics plan round 3, study 14; WP-C-06 TC-14, TC-03, WP-V-03 KS-01).

The ODD lets the car corner at up to 2.5 m/s² (WP-C-02 §3.2, R_ODD = v²/2.5). The tyres must hold that sideways,
and, if the item brakes in the curve at its −3.5 m/s² (opendbc ACCEL_MIN), the two together: on the friction
circle the tyres need sqrt(a_lat² + a_brake²) / g, less what the road's bank takes off the lateral part. That need is
set against the peak friction of the wet-braking study's table (`wet_braking.py`) in the ODD's wettest rain (light,
2.5 mm/h on the worst drainage row), for new tyres, the ODD's 3 mm of tread (DQ-416 A, a band from two measured tests) and the 1.6 mm legal minimum.
Writes `../results/wet-curves.json` and `.md`.

    python3 wet_curves.py --figures
    python3 wet_curves.py --check

The friction circle is taken as round (the same grip sideways as lengthways), an assumption. The 3 mm grip is the
new tyre's divided by the measured ratio of wet stopping distances (Continental 1.07, MIRA 1.35). The table is typical tyres, not this car's.
Synthetic (DSR-12), design aid, no evidence credit.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import wet_braking as wb  # noqa: E402

SIM = HERE.parent
OUT_JSON = SIM / "results" / "wet-curves.json"
OUT_MD = SIM / "results" / "wet-curves.md"
G = wb.G


def mu_odd(p: dict, v_kph: float, water_mm: float, end: str = "high") -> float:
  """Peak friction with the ODD's 3 mm of tread: the new tyre's, divided by the measured ratio of wet stopping
  distances at 3 mm to new ("low" Continental's 1.07, "high" MIRA's 1.35). Dry, tread depth hardly matters."""
  ratio = p["curves"]["odd_tread_stop_ratio"][end] if water_mm > 0 else 1.0
  return wb.mu(p, "new", v_kph, water_mm) / ratio


def need(a_lat: float, a_brake: float, bank: float = 0.0) -> float:
  """Friction the tyres need to corner at a_lat and brake at a_brake (m/s²) on a road banked at `bank` (rise/run)."""
  th = math.atan(bank)
  lat = a_lat * math.cos(th) - G * math.sin(th)       # the part of the lateral load the tyres carry
  normal = G * math.cos(th) + a_lat * math.sin(th)
  return math.hypot(max(lat, 0.0), a_brake) / normal


def run(p: dict) -> dict:
  c = p["curves"]
  a_lat = c["lateral_odd"]["value"]
  a_brake = -wb.accel_min()
  depth = float(wb.water(p, [c["rain_mm_h"]["value"]])[0])
  grip = {"new": lambda v, d: wb.mu(p, "new", v, d), "odd_3mm_continental": lambda v, d: mu_odd(p, v, d, "low"),
          "odd_3mm_mira": lambda v, d: mu_odd(p, v, d, "high"), "legal_1_6mm": lambda v, d: wb.mu(p, "worn_1_6mm", v, d)}
  out = {"about": "Synthetic (DSR-12), design aid, no evidence credit. Handbook friction table, not this car's tyres; "
                  "round friction circle; 3 mm from two measured tread-depth tests.",
         "a_lat": a_lat, "a_ctrl": c["lateral_ctrl"]["value"], "a_brake": a_brake, "water_mm": round(depth, 3),
         "need": {}, "available": {}, "speeds_kph": c["speeds_kph"]}
  for bank_name, bank in (("flat", c["superelevation"]["value"]), ("banked", c["superelevation"]["high"])):
    out["need"][bank_name] = {"corner": round(need(a_lat, 0.0, bank), 3), "corner_brake": round(need(a_lat, a_brake, bank), 3),
                              "ctrl_corner_brake": round(need(c["lateral_ctrl"]["value"], a_brake, bank), 3)}
  for tn, f in grip.items():
    out["available"][tn] = {"dry": [round(f(v, 0.0), 3) for v in c["speeds_kph"]],
                            "wet": [round(f(v, depth), 3) for v in c["speeds_kph"]]}
  # the braking the 3 mm tyres still allow while holding the curve, on the flat, at each end of the measured band
  out["brake_in_curve_wet_3mm"] = {}
  for end in ("odd_3mm_continental", "odd_3mm_mira"):
    out["brake_in_curve_wet_3mm"][end] = {}
    for v, m in zip(c["speeds_kph"], out["available"][end]["wet"], strict=True):
      room = (m * G) ** 2 - a_lat ** 2
      out["brake_in_curve_wet_3mm"][end][str(v)] = round(math.sqrt(room), 2) if room > 0 else 0.0
  return out


NAMES = {"new": "New tyres (8 mm)", "odd_3mm_continental": "3 mm, Continental's test (+7 % stop)",
         "odd_3mm_mira": "3 mm, MIRA's tests (+35 % stop)", "legal_1_6mm": "1.6 mm, legal minimum (outside the ODD)"}


def markdown(r: dict, p: dict) -> str:
  n = r["need"]["flat"]
  nb = r["need"]["banked"]
  v = r["speeds_kph"]
  L = [
    "# Curves on a wet road: the grip a curve at the ODD's bound needs",
    "",
    "> **Synthetic data (DSR-12). Design aid, no evidence credit (DQ-413).** Generated by "
    "[`weather/wet_curves.py`](../weather/wet_curves.py) from the wet-braking study's friction table "
    "([`wet-braking.md`](wet-braking.md)) and two measured tread-depth tests; do not edit by hand. Typical tyres, not "
    "this car's.",
    "",
    f"At the ODD's curve bound the car corners at {r['a_lat']:.1f} m/s² (WP-C-02 §3.2). The tyres need, on a flat "
    f"curve, a friction of **{n['corner']:.2f}** to corner, **{r['a_brake'] / 9.81:.2f}** to brake at the item's "
    f"{r['a_brake']:.1f} m/s² on a straight, and **{n['corner_brake']:.2f}** to do both at once (on a 6 % bank: "
    f"{nb['corner']:.2f} and {nb['corner_brake']:.2f}). Water on the road in the ODD's light rain: {r['water_mm']:.2f} mm.",
    "",
    "The ODD's 3 mm of tread is a band between two measured tests: the wet stop at 3 mm is 7 % (Continental) to 35 % "
    "(MIRA) longer than with new tyres, so the grip is the new tyre's divided by 1.07 to 1.35.",
    "",
    "| Tyres | Wet friction at " + " / ".join(f"{s}" for s in v) + " km/h |",
    "|---|---|",
  ]
  for k, nm in NAMES.items():
    L.append(f"| {nm} | " + " / ".join(f"{m:.2f}" for m in r["available"][k]["wet"]) + " |")
  bc, bm = r["brake_in_curve_wet_3mm"]["odd_3mm_continental"], r["brake_in_curve_wet_3mm"]["odd_3mm_mira"]
  top = str(v[-1])
  L += ["", f"Braking the 3 mm tyres still allow while holding the curve at the bound, wet, at {top} km/h: "
        f"{bm[top]:.1f} (MIRA) to {bc[top]:.1f} m/s² (Continental).", "", "## What this shows (generated)", ""]
  wm, wc_ = r["available"]["odd_3mm_mira"]["wet"], r["available"]["odd_3mm_continental"]["wet"]
  brake = r["a_brake"] / 9.81
  L += [
    f"- **Cornering alone holds** with 3 mm of tread at every ODD speed: at least {min(wm):.2f} against "
    f"{n['corner']:.2f} needed." if min(wm) >= n["corner"] else
    f"- **Cornering alone does not hold** with 3 mm at every ODD speed (as low as {min(wm):.2f}).",
    (f"- **Braking at the item's rate on a straight holds** at every ODD speed, even at MIRA's end "
     f"({min(wm):.2f} against {brake:.2f})." if min(wm) >= brake else
     f"- **Braking at the item's rate on a straight does not hold** at MIRA's end ({min(wm):.2f} against {brake:.2f})."),
    f"- **Cornering at the bound and braking at the item's rate together** need {n['corner_brake']:.2f}. "
    + ("Continental's end holds at every speed" if min(wc_) >= n["corner_brake"] else "Continental's end falls short")
    + (", and so does MIRA's." if min(wm) >= n["corner_brake"] else
       f"; MIRA's falls just short at speed ({min(wm):.2f}), leaving {bm[top]:.1f} m/s² of braking at {top} km/h "
       f"instead of {r['a_brake']:.1f}. The stability control would step in before the car ran wide."),
    f"- New tyres hold every case (at least {min(r['available']['new']['wet']):.2f}); at the 1.6 mm legal minimum "
    f"even cornering alone falls short at speed ({min(r['available']['legal_1_6mm']['wet']):.2f}), which is why the ODD "
    "asks for 3 mm.",
    "- For WP-C-02 §3.2: the 0.5 m/s² curve margin was set for controller error and road crown, not for braking in "
    "the curve on a wet road. The case that does not fit is a narrow one (a hard brake at the curve bound, in rain, on "
    "tyres at the ODD's minimum); it is a note for the curve bound's rationale rather than a reason to move it, unless "
    "measured data for this car's tyres says otherwise.",
    "",
  ]
  return "\n".join(L)


def main(argv):
  ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  ap.add_argument("--check", action="store_true")
  ap.add_argument("--figures", action="store_true")
  a = ap.parse_args(argv[1:])
  p = yaml.safe_load((HERE / "params.yaml").read_text(encoding="utf-8"))
  r = run(p)
  md = markdown(r, p)
  if a.check:
    from sun_glare import compare
    errs = compare(r, json.loads(OUT_JSON.read_text(encoding="utf-8")))
    if not errs and OUT_MD.read_text(encoding="utf-8") != md:
      errs.append(f"{OUT_MD.name} is stale")
    for e in errs[:20]:
      print("FAIL", e)
    print("wet curves:", "OK" if not errs else f"{len(errs)} difference(s)")
    return 1 if errs else 0
  OUT_JSON.write_text(json.dumps(r, indent=1) + "\n", encoding="utf-8")
  OUT_MD.write_text(md, encoding="utf-8")
  print("wrote", OUT_JSON.name, OUT_MD.name, r["need"], {k: v["wet"] for k, v in r["available"].items()})
  if a.figures:
    import fig_weather
    fig_weather.wet_curves_figures(p, r, HERE / "figures")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv))
