#!/usr/bin/env python3
"""Project Chrono pilot against the L1 plant: same cases, side by side.

Reads `../results/chrono-pilot.json` and `../results/chrono-corolla.json` (written by `chrono_pilot.py` in the PyChrono
environment), runs the matching L1 plant cases (F-04b, siren muted: the cases of `straight_drift.py` and of
`silent_stall.py` before DQ-404) and writes `../results/chrono-pilot.md` (the generic Sedan) and
`../results/chrono-corolla.md` (the vehicle of the spec, `../vehicle/specs/`, with its sweep). Runs in the plant's
Python; it does not need Chrono.

    python3 compare_l1.py            # write the comparison
    python3 compare_l1.py --check    # CI: fail if the committed comparison differs from a fresh one

Synthetic (DSR-12), no evidence credit.
"""

from __future__ import annotations

import dataclasses
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
sys.path.insert(0, str(SIM / "plant"))
sys.path.insert(0, str(SIM / "vehicle"))

import cases  # noqa: E402
import simulate  # noqa: E402
import vehicle_spec  # noqa: E402

IN_JSON = SIM / "results" / "chrono-pilot.json"
OUT_MD = SIM / "results" / "chrono-pilot.md"
IN_COROLLA = SIM / "results" / "chrono-corolla.json"
OUT_COROLLA = SIM / "results" / "chrono-corolla.md"
CURVE_ROAD = {1.5: "curve", 2.5: "curve-odd-bound"}


def l1(case: dict) -> dict:
  base = {c.id: c for c in cases.all_cases()}["F-04b"]
  if case["road"] == "straight":
    c = dataclasses.replace(base, road="straight", t_fault=6.0, duration=8.0, speed_kph=case["kph"],
                            ay_disturbance=case["push"])
  else:
    c = dataclasses.replace(base, road=CURVE_ROAD[case["a_y"]], t_fault=None, speed_kph=case["kph"])
  r = simulate.simulate(c, {"whatif_silent_panda": 1.0})
  m, ev = r.metrics, r.metrics["events"]
  first = lambda p: next((v for k, v in ev.items() if k.startswith(p)), None)  # noqa: E731
  return {"e0": r.e0, "cue": first("driver cue"), "corr": first("driver correction"), "t_line30": m["t_narrow"],
          "t_line37": m["t_line"], "max_dev": abs(m["max_dev"])}


def f(v, unit=" s"):
  return "—" if v is None else f"{v:.2f}{unit}"


def pair(a, b, unit=" s"):
  return f"{f(a, unit)} / {f(b, unit)}"


def table(data: dict) -> str:
  rows = [(c, l1(c)) for c in data["cases"]]
  lines = [
    "# Project Chrono pilot: the silent assist loss on a multibody vehicle",
    "",
    "> **Synthetic data (DSR-12).** Generated by [`chrono/compare_l1.py`](../chrono/compare_l1.py) from "
    f"[`chrono-pilot.json`](chrono-pilot.json) ([`chrono/chrono_pilot.py`](../chrono/chrono_pilot.py), Project Chrono "
    f"{data['chrono']}, BSD 3-Clause) and fresh L1 plant runs; do not edit by hand. The Chrono vehicle is "
    f"{data['vehicle']} with its own generic parameters, **not the reference Corolla**. **No evidence credit** (DQ-139).",
    "",
    "Both columns run the same scenario with the same item law, EPS lag (tau_eps 0.12 s) and driver (cue at 0.2 m of "
    "drift, correction 1.5 s later, ≤ 4 m/s²). L1 is the plant's own model: F-04b with the panda siren muted, the cases "
    "of [straight-drift.md](straight-drift.md) and of the \"before DQ-404\" rows of [silent-stall.md](silent-stall.md). "
    "In Chrono the cross slope is real (gravity tilted) and the curve is a 100 m clothoid into the arc, as in the plant. "
    "Chrono's steering is a kinematic input, so the tyres' aligning torque does not turn the wheel here either: the "
    "difference between the columns is the vehicle (tyre slip and saturation, yaw and sideslip, roll, load transfer). "
    "Each cell reads Chrono / L1; times are seconds from the loss.",
    "",
    "| Case | Offset at the loss | Driver notices the drift | Correction starts | Body on the lane line, 3.0 m lane | "
    "Body on the lane line, 3.7 m lane | Peak drift |",
    "|---|---|---|---|---|---|---|",
  ]
  for c, b in rows:
    label = (f"straight, {c['push']:.1f} m/s² cross slope, {c['kph']:.0f} km/h" if c["road"] == "straight"
             else f"curve entry, {c['a_y']:.1f} m/s², {c['kph']:.0f} km/h")
    lines.append(f"| {label} | {pair(abs(c['e0']), abs(b['e0']), ' m')} | {pair(c['cue'], b['cue'])} | "
                 f"{pair(c['corr'], b['corr'])} | {pair(c['t_line30'], b['t_line30'])} | "
                 f"{pair(c['t_line37'], b['t_line37'])} | {pair(c['max_dev'], b['max_dev'], ' m')} |")

  def line(c, b):
    return c["t_line30"], b["t_line30"]

  curves = [(c, b) for c, b in rows if c["road"] == "curve"]
  pushed = [(c, b) for c, b in rows if c["road"] == "straight" and c["push"] >= 0.2]
  calm = [c for c, _ in rows if c["road"] == "straight" and c["push"] == 0.0]
  later = sum(1 for c, b in pushed if b["cue"] is not None and (c["cue"] is None or c["cue"] > b["cue"]))
  dcurve = max(abs(x - y) for c, b in curves for x, y in (line(c, b), (c["cue"], b["cue"])) if None not in (x, y))
  lines += [
    "",
    "**What this shows** (generated from the rows above):",
    "",
    f"- Curve entry: the times agree to within {dcurve:.2f} s (driver cue and 3.0 m lane line). There the drift is the "
    "geometry of a car that stops turning, and the L1 plant gets it right; the peak drift after the correction "
    "differs, but by then the car is in the next lane and the magnitude means little.",
    f"- Straight with a cross slope: the Chrono vehicle drifts more slowly; the driver notices later in {later} of "
    f"{len(pushed)} runs with 0.2 m/s² or more. A real slope is resisted by the tyres' slip, which the L1 push, added "
    "as a lateral acceleration, is not; the L1 plant is the conservative one here. The Chrono item also holds the lane "
    "centre against the slope (an integral term), where the L1 item stands off it, so the time to the line starts "
    "from a different offset.",
    f"- With no slope at all the Chrono vehicle still drifts {min(c['max_dev'] for c in calm):.2f}–"
    f"{max(c['max_dev'] for c in calm):.2f} m in 8 s from the small heading the item leaves at the loss: the noise "
    "floor of this pilot.",
    "- The aligning torque and the hands on the wheel (the L1 caveat of straight-drift.md) stay open: Chrono's "
    "standard steering cannot show them. The L2 Modelica column (sim README §3.5) is the place for the steering "
    "side; the vehicle side is what Chrono adds, and it would need the reference Corolla's tyre and suspension "
    "parameters (WP-S-04 M-02) before it says more than a generic sedan does.",
  ]
  return "\n".join(lines) + "\n"


def label(c: dict) -> str:
  return (f"straight, {c['push']:.1f} m/s² cross slope, {c['kph']:.0f} km/h" if c["road"] == "straight"
          else f"curve entry, {c['a_y']:.1f} m/s², {c['kph']:.0f} km/h")


def key(c: dict):
  return (c["road"], c.get("push", c.get("a_y")), c["kph"])


def span(vals, unit=" s"):
  vals = [x for x in vals if x is not None]
  if not vals:
    return "—"
  lo, hi = f"{min(vals):.2f}", f"{max(vals):.2f}"
  return f"{lo}{unit}" if lo == hi else f"{lo}–{hi}{unit}"


def corolla(data: dict, sedan: dict) -> str:
  spec = vehicle_spec.load(vehicle_spec.SPECS / data["spec"])
  d = vehicle_spec.derive(vehicle_spec.values(spec))
  nom = data["nominal"]
  real = nom["cases"][0]
  sed = {key(c): c for c in sedan["cases"]}
  deg = 180 / 3.141592653589793
  lines = [
    f"# Chrono pilot on a vehicle spec: {data['vehicle']}",
    "",
    "> **Synthetic data (DSR-12).** Generated by [`chrono/compare_l1.py`](../chrono/compare_l1.py) from "
    f"[`chrono-corolla.json`](chrono-corolla.json) ([`chrono/chrono_pilot.py`](../chrono/chrono_pilot.py), Project "
    f"Chrono {data['chrono']}) and fresh L1 plant runs; do not edit by hand. The vehicle is built by "
    "[`vehicle/vehicle_spec.py`](../vehicle/vehicle_spec.py) from the spec "
    f"[`{data['spec']}`](../vehicle/specs/{data['spec']}): public data where it exists, physics or a typical value "
    "where it does not, each with its source and range. **Nothing is measured on the reference car** (WP-S-04 M-01, "
    "M-02 replace it). **No evidence credit** (DQ-139).",
    "",
    "## The spec",
    "",
    "| Parameter | Value | Range swept or stated | Status | Source |",
    "|---|---|---|---|---|",
  ]
  for n, p in spec["param"].items():
    rng = "—" if p["low"] == p["high"] else f"{p['low']:g}–{p['high']:g}"
    lines.append(f"| {n} | {p['value']:g} {p['unit']} | {rng} | {p['status']} | {p['source']} |")
  lines += [f"| *front suspension* | MacPherson strut | | published | {spec['note']['front_suspension']} |",
            f"| *rear suspension* | multi-link | | published | {spec['note']['rear_suspension']} |", ""]
  lines += [
    "## Derived, and what the assembled Chrono vehicle has",
    "",
    "| Quantity | Derived from the spec | Assembled in Chrono | How |",
    "|---|---|---|---|",
    f"| total mass | {d['mass']:.1f} kg | {real['realised_mass']:.1f} kg | curb + load; the chassis mass is calibrated "
    "against the assembled vehicle |",
    f"| CoG to front axle a | {d['a']:.3f} m | {real['realised_a']:.3f} m | (1 − front weight fraction) × wheelbase |",
    f"| CoG height | {d['cg_height']:.3f} m | {real['realised_cg_height']:.3f} m | spec value; chassis CoG calibrated |",
    f"| yaw inertia I_zz | {d['izz']:.0f} kg m² | (chassis) | k m a b (Garrott et al., SAE 881767) |",
    f"| roll, pitch inertia | {d['ixx']:.0f}, {d['iyy']:.0f} kg m² | (chassis) | m r_x²; ratio × I_zz |",
    f"| tyre radius | {d['tire_radius']:.4f} m | (tyre file) | rim/2 + width × aspect (205/55R16) |",
    f"| steering lock, outer / inner wheel | {d['delta_max_outer'] * deg:.1f}° / {d['delta_max_inner'] * deg:.1f}° | "
    "the Chrono sedan's rack | Ackermann on the turning circle; Chrono keeps the sedan's rack (no effect at these angles) |",
    f"| openpilot axle cornering stiffness, front / rear | {d['op_cf'] / 1000:.1f} / {d['op_cr'] / 1000:.1f} kN/rad | "
    "TMeasy from the load index | opendbc scale_tire_stiffness with tireStiffnessFactor (fleet-fitted) |",
    "",
    "**Cross-check of the tyre and suspension model: the understeer gradient.** Chrono measures it from the front-wheel "
    "angle in two steady turns (1.0 and 2.0 m/s² at 110 km/h, the kinematic part taken out); openpilot's comes from its "
    "fleet-fitted axle stiffness in the single-track model, so it also carries the steering's compliance.",
    "",
    "| | Understeer gradient |",
    "|---|---|",
    f"| Chrono, this spec | {nom['understeer'] * deg:.3f} °/(m/s²) |",
    f"| Chrono, this spec, over the sweep | {span([x['understeer'] * deg for x in data['sweep']], ' °/(m/s²)')} |",
    f"| openpilot single-track model (opendbc) | {d['op_understeer'] * deg:.3f} °/(m/s²) |",
    "",
    "## The cases: this spec, the generic Sedan and the L1 plant",
    "",
    "Times are seconds from the loss. Each cell reads spec / Sedan / L1.",
    "",
    "| Case | Driver notices the drift | Correction starts | Body on the lane line, 3.0 m lane | Body on the lane line, "
    "3.7 m lane | Peak drift |",
    "|---|---|---|---|---|---|",
  ]

  def tri(a, b, c, unit=" s"):
    return f"{f(a, unit)} / {f(b, unit)} / {f(c, unit)}"

  for c in nom["cases"]:
    s_, l_ = sed[key(c)], l1(c)
    lines.append(f"| {label(c)} | {tri(c['cue'], s_['cue'], l_['cue'])} | {tri(c['corr'], s_['corr'], l_['corr'])} | "
                 f"{tri(c['t_line30'], s_['t_line30'], l_['t_line30'])} | {tri(c['t_line37'], s_['t_line37'], l_['t_line37'])} | "
                 f"{tri(c['max_dev'], s_['max_dev'], l_['max_dev'], ' m')} |")
  lines += [
    "",
    "## The sweep: one parameter at a time to each end of its range",
    "",
    "The others stay at their values; interactions are not tested. Each cell: driver cue / body on the 3.0 m lane "
    "line, seconds from the loss.",
    "",
    "| Parameter | End | Value | " + " | ".join(label({"road": r, "push": x, "a_y": x, "kph": k}) for r, x, k in
                                            [(c["road"], c.get("push", c.get("a_y")), c["kph"]) for c in data["sweep"][0]["cases"]]) +
    " | Understeer |",
    "|---|---|---|" + "---|" * len(data["sweep"][0]["cases"]) + "---|",
  ]
  nomc = {key(c): c for c in nom["cases"]}
  lines.append("| (nominal) | | | " + " | ".join(
    f"{f(nomc[key(c)]['cue'])} / {f(nomc[key(c)]['t_line30'])}" for c in data["sweep"][0]["cases"]) +
    f" | {nom['understeer'] * deg:.3f}° |")
  for x in data["sweep"]:
    lines.append(f"| {x['param']} | {x['end']} | {x['value']:g} | " + " | ".join(
      f"{f(c['cue'])} / {f(c['t_line30'])}" for c in x["cases"]) + f" | {x['understeer'] * deg:.3f}° |")

  def spread(road, a_val, field):
    vals = [c[field] for x in data["sweep"] for c in x["cases"] if key(c)[0] == road and key(c)[1] == a_val]
    vals += [nomc[k][field] for k in nomc if k[0] == road and k[1] == a_val and k[2] == 110.0]
    return [v for v in vals if v is not None]

  cl = {a: spread("curve", a, "t_line30") for a in (1.5, 2.5)}
  st = spread("straight", 0.2, "cue")
  l1c = {a: l1({"road": "curve", "a_y": a, "kph": 110.0})["t_line30"] for a in (1.5, 2.5)}
  inside = [x for x in data["sweep"] if x["understeer"] >= d["op_understeer"]]
  lines += [
    "",
    "**What this shows** (generated from the rows above):",
    "",
    f"- Curve entry: over the whole sweep the 3.0 m lane line comes at {span(cl[1.5])} (1.5 m/s²) and "
    f"{span(cl[2.5])} (ODD bound), against {f(l1c[1.5])} and {f(l1c[2.5])} in the L1 plant: the plant's curve "
    "results hold at every end of the sweep (one parameter at a time; combinations are not run).",
    f"- Straight with a 0.2 m/s² cross slope: the driver notices the drift at {span(st)} over the sweep, against "
    f"{f(l1({'road': 'straight', 'push': 0.2, 'kph': 110.0})['cue'])} in the L1 plant, which stays the conservative one.",
    f"- Understeer: this spec gives {nom['understeer'] * deg:.3f} °/(m/s²) against openpilot's "
    f"{d['op_understeer'] * deg:.3f}; {len(inside)} of {len(data['sweep'])} sweep ends reach openpilot's value "
    f"({', '.join(sorted({x['param'] + ' ' + x['end'] for x in inside})) or 'none'}). Part of the gap is expected: "
    "openpilot's figure is a lumped fit that also carries the steering's compliance. The rest measures what the "
    "estimated tyre and the generic suspension geometry miss; M-02 decides.",
    "- To add a car: write a spec file with its sources and ranges; the builder, the runner and this page take it "
    "as it is.",
  ]
  return "\n".join(lines) + "\n"


def build() -> dict[Path, str]:
  sedan = json.loads(IN_JSON.read_text(encoding="utf-8"))
  out = {OUT_MD: table(sedan)}
  if IN_COROLLA.exists():
    out[OUT_COROLLA] = corolla(json.loads(IN_COROLLA.read_text(encoding="utf-8")), sedan)
  return out


def main(argv: list[str]) -> int:
  out = build()
  if "--check" in argv:
    stale = [p for p, c in out.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
    for p in stale:
      print(f"stale: {p.relative_to(SIM.parent)}", file=sys.stderr)
    if not stale:
      print(f"compare_l1: {len(out)} file(s) current")
    return 1 if stale else 0
  for p, c in out.items():
    p.write_text(c, encoding="utf-8")
  print(f"wrote {len(out)} file(s)")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
