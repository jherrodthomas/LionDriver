"""Gallery of the hazardous-event dashboards (assurance/sim/blender).

Copies each scene's decisive dashboard (out/<scene>/dashboard.png from compose.py) to dashboards/<scene>.jpg at
1600 px and writes dashboards/README.md: one row per scene with the entry it pictures, the motion source, the
outcome and the image. Renders of the purchased mesh may be published (assets/README.md); the .blend files may not
and stay in out/.

  python3 assurance/sim/blender/gallery.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from PIL import Image

import export_scene

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
GAL = HERE / "dashboards"


def outcome(sc: dict) -> str:
  c = sc.get("contact")
  if c:
    return f"**contact** with the {c['who']} at {c['t']:+.2f} s, {c['rel_kph']:.0f} km/h"
  if sc.get("gap"):
    ttcs = [v for v in sc["ttc"] if v < 20]
    return f"no contact; minimum gap {min(sc['gap']):.1f} m" + (f", minimum TTC {min(ttcs):.2f} s" if ttcs else "")
  line = next((e for e in sc["events"] if e["label"] == "body reaches the lane line"), None)
  peak = max(abs(v) for v in sc["lateral"])
  return (f"body at the lane line at {line['t']:+.2f} s; " if line else "stays in lane; ") + f"peak offset {peak:.2f} m"


def main() -> int:
  GAL.mkdir(exist_ok=True)
  rows, variants, missing = [], [], []
  for s in export_scene.load_scenes():
    sid = s["id"]
    src = OUT / sid / "dashboard.png"
    if not src.exists():
      missing.append(sid)
      continue
    sc = json.loads((OUT / sid / "scene.json").read_text())
    im = Image.open(src).convert("RGB")
    im.resize((1600, 900), Image.LANCZOS).save(GAL / f"{sid}.jpg", quality=75, optimize=True)
    cd = sc["card"]
    entry = f"{cd['id']} ({'ASIL ' + cd['badge'].split('ASIL ')[1] if 'ASIL' in cd['badge'] else 'SOTIF'})"
    motion = f"plant {sc['case']['id']}" if sc["motion"] == "plant" else "kinematic"
    c = sc.get("condition") or {}
    cond = f"{c.get('code', '—')}" + (f" ({c['exposure']})" if c.get("exposure") else "")
    if sc.get("variant_of"):
      variants.append(f"| [{sid}]({sid}.jpg) | {c['code']}: {c['title']} | {c['hara']} |")
      continue
    where = (sc.get("environment") or {}).get("id", sc["road"]["type"])
    rows.append(f"| [{sid}]({sid}.jpg) | {entry} | {cd['effect']} | {where}, {cond} | {motion} | {outcome(sc)} |")
  head = ("# Hazardous-event dashboards\n\n"
          "Generated by [`../gallery.py`](../gallery.py) from the renders of [`../hazard_scene.py`](../hazard_scene.py) "
          "and [`../compose.py`](../compose.py); the scenes are defined in [`../scenes.yaml`](../scenes.yaml) and "
          "explained in [`../README.md`](../README.md). Synthetic (DSR-12): **pictures only, no evidence credit**. "
          "Plant scenes run the real panda safety code under the plant's stated assumptions; kinematic scenes use the "
          "plant's driver assumptions and WP-S-04 §3 values. Contact is not modelled by either: the outcome column "
          "reports the first overlap of the body outlines and the relative speed there. Each scene is an environment, "
          "a condition and traffic from [`../library/`](../library/README.md).\n\n"
          "| Scene | Entry | Effect (HARA / WP-C-05) | Environment, condition | Motion | Outcome in the scene |\n"
          "|---|---|---|---|---|---|\n")
  clips = sorted((GAL / "clips").glob("*.mp4")) if (GAL / "clips").exists() else []
  tail = ""
  if clips:
    tail = ("\n## Clips\n\nThe whole scene with the dashboard running, 24 fps (`hazard_scene.py --video`, "
            "`compose.py --video`):\n\n" + "\n".join(f"- [{c.stem}](clips/{c.name})" for c in clips) + "\n")
  if variants:
    tail = ("\n## The same events under other conditions\n\nVariants re-render a scene under another weather or "
            "lighting code it is rated for (`variants:` in scenes.yaml). The motion and the outcome are the base "
            "scene's: the plant's tyre model has no friction limit and the kinematic scenes use the stated "
            "accelerations, so a condition changes the picture, not the dynamics. The last column is what the HARA "
            "model changes for the condition.\n\n| Scene | Condition | HARA under this condition |\n|---|---|---|\n"
            + "\n".join(variants) + "\n" + tail)
  (GAL / "README.md").write_text(head + "\n".join(rows) + "\n" + tail)
  print(f"{len(rows)} dashboards in {GAL}" + (f"; not rendered yet: {', '.join(missing)}" if missing else ""))
  return 0


if __name__ == "__main__":
  sys.exit(main())
