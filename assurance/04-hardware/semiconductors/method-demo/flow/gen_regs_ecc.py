#!/usr/bin/env python3
"""Generate a SECDED (Hamming 39,32) register file for PicoRV32's PICORV32_REGS hook.

Stored word: bits [31:0] = data, bits [37:32] = Hamming check bits p1,p2,p4,p8,p16,p32, bit [38] = overall parity.
Reads correct any single-bit error (corr=1) and flag any double-bit error (err=1). No write-back scrubbing.
"""
# Hamming positions 1..38: powers of two are check bits, the rest carry data bits 0..31 in order
pos_of_data, k = {}, 0
for p in range(1, 39):
  if p & (p - 1):
    pos_of_data[k] = p
    k += 1
assert k == 32
CHK = [1, 2, 4, 8, 16, 32]
pos_bit = {pos_of_data[d]: f"[{d}]" for d in range(32)}
pos_bit.update({c: f"[{32 + i}]" for i, c in enumerate(CHK)})


def x(terms):
  return " ^ ".join(terms) if terms else "1'b0"


L = ["// generated by gen_regs_ecc.py: SECDED register file for PicoRV32 (36 entries: x0-x31 and q0-q3)",
     "module picorv32_regs_ecc (",
     "  input clk, wen,", "  input [5:0] waddr, raddr1, raddr2,", "  input [31:0] wdata,",
     "  output [31:0] rdata1, rdata2,", "  output corr, err", ");",
     "  reg [38:0] regs [0:35];", "  wire [38:0] wcode;", "  assign wcode[31:0] = wdata;"]
for i, c in enumerate(CHK):
  L.append(f"  assign wcode[{32 + i}] = {x([f'wdata[{d}]' for d in range(32) if pos_of_data[d] & c])};")
L.append(f"  assign wcode[38] = {x([f'wcode[{b}]' for b in range(38)])};")
L.append("  always @(posedge clk) if (wen) regs[waddr] <= wcode;")
for port in (1, 2):
  r = f"r{port}"
  L.append(f"  wire [38:0] {r} = regs[raddr{port}];")
  L.append(f"  wire [5:0] s{port};")
  for i, c in enumerate(CHK):
    terms = [f"{r}{pos_bit[p]}" for p in range(1, 39) if p & c]
    L.append(f"  assign s{port}[{i}] = {x(terms)};")
  L.append(f"  wire o{port} = {x([f'{r}[{b}]' for b in range(39)])};")
  for d in range(32):
    L.append(f"  assign rdata{port}[{d}] = {r}[{d}] ^ (o{port} && s{port} == 6'd{pos_of_data[d]});")
  L.append(f"  wire c{port} = o{port};")
  L.append(f"  wire e{port} = !o{port} && (s{port} != 6'd0);")
L.append("  assign corr = c1 | c2;")
L.append("  assign err = e1 | e2;")
L.append("endmodule")
open("picorv32_regs_ecc.v", "w").write("\n".join(L) + "\n")
print("ok", len(L), "lines")
