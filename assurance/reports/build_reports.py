#!/usr/bin/env python3
"""Generate LionDriver's LaTeX reports from the records, check them, and build the PDFs.

The records (Markdown work products, YAML) stay the source of record. Each report is a rendering of one of them:
build_reports.py writes its .tex and a numbers.tex of macros for every number the prose uses, so the text cannot
fall out of step with the record. The generated .tex is committed and checked; the PDF is built in CI and kept as a
build artifact, never committed.

Reports so far:
  fsc   WP-C-04 Functional safety concept: safety goals, the FSRs per goal, FTTI allocation, the allocation and
        degradation figures, abbreviations from the project's terms list, bibliography

    python3 build_reports.py               # write every report's .tex
    python3 build_reports.py --check       # fail if a record changed shape or a generated .tex is stale
    python3 build_reports.py --pdf DIR     # also build the PDFs into DIR (needs pdflatex and rsvg-convert)

The build fails when a table it reads loses or renames a column, a section it reads is missing, the text holds a
character LaTeX cannot set, or a cited reference is not in references.yaml. Standard library and PyYAML.
"""
from __future__ import annotations

import datetime
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ASSURANCE = HERE.parent
REPO = ASSURANCE.parent
sys.path.insert(0, str(ASSURANCE / "trace" / "tools"))
import terms  # noqa: E402

STYLE = HERE / "latex" / "liondriver-report.sty"
REFS = HERE / "references.yaml"
HEADER = "% GENERATED by assurance/reports/build_reports.py from the records; do not edit.\n"


class ReportError(ValueError):
  pass


# ---------------------------------------------------------------- Markdown to LaTeX

MATH = {"≤": r"$\le$", "≥": r"$\ge$", "→": r"$\to$", "←": r"$\leftarrow$", "↔": r"$\leftrightarrow$", "≈": r"$\approx$",
        "≠": r"$\ne$", "±": r"$\pm$", "×": r"$\times$", "·": r"$\cdot$", "τ": r"$\tau$", "Δ": r"$\Delta$", "µ": r"$\mu$",
        "Ω": r"$\Omega$", "²": r"$^2$", "³": r"$^3$", "‡": r"\dagr{}", "⚠": r"\warn{}", "…": r"\ldots{}",
        "°": r"\textdegree{}", "✓": r"$\checkmark$"}
PLAIN = set("–—‘’“”§éèüöäÉ ")   # set directly by T1 with utf8 input
SPECIAL = (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
           ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"))


def tex(s: str, where: str = "") -> str:
  """One Markdown cell or line as LaTeX: links to their text, bold and code kept, specials escaped."""
  s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)
  out = []
  for part in re.split(r"(`[^`]*`|\*\*[^*]+\*\*)", s):
    kind = "code" if part.startswith("`") else "bold" if part.startswith("**") else ""
    if kind:
      part = part.strip("`") if kind == "code" else part[2:-2]
    for a, b in SPECIAL:
      part = part.replace(a, b)
    res = []
    for ch in part:
      if ch in MATH:
        res.append(MATH[ch])
      elif ord(ch) < 128 or ch in PLAIN:
        res.append(ch)
      else:
        raise ReportError(f"{where}: character {ch!r} (U+{ord(ch):04X}) has no LaTeX mapping; add it to MATH")
    part = "".join(res)
    out.append(r"\texttt{" + part + "}" if kind == "code" else r"\textbf{" + part + "}" if kind == "bold" else part)
  return "".join(out)


def section(md: str, heading: str) -> str:
  m = re.search(rf"^{re.escape(heading)}.*$", md, re.M)
  if not m:
    raise ReportError(f"section not found: {heading}")
  level = len(heading) - len(heading.lstrip("#"))
  rest = md[m.end():]
  end = re.search(rf"^#{{1,{level}}} ", rest, re.M)
  return rest[:end.start()] if end else rest


def md_table(body: str, columns: list[str], where: str) -> list[dict]:
  """The first table in body whose header is exactly `columns`, as rows keyed by column."""
  lines = body.splitlines()
  for i, ln in enumerate(lines):
    if ln.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s\-:|]+\|$", lines[i + 1]):
      head = [c.strip() for c in ln.strip()[1:-1].split("|")]
      if head != columns:
        continue
      rows = []
      for r in lines[i + 2:]:
        if not r.startswith("|"):
          break
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", r.strip())[1:-1]]
        if len(cells) != len(columns):
          raise ReportError(f"{where}: row {cells[:1]} has {len(cells)} cells, expected {len(columns)}")
        rows.append(dict(zip(columns, cells)))
      return rows
  raise ReportError(f"{where}: no table with columns {columns}")


def longtable(spec: str, heads: list[str], rows: list[list[str]], caption: str, label: str, small: bool = True) -> str:
  head = " & ".join(rf"\textbf{{{h}}}" for h in heads) + r" \\ \midrule"
  body = "\n".join(" & ".join(r) + r" \\ \midrule" for r in rows)
  out = (rf"\begin{{longtable}}{{@{{}}{spec}@{{}}}}" + "\n" + rf"\caption{{{caption}}}\label{{{label}}}\\" + "\n"
         + r"\toprule " + head + r"\endfirsthead" + "\n" + r"\toprule " + head + r"\endhead" + "\n" + body + "\n"
         + r"\bottomrule" + "\n" + r"\end{longtable}")
  return ("{\\small\n" + out + "\n}") if small else out


# ---------------------------------------------------------------- shared parts

def version_of(md: str, where: str) -> tuple[str, str]:
  """(version, date) of the newest Version-row entry."""
  m = re.search(r"^\| Version \| ([\d.]+) \((.*?)\)\.", md, re.M)
  if not m:
    raise ReportError(f"{where}: no Version row")
  d = re.findall(r"\d{4}-\d{2}-\d{2}", m.group(2))
  return m.group(1), (d[-1] if d else "")


def abbreviations(body: str) -> str:
  plain = re.sub(r"\\[a-zA-Z]+\{?|[{}$\\]", " ", body)
  used, _ = terms.find(plain)
  items = "\n".join(rf"\item[{tex(terms.label(k))}] {tex(terms.TERMS[k], k)}"
                    for k in sorted(used, key=lambda k: terms.label(k).lower()))
  return ("\\chapter{Abbreviations}\nWritten from the project's single list of terms (\\texttt{terms.py}), with only "
          "the terms this report uses.\n\\begin{description}\\small\n" + items + "\n\\end{description}\n")


def bibliography(body: str) -> str:
  refs = {r["key"]: r["text"] for r in yaml.safe_load(REFS.read_text(encoding="utf-8"))}
  cited = []
  for group in re.findall(r"\\cite\{([^}]*)\}", body):
    for k in group.split(","):
      k = k.strip()
      if k not in refs:
        raise ReportError(f"cited reference {k!r} is not in references.yaml")
      if k not in cited:
        cited.append(k)
  items = "\n".join(rf"\bibitem{{{k}}} {tex(refs[k], k)}" for k in cited)
  return "\\begin{thebibliography}{9}\n" + items + "\n\\end{thebibliography}\n"


def numbers_tex(numbers: dict) -> str:
  return HEADER + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in numbers.items())


# ---------------------------------------------------------------- the FSC report

FSC_MD = ASSURANCE / "02-concept" / "WP-C-04-functional-safety-concept.md"
FSC_FIG = ASSURANCE / "02-concept" / "fsc" / "figures"
GOAL_COLS = ["SG", "Statement (short)", "ASIL", "Safe state", "Preliminary FTTI"]
FSR_COLS = ["ID", "Requirement", "ASIL", "Alloc", "Verif"]
FTTI_COLS = ["SG", "FTTI (prelim.)", "Detection budget", "Reaction budget", "Current behaviour", "Gap"]


def fsc() -> tuple[dict[str, str], list[Path]]:
  md = FSC_MD.read_text(encoding="utf-8")
  where = "WP-C-04"
  version, date = version_of(md, where)
  goals = md_table(section(md, "## 3. Safety goals"), GOAL_COLS, f"{where} §3")
  s5 = section(md, "## 5. Functional safety requirements")
  blocks = re.split(r"^### (5\.\d+ .*)$", s5, flags=re.M)
  per_goal = []
  for title, body in zip(blocks[1::2], blocks[2::2]):
    lines = body.splitlines()
    i = next((k for k, ln in enumerate(lines) if ln.startswith("| ID | Requirement")), None)
    if i is None:
      raise ReportError(f"{where} §{title}: no FSR table")
    cols = [c.strip() for c in lines[i].strip()[1:-1].split("|")]
    if cols[:5] != FSR_COLS:
      raise ReportError(f"{where} §{title}: FSR table columns {cols} do not start with {FSR_COLS}")
    rows = md_table(body, cols, f"{where} §{title}")
    per_goal.append((title, rows))
  if len(per_goal) != len(goals):
    raise ReportError(f"{where}: {len(goals)} safety goals in §3 but {len(per_goal)} FSR sections in §5")
  ftti = md_table(section(md, "## 8. FTTI allocation"), FTTI_COLS, f"{where} §8")
  fsrs = [r for _, rows in per_goal for r in rows]
  cat: dict[str, int] = {}
  for r in fsrs:
    first = r["ASIL"].split()[0] if r["ASIL"] else "?"
    key = {"—": "Ext", "as": "Ref"}.get(first, first)
    cat[key] = cat.get(key, 0) + 1
  known = {"A", "B", "C", "D", "QM", "Ext", "Ref"}
  if set(cat) - known:
    raise ReportError(f"{where}: FSR ASIL values {sorted(set(cat) - known)} are not handled")
  numbers = {"FscVersion": version, "FscDate": date, "GoalCount": len(goals), "FsrCount": len(fsrs),
             "FsrAsilD": cat.get("D", 0), "FsrAsilC": cat.get("C", 0), "FsrAsilB": cat.get("B", 0),
             "FsrAsilA": cat.get("A", 0), "FsrQM": cat.get("QM", 0), "FsrExt": cat.get("Ext", 0),
             "FsrRef": cat.get("Ref", 0)}

  body = [r"\chapter{Introduction}",
          r"This report renders the functional safety concept of LionDriver (work product WP-C-04, version "
          r"\FscVersion{} of \FscDate{}) from its source of record, as ISO 26262-3 asks of the concept phase "
          r"\cite{iso26262-3}. It derives \FsrCount{} functional safety requirements (FSRs) from \GoalCount{} safety "
          r"goals: \FsrAsilC{} at ASIL~C, \FsrAsilB{} at ASIL~B, \FsrAsilA{} at ASIL~A and \FsrQM{} at QM, with "
          r"\FsrExt{} external measures outside the item and \FsrRef{} cross-reference to other FSRs.",
          "",
          r"Every number in this report is a macro written from the record (\texttt{numbers.tex}), and every table is "
          r"read from it, so the report cannot fall out of step with the analysis: when the record changes, the "
          r"build fails until the report is regenerated. The record is a draft, AI-assisted (independence I0) and "
          r"not reviewed; so is this report.",
          r"\chapter{Safety goals}",
          r"Table~\ref{tab:goals} summarises the safety goals of the hazard analysis (WP-C-03) that the concept "
          r"refines. A \warn{} marks an ASIL that rises if an assumption of use fails.",
          longtable(r"p{1.2cm}p{4.3cm}p{2.3cm}p{3.6cm}p{2.9cm}", ["SG", "Statement", "ASIL", "Safe state", "FTTI"],
                    [[tex(g[c], f"{where} §3") for c in GOAL_COLS] for g in goals],
                    r"Safety goals with their ASIL, safe state and preliminary FTTI (WP-C-04 \S3).", "tab:goals"),
          r"\chapter{Functional safety requirements}",
          r"Figure~\ref{fig:alloc} shows every safety goal with the FSRs that refine it; the sections below list "
          r"them goal by goal, with their ASIL, the element they are allocated to and how they are verified. The "
          r"implementation status of each FSR is kept in the record (WP-C-04 \S5).",
          r"\begin{landscape}\begin{figure}[p]\centering",
          r"\includegraphics[width=\linewidth,height=0.88\textheight,keepaspectratio]{fig-c04-5-1-sg-fsr-allocation.pdf}",
          r"\caption{Safety goals and their FSRs (WP-C-04 Figure 5-1).}\label{fig:alloc}",
          r"\end{figure}\end{landscape}"]
  for title, rows in per_goal:
    num, name = title.split(" ", 1)
    body.append(rf"\section{{{tex(name, where)}}}")
    body.append(longtable(r"p{1.7cm}p{7.4cm}p{1.1cm}p{1.8cm}p{2.3cm}", ["ID", "Requirement", "ASIL", "Alloc.", "Verification"],
                          [[tex(r[c], f"{where} §{num}") for c in FSR_COLS] for r in rows],
                          rf"FSRs of {tex(name.split(' ')[0], where)} (WP-C-04 \S{num}).", f"tab:fsr-{num}"))
  body += [r"\chapter{FTTI allocation}",
           r"Table~\ref{tab:ftti} splits each preliminary fault-tolerant time interval into a detection and a "
           r"reaction budget for the technical safety requirements to meet. The behaviour today is kept in the "
           r"record (WP-C-04 \S8).",
           longtable(r"p{3.6cm}p{2.5cm}p{2.9cm}p{2.9cm}p{2.4cm}",
                     ["Goal and case", "FTTI", "Detection", "Reaction", "Gap"],
                     [[tex(r[c], f"{where} §8") for c in ("SG", "FTTI (prelim.)", "Detection budget", "Reaction budget",
                                                          "Gap")] for r in ftti],
                     r"FTTI allocation (WP-C-04 \S8, preliminary).", "tab:ftti"),
           r"\chapter{Warning and degradation}",
           r"Figure~\ref{fig:ladder} shows the degradation levels from full function to lockout, what the driver is "
           r"told at each, and the safe states they end in.",
           r"\begin{figure}[htbp]\centering",
           r"\includegraphics[width=\linewidth,height=0.8\textheight,keepaspectratio]{fig-c04-12-1-degradation-ladder.pdf}",
           r"\caption{The degradation ladder (WP-C-04 Figure 12-1).}\label{fig:ladder}",
           r"\end{figure}"]
  main = "\n".join(body) + "\n"
  doc = (HEADER + r"\documentclass[11pt,a4paper]{report}" + "\n" + r"\usepackage{../latex/liondriver-report}" + "\n"
         + r"\input{numbers.tex}" + "\n" + r"\LDsetdoc{WP-C-04 Functional Safety Concept}{\FscVersion}" + "\n"
         + r"\title{Functional Safety Concept\\[4pt]\large WP-C-04, version \FscVersion}" + "\n"
         + r"\author{LionDriver assurance\\\small generated from \texttt{assurance/02-concept/WP-C-04-functional-safety-concept.md}}"
         + "\n" + r"\date{\FscDate}" + "\n" + r"\begin{document}" + "\n" + r"\maketitle" + "\n" + r"\tableofcontents"
         + "\n" + main + r"\appendix" + "\n" + abbreviations(main) + bibliography(main) + r"\end{document}" + "\n")
  return ({"fsc/fsc.tex": doc, "fsc/numbers.tex": numbers_tex(numbers)},
          [FSC_FIG / "fig-c04-5-1-sg-fsr-allocation.svg", FSC_FIG / "fig-c04-12-1-degradation-ladder.svg"])


REPORTS = {"fsc": fsc}


# ---------------------------------------------------------------- build

def build_all() -> dict[str, tuple[dict[str, str], list[Path]]]:
  return {name: fn() for name, fn in REPORTS.items()}


def pdf(name: str, files: dict[str, str], figures: list[Path], out: Path) -> Path:
  """Build one report's PDF in out/<name>/ from the generated sources. Fails on a LaTeX error or an undefined
  reference."""
  work = out / name
  if work.exists():
    shutil.rmtree(work)
  (out / "latex").mkdir(parents=True, exist_ok=True)
  shutil.copy(STYLE, out / "latex" / STYLE.name)
  work.mkdir(parents=True)
  for rel, content in files.items():
    (out / rel).write_text(content, encoding="utf-8")
  version_date = re.search(r"\\newcommand\{\\\w+Date\}\{([\d-]+)\}", files[f"{name}/numbers.tex"])
  epoch = int(datetime.datetime.fromisoformat(version_date.group(1)).replace(tzinfo=datetime.timezone.utc).timestamp()
              if version_date else 0)
  env = {**os.environ, "SOURCE_DATE_EPOCH": str(epoch), "FORCE_SOURCE_DATE": "1"}
  for svg in figures:
    subprocess.run(["rsvg-convert", "-f", "pdf", "-o", str(work / (svg.stem + ".pdf")), str(svg)], check=True, env=env)
  tex_file = f"{name}.tex"
  for _ in range(2):
    r = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex_file], cwd=work, env=env,
                       capture_output=True, text=True)
    if r.returncode:
      tail = "\n".join(ln for ln in r.stdout.splitlines() if ln.startswith("!") or ln.startswith("l."))
      raise ReportError(f"{name}: pdflatex failed\n{tail}")
  log = (work / f"{name}.log").read_text(encoding="utf-8", errors="replace")
  if re.search(r"undefined (references|citations)|Reference .* undefined|Citation .* undefined", log):
    raise ReportError(f"{name}: undefined references or citations after two passes")
  return work / f"{name}.pdf"


def main(argv: list[str]) -> int:
  try:
    reports = build_all()
  except ReportError as e:
    print(f"build_reports: {e}", file=sys.stderr)
    return 1
  stale = []
  for name, (files, _) in reports.items():
    for rel, content in files.items():
      p = HERE / rel
      if "--check" in argv:
        if not p.exists() or p.read_text(encoding="utf-8") != content:
          stale.append(rel)
      else:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
  if stale:
    print(f"build_reports: stale {', '.join(stale)}; run python3 assurance/reports/build_reports.py", file=sys.stderr)
    return 1
  if "--pdf" in argv:
    out = Path(argv[argv.index("--pdf") + 1]).resolve()
    for name, (files, figures) in reports.items():
      try:
        p = pdf(name, files, figures, out)
      except (ReportError, subprocess.CalledProcessError) as e:
        print(f"build_reports: {e}", file=sys.stderr)
        return 1
      print(f"build_reports: built {p}")
  print("build_reports: " + ("up to date" if "--check" in argv else "wrote " + ", ".join(
    rel for files, _ in reports.values() for rel in files)))
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
