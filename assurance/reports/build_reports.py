# ---------------------------------------------------------------- Markdown to LaTeX

MATH = {"≤": r"$\le$", "≥": r"$\ge$", "→": r"$\to$", "←": r"$\leftarrow$", "↔": r"$\leftrightarrow$", "≈": r"$\approx$",
        "≠": r"$\ne$", "±": r"$\pm$", "×": r"$\times$", "·": r"$\cdot$", "τ": r"$\tau$", "Δ": r"$\Delta$", "µ": r"$\mu$",
        "Ω": r"$\Omega$", "²": r"$^2$", "³": r"$^3$", "⁹": r"$^9$", "⁻": r"$^{-}$", "λ": r"$\lambda$", "‡": r"\dagr{}", "⚠": r"\warn{}", "…": r"\ldots{}",
        "°": r"\textdegree{}", "✓": r"$\checkmark$"}
PLAIN = set("–—‘’“”§éèüöäÉ ")   # set directly by T1 with utf8 input
SPECIAL = (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
           ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"))


def tex(s: str, where: str = "") -> str:
  """One Markdown cell or line as LaTeX: links to their text, bold and code kept, specials escaped."""
  s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)
  out = []
  for part in re.split(r"(`[^`]*`|\*\*[^*]+\*\*)", s):
    kind = "code" if part.startswith("`") else "bold" if part.startswith("**") else ""
    if kind:
      part = part.strip("`") if kind == "code" else part[2:-2]
    for a, b in SPECIAL:
      part = part.replace(a, b)
    res = []
    for ch in part:
      if ch in MATH:
        res.append(MATH[ch])
      elif ord(ch) < 128 or ch in PLAIN:
        res.append(ch)
      else:
        raise ReportError(f"{where}: character {ch!r} (U+{ord(ch):04X}) has no LaTeX mapping; add it to MATH")
    part = "".join(res)
    out.append(r"\texttt{" + part + "}" if kind == "code" else r"\textbf{" + part + "}" if kind == "bold" else part)
  return "".join(out)


def section(md: str, heading: str) -> str:
  m = re.search(rf"^{re.escape(heading)}.*$", md, re.M)
  if not m:
    raise ReportError(f"section not found: {heading}")
  level = len(heading) - len(heading.lstrip("#"))
  rest = md[m.end():]
  end = re.search(rf"^#{{1,{level}}} ", rest, re.M)
  return rest[:end.start()] if end else rest


def md_table(body: str, columns: list[str], where: str) -> list[dict]:
  """The first table in body whose header is exactly `columns`, as rows keyed by column."""
  lines = body.splitlines()
  for i, ln in enumerate(lines):
    if ln.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s\-:|]+\|$", lines[i + 1]):
      head = [c.strip() for c in ln.strip()[1:-1].split("|")]
      if head != columns:
        continue
      rows = []
      for r in lines[i + 2:]:
        if not r.startswith("|"):
          break
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", r.strip())[1:-1]]
        if len(cells) != len(columns):
          raise ReportError(f"{where}: row {cells[:1]} has {len(cells)} cells, expected {len(columns)}")
        rows.append(dict(zip(columns, cells)))
      return rows
  raise ReportError(f"{where}: no table with columns {columns}")


def longtable(spec: str, heads: list[str], rows: list[list[str]], caption: str, label: str, small: bool = True) -> str:
  head = " & ".join(rf"\textbf{{{h}}}" for h in heads) + r" \\ \midrule"
  body = "\n".join(" & ".join(r) + r" \\ \midrule" for r in rows)
  out = (rf"\begin{{longtable}}{{@{{}}{spec}@{{}}}}" + "\n" + rf"\caption{{{caption}}}\label{{{label}}}\\" + "\n"
         + r"\toprule " + head + r"\endfirsthead" + "\n" + r"\toprule " + head + r"\endhead" + "\n" + body + "\n"
         + r"\bottomrule" + "\n" + r"\end{longtable}")
  return ("{\\small\n" + out + "\n}") if small else out


# ---------------------------------------------------------------- shared parts

def version_of(md: str, where: str) -> tuple[str, str]:
  """(version, date) of the newest Version-row entry."""
  m = re.search(r"^\| Version \| ([\d.]+) \((.*?)\)\.", md, re.M)
  if not m:
    raise ReportError(f"{where}: no Version row")
  d = re.findall(r"\d{4}-\d{2}-\d{2}", m.group(2))
  return m.group(1), (d[-1] if d else "")


def abbreviations(body: str) -> str:
  plain = re.sub(r"\\[a-zA-Z]+\{?|[{}$\\]", " ", body)
  used, _ = terms.find(plain)
  items = "\n".join(rf"\item[{tex(terms.label(k))}] {tex(terms.TERMS[k], k)}"
                    for k in sorted(used, key=lambda k: terms.label(k).lower()))
  return ("\\chapter{Abbreviations}\nWritten from the project's single list of terms (\\texttt{terms.py}), with only "
          "the terms this report uses.\n\\begin{description}\\small\n" + items + "\n\\end{description}\n")


def bibliography(body: str) -> str:
  refs = {r["key"]: r["text"] for r in yaml.safe_load(REFS.read_text(encoding="utf-8"))}
  cited = []
  for group in re.findall(r"\\cite\{([^}]*)\}", body):
    for k in group.split(","):
      k = k.strip()
      if k not in refs:
        raise ReportError(f"cited reference {k!r} is not in references.yaml")
      if k not in cited:
        cited.append(k)
  items = "\n".join(rf"\bibitem{{{k}}} {tex(refs[k], k)}" for k in cited)
  return "\\begin{thebibliography}{9}\n" + items + "\n\\end{thebibliography}\n"


def numbers_tex(numbers: dict) -> str:
  return HEADER + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in numbers.items())


