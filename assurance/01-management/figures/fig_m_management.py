# ================================================================ WP-M-00 work-product register

@dataclass
class WorkProduct:
  wid: str
  name: str
  gate_text: str
  gates: list[int]
  parts: list[tuple[int, int]]      # one (first, last) gate run per comma-separated part of the Gate cell
  status: str


@dataclass
class Register:
  gates: list[tuple[str, str]]                  # (G0, Governance)
  statuses: list[tuple[str, str]]               # (S, Skeleton) in legend order
  sections: list[tuple[str, str, list[WorkProduct]]] = field(default_factory=list)  # (3.1, Management, rows)

  @property
  def products(self) -> list[WorkProduct]:
    return [w for _, _, ws in self.sections for w in ws]


GATE_PART = re.compile(r"G(\d)(?:\s*[–→-]\s*G(\d))?")


def parse_gates(s: str) -> list[tuple[int, int]]:
  """Gate runs of a Gate cell: 'G2 (activation), G3–G4 (use)' -> [(2, 2), (3, 4)]; 'G1→G5' -> [(1, 5)]."""
  out = [(int(lo), int(hi or lo)) for lo, hi in GATE_PART.findall(s)]
  if not out:
    raise FigureError(f"no gate in {s!r}")
  return out


def load_register(md: str | None = None) -> Register:
  md = md if md is not None else WP_M_00.read_text(encoding="utf-8")
  head, rows = table(section(md, "## 2. Gates"), "Gate")
  gates = [(r[col(head, "Gate")], r[col(head, "Name")]) for r in rows]
  if [g for g, _ in gates] != [f"G{i}" for i in range(len(gates))]:
    raise FigureError(f"WP-M-00 §2 gates not G0..Gn in order: {gates}")
  s3 = section(md, "## 3. Register")
  m = re.search(r"^\*\*Status\*\*: (.+?)\.?$", s3, re.M)
  if not m:
    raise FigureError("WP-M-00 §3 status legend not found")
  statuses = [tuple(p.split(" = ", 1)) for p in m.group(1).split(", ")]
  reg = Register(gates, statuses)
  letters = {s for s, _ in statuses}
  for num, title in re.findall(r"^### (3\.\d+) (.+?)(?: \(`[^`]*`\))?\s*$", s3, re.M):
    head, rows = table(section(s3, f"### {num} "), "ID")
    ws = []
    for r in rows:
      wid = plain(r[col(head, "ID")])
      status = r[col(head, "Status")]
      if status not in letters:
        raise FigureError(f"WP-M-00 {wid}: status {status!r} not in the §3 legend")
      gt = r[col(head, "Gate")]
      parts = parse_gates(gt)
      gates = sorted({g for a, b in parts for g in range(a, b + 1)})
      ws.append(WorkProduct(wid, plain(r[col(head, "Work product")]), gt, gates, parts, status))
    reg.sections.append((num, title, ws))
  return reg


# status letter -> (fill, stroke, text colour, dash); green only for an explicit approved/baselined status
STATUS_STYLE = {
  "S": ("url(#hatch)", FAINT, MUTED, "3 2"),
  "D": (AMBER, AMBER, "#FFFFFF", ""),
  "R": ("#FDE68A", AMBER, INK, ""),
  "A": (GREEN, GREEN, "#FFFFFF", ""),
  "B": ("#166534", "#166534", "#FFFFFF", ""),
  "N/A": ("#FFFFFF", FAINT, MUTED, "2 2"),
}


def fig_m00(reg: Register) -> str:
  W = 1280
  ng = len(reg.gates)
  wps = reg.products
  totals = Counter(w.status for w in wps)
  per_gate = [Counter(w.status for w in wps if g in w.gates) for g in range(ng)]
  names = dict(reg.statuses)
  body = header(W, "3-1", "Work-product status by gate",
                f"{len(wps)} work products of the register (§3.1–§3.{len(reg.sections)}), each at the gate(s) " +
                "that need it, coloured by its status", "WP-M-00 §2, §3")
  # ---- status totals
  y = 112
  body.append(text(40, y, "Status totals", size=12, weight=700))
  bx, bw = 160, 560
  x = bx
  for s, _ in reg.statuses:
    n = totals.get(s, 0)
    if not n:
      continue
    fill, stroke, tc, dash = STATUS_STYLE[s]
    w = bw * n / len(wps)
    body.append(rect(x, y - 13, w, 18, fill=fill, stroke=stroke, rx=3, sw=1, dash=dash))
    lab = f"{s} {names[s]} {n}"
    if text_w(lab, 10.5, True) < w - 10:
      body.append(text(x + 8, y, lab, size=10.5, weight=700, fill=tc))
    x += w
  x = bx + bw + 14
  for s, _ in reg.statuses:
    n = totals.get(s, 0)
    if n and bw * n / len(wps) >= text_w(f"{s} {names[s]} {n}", 10.5, True) + 10:
      continue
    lab = f"{s} {names[s]}: {n}"
    body.append(text(x, y, lab, size=10.5, fill=INK if n else MUTED, weight=700 if n else ""))
    x += text_w(lab, 10.5, bool(n)) + 14
  # ---- gate key with counts
  y = 136
  gw = (W - 80) / ng
  for g, (gid, gname) in enumerate(reg.gates):
    gx = 40 + g * gw
    body.append(rect(gx + 2, y, gw - 4, 40, fill=CHIP, stroke=HAIR, rx=6, sw=1))
    c = per_gate[g]
    parts = " · ".join(f"{c[s]} {s}" for s, _ in reg.statuses if c.get(s))
    body.append(text(gx + 10, y + 16, gid, size=11, weight=700, family=MONO))
    body.append(text(gx + 34, y + 16, f"{sum(c.values())} WPs" + (f" ({parts})" if parts else ""),
                     size=10.5, weight=700))
    body.append(text(gx + 10, y + 32, fit(gname, gw - 20, 10), size=10, fill=MUTED))
  # ---- panels: two columns of sections
  top = 200
  colw = (W - 80 - 24) / 2
  cell = 26
  rowh = 15
  hdr_h = 22
  idw = 62
  cells_w = cell * ng
  namew = colw - idw - cells_w - 16
  heights = [hdr_h + rowh * len(ws) + 8 for _, _, ws in reg.sections]
  # split so that the taller column is as short as possible, keeping section order
  best = min(range(1, len(heights)), key=lambda k: max(sum(heights[:k]), sum(heights[k:])))
  columns = [reg.sections[:best], reg.sections[best:]]
  bottom = top
  notes: list[WorkProduct] = []
  for ci, secs in enumerate(columns):
    cx = 40 + ci * (colw + 24)
    gx0 = cx + colw - cells_w
    for g in range(ng):
      body.append(text(gx0 + g * cell + cell / 2, top, f"G{g}", size=10, weight=700, fill=MUTED, anchor="middle",
                       family=MONO))
    body.append(text(cx, top, "ID", size=10, weight=700, fill=MUTED))
    body.append(text(cx + idw, top, "Work product", size=10, weight=700, fill=MUTED))
    y = top + 8
    for num, title, ws in secs:
      body.append(rect(cx, y, colw, hdr_h - 4, fill=GREY_BG, stroke="none", rx=4, sw=0))
      st = Counter(w.status for w in ws)
      tally = " · ".join(f"{st[s]} {s}" for s, _ in reg.statuses if st.get(s))
      body.append(text(cx + 8, y + 13, f"§{num} {title}", size=11, weight=700))
      body.append(text(cx + colw - 8, y + 13, f"{len(ws)} WPs · {tally}", size=10, fill=MUTED, anchor="end"))
      y += hdr_h
      for g in range(ng):
        body.append(line(gx0 + g * cell, y - 2, gx0 + g * cell, y + rowh * len(ws), stroke=HAIR, sw=1))
      body.append(line(gx0 + cells_w, y - 2, gx0 + cells_w, y + rowh * len(ws), stroke=HAIR, sw=1))
      for i, w in enumerate(ws):
        ry = y + i * rowh
        if i % 2:
          body.append(rect(cx, ry, colw - cells_w - 4, rowh, fill=CHIP, stroke="none", rx=0, sw=0))
        mark = " *" if not re.fullmatch(r"G\d", w.gate_text) else ""
        if mark:
          notes.append(w)
        body.append(text(cx + 2, ry + 11, w.wid, size=9.5, weight=700, family=MONO))
        body.append(text(cx + idw, ry + 11, fit(w.name, namew - 12, 10) + mark, size=10, fill=INK))
        fill, stroke, tc, dash = STATUS_STYLE[w.status]
        for a, b in w.parts:
          rx0 = gx0 + a * cell + 2
          rw = (b - a + 1) * cell - 4
          body.append(rect(rx0, ry + 1.5, rw, rowh - 3, fill=fill, stroke=stroke, rx=3, sw=1, dash=dash))
          body.append(text(rx0 + rw / 2, ry + 10.8, w.status, size=9, weight=700, fill=tc, anchor="middle"))
      y += rowh * len(ws) + 8
    bottom = max(bottom, y)
  # ---- notes, legend
  zero = [names[s].lower() for s, _ in reg.statuses if not totals.get(s)]
  zero_note = f" No work product is {', '.join(zero[:-1])} or {zero[-1]}." if len(zero) > 1 else (
    f" No work product is {zero[0]}." if zero else "")
  y = bottom + 10
  body.append(text(40, y, "* Gate column not a single gate: " +
                   " · ".join(f"{w.wid} {w.gate_text}" for w in notes) +
                   " (drawn over every gate named).", size=10.5, fill=MUTED))
  y += 18
  body.append(text(40, y, "Status letter = Status column of the register, legend of §3. A WP spanning several gates " +
                   "is counted at each gate in the gate key." + zero_note,
                   size=10.5, fill=MUTED))
  y += 16
  body.append(line(40, y, W - 40, y, stroke=HAIR, sw=1))
  y += 22
  used = [s for s, _ in reg.statuses if totals.get(s)]
  ents = []
  for s in used:
    fill, stroke, _, dash = STATUS_STYLE[s]
    ents.append((fill, stroke + (" dashed" if dash else ""), f"{s} {names[s]}"))
  lg, _ = legend(40, y, ents)
  body += lg
  body.append(text(W - 40, y, GENERATED, size=10.5, fill=FAINT, anchor="end"))
  H = int(y + 18)
  desc = (f"Heat map of the {len(wps)} work products of the WP-M-00 register by gate G0 to G{ng - 1}. " +
          "Status totals: " + ", ".join(f"{names[s]} {totals.get(s, 0)}" for s, _ in reg.statuses) + ". " +
          "Per gate: " + ", ".join(f"G{g} {sum(per_gate[g].values())}" for g in range(ng)) + ".")
  return svg(W, H, "Figure 3-1 · Work-product status by gate (WP-M-00)", desc, body)


# ================================================================ WP-M-07 risk heat map

@dataclass
class Risk:
  rid: str
  text: str
  p: int
  i: int
  e: int
  treatment: str
  owner: str
  due: str
  closed: bool
  was: tuple[int, int, int] | None

  @property
  def short(self) -> str:
    s = plain(self.text.split("→")[0])
    return s[0].upper() + s[1:]

  @property
  def strategy(self) -> str:
    return plain(self.treatment).split(":")[0]


@dataclass
class RiskRegister:
  p_labels: dict[int, str]
  i_labels: dict[int, str]
  risks: list[Risk]
  summary: dict[str, list[str]]   # §4.1 band -> risk IDs


def band(e: int) -> str:
  return "High" if e >= BAND_HIGH else ("Medium" if e >= BAND_MED else "Low")


def load_risks(md: str | None = None) -> RiskRegister:
  md = md if md is not None else WP_M_07.read_text(encoding="utf-8")
  head, rows = table(section(md, "### 2.2 Analysis"), "Score")
  p_labels = {int(r[0]): r[col(head, "Probability (P)")] for r in rows}
  i_labels = {int(r[0]): r[col(head, "Impact (I)")].split(":")[0] for r in rows}
  s4 = section(md, "## 4. Risk register")
  head, rows = table(s4, "ID")
  risks = []
  for r in rows:
    t = r[col(head, "Treatment")]
    was = re.search(r"was P(\d) I(\d) E(\d+)", t)
    risks.append(Risk(r[0], r[col(head, "Risk (cause → effect)")], int(r[col(head, "P")]), int(r[col(head, "I")]),
                      int(r[col(head, "E")]), t, r[col(head, "Owner")], r[col(head, "Due")],
                      "**Closed**" in t, tuple(int(v) for v in was.groups()) if was else None))
  head, rows = table(section(md, "### 4.1 Exposure summary"), "Band")
  summary = {r[0].split(" (")[0]: re.findall(r"R-\d+", r[1]) for r in rows}
  return RiskRegister(p_labels, i_labels, risks, summary)


BAND_STYLE = {"High": ("#FDE3DE", "#F3B7AB", RED), "Medium": ("#FEF3C7", "#FCD9A0", AMBER),
              "Low": (GREY_BG, LINE, MUTED)}


def fig_m07(rr: RiskRegister) -> str:
  W = 1280
  open_r = [r for r in rr.risks if not r.closed]
  closed = [r for r in rr.risks if r.closed]
  bands = Counter(band(r.e) for r in open_r)
  body = header(W, "4-1", "Risk heat map",
                f"{len(rr.risks)} project risks of the §4 register on the probability × impact grid of §2.2; " +
                f"{len(open_r)} open, {len(closed)} closed", "WP-M-07 §2.2, §4, §4.1")
  gx, gy, cw, ch = 214, 120, 100, 100
  # cells
  cells: dict[tuple[int, int], list[tuple[str, Risk]]] = {}
  for r in rr.risks:
    cells.setdefault((r.p, r.i), []).append(("closed" if r.closed else "open", r))
  for r in rr.risks:
    if r.was:
      cells.setdefault((r.was[0], r.was[1]), []).append(("was", r))
  for p in range(5, 0, -1):
    y = gy + (5 - p) * ch
    lab = rr.p_labels[p]
    m = re.match(r"(.+?) \((.+)\)", lab)
    body.append(text(gx - 12, y + ch / 2 - 2, f"{p} · {m.group(1) if m else lab}", size=11, weight=700,
                     anchor="end"))
    if m:
      body.append(text(gx - 12, y + ch / 2 + 13, m.group(2), size=10, fill=MUTED, anchor="end"))
    for i in range(1, 6):
      x = gx + (i - 1) * cw
      e = p * i
      fill, stroke, tc = BAND_STYLE[band(e)]
      body.append(rect(x + 2, y + 2, cw - 4, ch - 4, fill=fill, stroke=stroke, rx=6, sw=1))
      body.append(text(x + cw - 10, y + 16, f"E {e}", size=9.5, weight=700, fill=tc, anchor="end"))
      for k, (kind, r) in enumerate(cells.get((p, i), [])):
        cx = x + 8 + (k % 2) * 43
        cy = y + 24 + (k // 2) * 23
        if kind == "open":
          body.append(rect(cx, cy, 40, 18, fill="#FFFFFF", stroke=tc, rx=4, sw=1.2))
          body.append(text(cx + 20, cy + 12.5, r.rid, size=10, weight=700, anchor="middle", family=MONO))
        elif kind == "closed":
          body.append(rect(cx, cy, 40, 18, fill=GREY_BG, stroke=FAINT, rx=4, sw=1, dash="3 2"))
          body.append(text(cx + 20, cy + 12.5, r.rid, size=10, fill=MUTED, anchor="middle", family=MONO,
                           deco="line-through"))
        else:
          body.append(rect(cx, cy, 40, 18, fill="none", stroke=FAINT, rx=4, sw=1, dash="2 2"))
          body.append(text(cx + 20, cy + 12.5, r.rid, size=10, fill=FAINT, anchor="middle", family=MONO))
  # axes
  body.append(text(gx - 12, gy - 12, "Probability (P)", size=11, weight=700, fill=MUTED, anchor="end"))
  yb = gy + 5 * ch
  for i in range(1, 6):
    x = gx + (i - 1) * cw + cw / 2
    body.append(text(x, yb + 18, f"{i} · {rr.i_labels[i]}", size=11, weight=700, anchor="middle"))
  body.append(text(gx + 2.5 * cw, yb + 40, "Impact (I)", size=11, weight=700, fill=MUTED, anchor="middle"))
  # ---- side list: open High risks
  lx, lw = 770, W - 40 - 770
  high = sorted([r for r in open_r if band(r.e) == "High"], key=lambda r: (-r.e, r.rid))
  body.append(text(lx, gy - 12, f"Open High risks (E ≥ {BAND_HIGH}), by exposure", size=12, weight=700))
  y = gy
  rh = (5 * ch) / max(len(high), 1)
  for k, r in enumerate(high):
    ry = y + k * rh
    if k % 2 == 0:
      body.append(rect(lx, ry + 1, lw, rh - 2, fill=CHIP, stroke="none", rx=4, sw=0))
    body.append(rect(lx + 6, ry + 6, 40, 18, fill="#FFFFFF", stroke=RED, rx=4, sw=1.2))
    body.append(text(lx + 26, ry + 18.5, r.rid, size=10, weight=700, anchor="middle", family=MONO))
    body.append(text(lx + 56, ry + 19, f"E {r.e}", size=11, weight=700, fill=RED))
    body.append(text(lx + 92, ry + 19, f"P{r.p} × I{r.i}", size=10.5, fill=MUTED))
    meta = f"{r.strategy} · {r.owner} · due {r.due}"
    body.append(text(lx + lw - 8, ry + 19, meta, size=10.5, fill=MUTED, anchor="end"))
    body.append(text(lx + 56, ry + 36, fit(r.short, lw - 64, 10.5), size=10.5, fill=INK))
  # ---- notes, legend
  y = yb + 64
  rescored = [r for r in rr.risks if r.was]
  body.append(text(40, y, f"Open by band: High {bands['High']} · Medium {bands['Medium']} · Low {bands['Low']}" +
                   f" · closed {len(closed)} (" + ", ".join(r.rid for r in closed) + "). Re-scored: " +
                   ", ".join(f"{r.rid} P{r.was[0]} I{r.was[1]} E{r.was[2]} → P{r.p} I{r.i} E{r.e}" for r in rescored) +
                   " (dotted chip = previous cell).", size=10.5, fill=MUTED))
  body.append(text(40, y + 17, "Scores are single-author engineering judgement (§2.2, OI-2). Label = the cause clause " +
                   "of the risk text, before the arrow. Treatment strategy = first word of the Treatment column.",
                   size=10.5, fill=MUTED))
  y += 33
  body.append(line(40, y, W - 40, y, stroke=HAIR, sw=1))
  y += 22
  ents = [(BAND_STYLE[b][0], BAND_STYLE[b][1], f"{b} exposure cell") for b in ("High", "Medium", "Low")]
  ents += [("#FFFFFF", MUTED, "open risk"), (GREY_BG, FAINT + " dashed", "closed (struck through)"),
           ("none", FAINT + " dashed", "cell before re-scoring")]
  lg, _ = legend(40, y, ents)
  body += lg
  body.append(text(W - 40, y, GENERATED, size=10.5, fill=FAINT, anchor="end"))
  H = int(y + 18)
  desc = (f"Probability by impact grid of the {len(rr.risks)} WP-M-07 risks. Open: High {bands['High']} (" +
          ", ".join(f"{r.rid} E{r.e}" for r in high) + f"), Medium {bands['Medium']}, Low {bands['Low']}; closed: " +
          ", ".join(r.rid for r in closed) + ".")
  return svg(W, H, "Figure 4-1 · Risk heat map (WP-M-07)", desc, body)


# ================================================================ WP-M-13 capability profile

@dataclass
class Process:
  code: str
  name: str
  ratings: list[tuple[str, str]]     # (N/P/L/F, qualifier or "")
  cl: str                            # current CL text from §4 ("" when the table has none)
  group: str                         # A / B / C
  target: int | None                 # target CL from §6
  gap: str


@dataclass
class Profile:
  groups: list[tuple[str, str, list[Process]]]   # (4.1, System engineering, processes)
  pa2: dict[str, str]                            # PA 2.1 -> N
  baseline: str                                  # commit of the Baseline field

  @property
  def processes(self) -> list[Process]:
    return [p for _, _, ps in self.groups for p in ps]


def expand(s: str) -> list[str]:
  """'SWE.1–SWE.6' -> SWE.1 ... SWE.6; 'MLE.1–4' -> MLE.1 ... MLE.4; 'SYS.1' -> [SYS.1]."""
  m = re.fullmatch(r"([A-Z]{3})\.(\d+)(?:\s*[–-]\s*(?:[A-Z]{3}\.)?(\d+))?", s.strip())
  if not m:
    raise FigureError(f"process reference {s!r}")
  return [f"{m.group(1)}.{n}" for n in range(int(m.group(2)), int(m.group(3) or m.group(2)) + 1)]


def parse_rating(s: str) -> list[tuple[str, str]]:
  out = []
  for part in s.split(" / "):
    m = re.fullmatch(r"([NPLF])(?: \((.+)\))?", part.strip())
    if not m:
      raise FigureError(f"PA rating {s!r}")
    out.append((m.group(1), m.group(2) or ""))
  return out


def load_profile(md: str | None = None) -> Profile:
  md = md if md is not None else WP_M_13.read_text(encoding="utf-8")
  head, rows = table(section(md, "## 3. Scope"), "Group")
  group_of = {}
  for r in rows:
    g = r[0].split()[0]
    for ref in r[col(head, "Processes")].split(", "):
      for c in expand(ref):
        group_of[c] = g
  head, rows = table(section(md, "## 6. Summary"), "Process")
  target, gap = {}, {}
  for r in rows:
    for c in expand(r[0]):
      target[c] = int(r[col(head, "Target CL")])
      gap[c] = r[col(head, "Gap")]
  s4 = section(md, "## 4. Capability level 1")
  groups = []
  for num, title in re.findall(r"^### (4\.\d+) (.+?)\s*$", s4, re.M):
    head, rows = table(section(s4, f"### {num} "), "Process")
    ps = []
    for r in rows:
      code, name = r[0].split(" ", 1)
      if code not in group_of:
        raise FigureError(f"WP-M-13 {code} not in the §3 scope")
      ps.append(Process(code, name, parse_rating(r[col(head, "PA 1.1")]), r[col(head, "CL")] if "CL" in head else "",
                        group_of[code], target.get(code), gap.get(code, "")))
    groups.append((num, re.sub(r"\s*\(group [A-C]\)", "", title), ps))
  head, rows = table(section(md, "## 5. Capability level 2"), "Attribute")
  pa2 = {re.match(r"PA \d\.\d", r[0]).group(0): r[col(head, "Rating")] for r in rows}
  m = re.search(r"^\| Baseline \| `([0-9a-f]+)`", md, re.M)
  if not m:
    raise FigureError("WP-M-13 Baseline field not found")
  return Profile(groups, pa2, m.group(1))


