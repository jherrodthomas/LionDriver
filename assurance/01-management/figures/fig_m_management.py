def main(argv: list[str]) -> int:
  if "--repin" in argv:
    names = argv[argv.index("--repin") + 1:]
    for n in names:
      if n not in fig_m_plans.PINNED:
        print(f"not a pinned figure: {n} (pinned: {', '.join(fig_m_plans.PINNED)})", file=sys.stderr)
        return 1
      fig_m_plans.repin(n)
      print(f"fig_m_management: re-pinned {n}")
    return 0
  check = "--check" in argv
  missing = missing_sources() + fig_m_plans.missing_sources()
  if missing:
    for s in missing:
      print(f"source text no longer found: {s}", file=sys.stderr)
    print("review the prose values in fig_m_management.py (SRC) and regenerate", file=sys.stderr)
    return 1
  try:
    outputs = build()
  except FigureError as e:
    print(f"fig_m_management: {e}", file=sys.stderr)
    return 1
  problems = fig_m_plans.problems()
  for pr in problems:
    print(f"fig_m_management: {pr}", file=sys.stderr)
  if problems:
    return 1
  if check:
    stale = [n for n, c in outputs.items() if not (HERE / n).exists() or (HERE / n).read_text(encoding="utf-8") != c]
    for n in stale:
      print(f"stale: {n}", file=sys.stderr)
    if stale:
      print("run: python3 assurance/01-management/figures/fig_m_management.py", file=sys.stderr)
      return 1
    print(f"fig_m_management: {len(outputs)} figure(s) current, {len(SRC) + len(fig_m_plans.SRC)} source texts found, "
          f"decisions consistent, {len(fig_m_plans.PINNED)} pinned figure(s) current")
    return 0
  for n, c in outputs.items():
    (HERE / n).write_text(c, encoding="utf-8")
  print(f"fig_m_management: wrote {len(outputs)} figure(s)")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
