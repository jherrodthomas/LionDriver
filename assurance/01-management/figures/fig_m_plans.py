# ================================================================ decision check

def decision_word(s: str) -> str:
  """Status keyword of a decision cell or Status clause: done, decided, mostly done, answered, open, pending."""
  s = plain(s).lower().lstrip()
  for w in ("mostly done", "done", "decided", "answered", "pending", "open"):
    if s.startswith(w):
      return w
  return "?"


def decision_mismatches() -> list[str]:
  m01 = WP_M_01.read_text(encoding="utf-8")
  m07 = WP_M_07.read_text(encoding="utf-8")
  _, rows01 = table(section(m01, "## 8. Strategic decisions required"), "ID")
  head, rows07 = table(section(m07, "## 5. Decision log"), "ID")
  log = {r[0]: decision_word(r[col(head, "Status")]) for r in rows07}
  out = []
  for r in rows01:
    m = re.search(r"\*\*Status:\*\*\s*(.*)", r[2])
    w01 = decision_word(m.group(1)) if m else "no status"
    w07 = log.pop(r[0], "missing")
    if w01 != w07:
      out.append(f"{r[0]}: WP-M-01 §8 says {w01!r}, WP-M-07 §5 says {w07!r}")
  out += [f"{d}: in WP-M-07 §5 but not in WP-M-01 §8" for d in log]
  return out


# ================================================================ pinned hand-drawn figures

def pin_digest(name: str) -> str:
  h = hashlib.sha256()
  for doc, heading in PINNED[name]:
    h.update(section(doc.read_text(encoding="utf-8"), heading).strip().encode("utf-8"))
  return h.hexdigest()[:16]


def pin_problems() -> list[str]:
  out = []
  for name in PINNED:
    m = PIN_RE.search((HERE / name).read_text(encoding="utf-8"))
    if not m:
      out.append(f"{name}: no source digest; review it and run fig_m_management.py --repin {name}")
    elif m.group(1) != pin_digest(name):
      secs = ", ".join(f"{d.name} {h.lstrip('# ')}" for d, h in PINNED[name])
      out.append(f"{name}: its source sections changed ({secs}); review the drawing, then run "
                 f"fig_m_management.py --repin {name}")
  return out


def repin(name: str) -> None:
  p = HERE / name
  s = p.read_text(encoding="utf-8")
  tag = f"<!-- source-digest: {pin_digest(name)} -->"
  s = PIN_RE.sub(tag, s) if PIN_RE.search(s) else s.replace(">", ">\n" + tag, 1)
  p.write_text(s, encoding="utf-8")


