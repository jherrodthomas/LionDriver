@dataclass
class Phase:
  pid: str                 # P0
  name: str                # Governance
  gate: str                # G0
  months: tuple[int, int] | None   # §5 relative duration, None = continuous
  pw: str                  # §4.2 "6–10" or the P6 text
  depends: list[str]       # §5 "Depends on" parts after the gate
  overlap: str             # §5 "Can overlap with"
  due: list[tuple[str, str]] = field(default_factory=list)   # §10 (OI id, text) due at this phase's gate


@dataclass
class Backlog:
  bid: str
  title: str
  status: str              # done / exception / open / not
  note: str
  link: str                # Gap / decision column


@dataclass
class Plan:
  start: tuple[int, int] | None    # §5 "Calendar:" start (year, month); None = relative only
  stretch: float                   # §5 durations are at 1.0 FTE; the calendar stretches them by 40 h / hours a week
  phases: list[Phase]
  critical: list[str]
  long_lead: list[tuple[str, str, str, str]]   # (item, phase, §6 status, needed-by phase)
  backlog: list[Backlog]
