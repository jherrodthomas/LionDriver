#!/usr/bin/env python3
"""Draw a standard "folder card" at the top of the assurance READMEs that have no picture of their own.

The project lead asked for one visual summary per folder, on READMEs that do not already have one: a folder whose
README already explains itself with figures is left alone. Each card is two pictures, stacked so that each reads at
phone width:

- `card-overview.svg`: where the folder sits among the eleven phase folders (or which phases a cross-cutting folder
  serves), and what feeds it and what it feeds;
- `card-status.svg`: four numbers at a glance, status chips, and one picture of where the folder's work stands.

The card goes between `<!-- folder-card:start -->` and `<!-- folder-card:end -->` right under the README's title.
Nothing else in the README is touched. Every number, ID and status is read from the folder's own records at build
time. The build fails if:

- a folder in CARDS has a README with a picture of its own outside the card (the card is only for folders without);
- a document named as a feed does not exist;
- the purpose phrase quoted from the README is no longer in it;
- a record has lost the section, column or status word a card reads.

    python3 assurance/01-management/figures/folder_cards.py            # write the cards and the README blocks
    python3 assurance/01-management/figures/folder_cards.py --check    # fail if a card or block is stale

Standard library only (YAML through tools/safety/fmea_diagrams' loader). Output is deterministic.
"""

