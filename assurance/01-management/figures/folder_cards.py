def read(rel: str) -> str:
  p = A / rel
  if not p.exists():
    raise FigureError(f"{rel} not found")
  return p.read_text(encoding="utf-8")


def field(md: str, name: str) -> str:
  m = re.search(rf"^\| {re.escape(name)} \| (.+?) \|\s*$", md, re.M)
  if not m:
    raise FigureError(f"header field '{name}' not found")
  return fk.plain(m.group(1))


def rows(md: str, heading: str, first: str | None = None) -> tuple[list[str], list[list[str]]]:
  head, body = fk.table(fk.section(md, heading), first)
  if not body:
    raise FigureError(f"table under '{heading}' is empty")
  return head, body


def phrase(cell: str, table: dict[str, tuple], what: str):
  """Map free text to a state by a phrase quoted from it, so a reworded cell fails on purpose."""
  for k, v in table.items():
    if k.lower() in cell.lower():
      return v
  raise FigureError(f"{what}: no known phrase in '{cell[:80]}'")


