def box(x, y, w, h, label, sub, stroke=fk.LINE, fill="#FFFFFF", bold=fk.INK):
  return [fk.rect(x, y, w, h, fill=fill, stroke=stroke, rx=7), fk.text(x + 10, y + 16, fk.fit(label, w - 20, 10.5, True), size=10.5, weight=700, fill=bold),
          fk.text(x + 10, y + 30, fk.fit(sub, w - 20, 9.5), size=9.5, fill=fk.MUTED)]


def overview(key, c):
  b = [fk.text(M, 36, c["title"], size=17, weight=700), fk.text(M, 56, fk.fit(c["purpose"], W - 2 * M, 11), size=11, fill=fk.MUTED),
       fk.line(M, 70, W - M, 70, stroke=fk.HAIR, sw=1)]
  y = 92
  here, serves = c.get("phase"), set(c.get("serves", ()))
  b.append(fk.text(M, y, "Where it sits" if here else "Which phases it serves", size=10, fill=fk.FAINT, weight=700))
  cw = (W - 2 * M - 10 * 3) / 11
  for i, (n, lab) in enumerate(PHASES):
    x = M + i * (cw + 3)
    on, near = n == here, n in serves
    b.append(fk.rect(x, y + 8, cw, 24, fill=fk.SAFETY if on else (fk.SAFETY_BG if near else fk.GREY_BG),
                     stroke=fk.SAFETY if near else "none", rx=5, sw=1.2))
    b.append(fk.text(x + cw / 2, y + 24, n, size=10, weight=700, anchor="middle",
                     fill="#FFFFFF" if on else (fk.SAFETY if near else fk.FAINT)))
  marks = [n for n, _ in PHASES if n == here or n in serves]
  label = (f"{here} {dict(PHASES)[here]}" if here else "cross-cutting: serves " + ", ".join(f"{n} {dict(PHASES)[n]}" for n in marks))
  i0 = [n for n, _ in PHASES].index(marks[0])
  lx = min(max(M, M + i0 * (cw + 3)), W - M - fk.text_w(label, 10, True))
  b.append(fk.text(lx, y + 48, label, size=10, weight=700, fill=fk.SAFETY))
  y += 72
  b.append(fk.text(M, y, "What feeds it, what it feeds", size=10, fill=fk.FAINT, weight=700))
  y += 10

  def row(items, yy):
    bw = (W - 2 * M - (len(items) - 1) * 12) / len(items)
    out = []
    for i, (lab, sub, rel) in enumerate(items):
      if not (A / rel).exists():
        raise FigureError(f"{key}: feed {lab} names {rel}, which does not exist")
      out += box(M + i * (bw + 12), yy, bw, 38, lab, sub)
    return out

  b += row(c["ins"], y)
  b.append(fk.path(f"M{W / 2} {y + 42} L{W / 2} {y + 58}", stroke=fk.FAINT, sw=1.6))
  b.append(fk.path(f"M{W / 2 - 5} {y + 53} L{W / 2} {y + 59} L{W / 2 + 5} {y + 53}", stroke=fk.FAINT, sw=1.6))
  y += 62
  b += box(W / 2 - 120, y, 240, 38, "This folder", c["me"], stroke=fk.SAFETY, fill=fk.SAFETY_BG, bold=fk.SAFETY)
  b.append(fk.path(f"M{W / 2} {y + 42} L{W / 2} {y + 58}", stroke=fk.FAINT, sw=1.6))
  b.append(fk.path(f"M{W / 2 - 5} {y + 53} L{W / 2} {y + 59} L{W / 2 + 5} {y + 53}", stroke=fk.FAINT, sw=1.6))
  y += 62
  b += row(c["outs"], y)
  y += 60
  tb, y = terms.svg_footer(b, M, y, W - 2 * M)
  b += tb
  desc = (f"{c['title']}: " + (f"phase {label}" if here else label) + ". Fed by " + "; ".join(f"{a} ({s})" for a, s, _ in c["ins"]) +
          ". Feeds " + "; ".join(f"{a} ({s})" for a, s, _ in c["outs"]) + ".")
  return fk.svg(W, int(y + 8), f"{c['title']}: where it sits", desc, b), desc


def picture(kind, y):
  b = []
  if kind[0] == "ladder":
    steps = kind[1]
    sw = (W - 2 * M - (len(steps) - 1) * 8) / len(steps)
    for i, (lab, n) in enumerate(steps):
      x = M + i * (sw + 8)
      on = n > 0
      b += [fk.rect(x, y, sw, 64, fill=fk.GREEN_BG if on else "#FFFFFF", stroke=fk.GREEN if on else fk.LINE, rx=7, dash="" if on else "4 3"),
            fk.text(x + 10, y + 30, str(n), size=20, weight=700, fill=fk.GREEN if on else fk.FAINT)]
      words = lab.split(" ")
      half = (len(words) + 1) // 2 if fk.text_w(lab, 9, False) > sw - 16 else len(words)
      b.append(fk.text(x + 10, y + 46, " ".join(words[:half]), size=9, fill=fk.MUTED))
      if half < len(words):
        b.append(fk.text(x + 10, y + 57, " ".join(words[half:]), size=9, fill=fk.MUTED))
    return b, 70
  if kind[0] == "pipeline":
    steps = kind[1]
    for i, (lab, n) in enumerate(steps):
      yy = y + i * 30
      b += [fk.rect(M, yy, 26, 22, fill=fk.SW, stroke="none", rx=5),
            fk.text(M + 13, yy + 15, str(i + 1), size=9.5, weight=700, fill="#FFFFFF", anchor="middle"),
            fk.text(M + 36, yy + 15, lab, size=11, weight=700), fk.text(W - M, yy + 15, n, size=11, fill=fk.SW, weight=700, anchor="end"),
            fk.line(M + 36, yy + 24, W - M, yy + 24, stroke=fk.HAIR, sw=1)]
      if i:
        b.append(fk.line(M + 13, yy - 8, M + 13, yy, stroke=fk.SW, sw=1.6))
    return b, len(steps) * 30
  if kind[0] == "stack":
    segs, months = kind[1], kind[2]
    total = sum(v for _, v, _ in segs)
    x, bw = M, W - 2 * M
    for lab, v, tone in segs:
      w = bw * v / total
      fg, bg = TONE[tone]
      b.append(fk.rect(x, y, w, 26, fill=fg, stroke="#FFFFFF", rx=0, sw=1))
      if w > 26:
        b.append(fk.text(x + w / 2, y + 17, str(v), size=10.5, weight=700, fill="#FFFFFF", anchor="middle"))
      x += w
    lx = M
    for lab, v, tone in segs:
      b.append(fk.rect(lx, y + 34, 10, 10, fill=TONE[tone][0], stroke="none", rx=2))
      b.append(fk.text(lx + 14, y + 43, f"{lab} {v}", size=9.5, fill=fk.MUTED))
      lx += 26 + fk.text_w(f"{lab} {v}", 9.5)
    my = y + 64
    b.append(fk.text(M, my, "Records by month", size=9.5, fill=fk.FAINT, weight=700))
    top = max(n for _, n in months)
    for i, (m, n) in enumerate(months):
      w = (bw - 70) * n / top
      b += [fk.text(M, my + 20 + i * 18, m, size=10, fill=fk.MUTED), fk.rect(M + 60, my + 10 + i * 18, w, 12, fill=fk.LINE, stroke="none", rx=2),
            fk.text(M + 66 + w, my + 20 + i * 18, str(n), size=10, fill=fk.INK, weight=700)]
    return b, 64 + 14 + len(months) * 18
  raise FigureError(f"unknown picture kind {kind[0]}")


def status(key, c, d):
  b = [fk.text(M, 22, "At a glance", size=10, fill=fk.FAINT, weight=700)]
  y = 30
  tw = (W - 2 * M - 3 * 8) / 4
  for i, (num, lab, tone) in enumerate(d["tiles"]):
    fg, bg = TONE[tone]
    x = M + i * (tw + 8)
    b += [fk.rect(x, y, tw, 54, fill=bg, stroke="none", rx=7), fk.text(x + 10, y + 26, str(num), size=19, weight=700, fill=fg),
          fk.text(x + 10, y + 44, fk.fit(lab, tw - 18, 9.5), size=9.5, fill=fk.MUTED)]
  y += 62
  x = M
  for lab, tone in d["chips"]:
    fg, bg = TONE[tone]
    p, w = fk.pill(x, y, lab, bg, fg, h=18, size=9.5)
    if x + w > W - M:
      x, y = M, y + 22
      p, w = fk.pill(x, y, lab, bg, fg, h=18, size=9.5)
    b += p
    x += w + 6
  y += 40
  b.append(fk.text(M, y, "Where it stands", size=10, fill=fk.FAINT, weight=700))
  p, h = picture(d["picture"], y + 10)
  b += p
  y += h + 28
  words, ln, lines = d["caption"].split(), "", []
  for wd in words:
    if fk.text_w((ln + " " + wd).strip(), 10.5) > W - 2 * M:
      lines.append(ln)
      ln = wd
    else:
      ln = (ln + " " + wd).strip()
  lines.append(ln)
  for i, l in enumerate(lines):
    b.append(fk.text(M, y + i * 15, l, size=10.5, fill=fk.INK))
  y += len(lines) * 15 + 6
  b.append(fk.text(M, y, "Generated by folder_cards.py from this folder's own records; the page's text follows below.", size=9.5, fill=fk.FAINT))
  y += 20
  tb, y = terms.svg_footer(b, M, y, W - 2 * M)
  b += tb
  return fk.svg(W, int(y + 8), f"{c['title']}: at a glance", d["alt"] + ". " + d["caption"], b)


IMG = re.compile(r"!\[|<img\b")


def block(c, d, o_desc):
  return "\n".join([START, f"![{c['title']}, where it sits. {o_desc}](card-overview.svg)", "",
                    f"![{c['title']}, at a glance: {d['alt']}](card-status.svg)", END])


def build() -> dict[Path, str]:
  out: dict[Path, str] = {}
  for key, c in CARDS.items():
    folder = A / key
    readme = (folder / "README.md").read_text(encoding="utf-8")
    if c["quote"] not in readme:
      raise FigureError(f"{key}: the README no longer says '{c['quote']}'")
    rest = re.sub(re.escape(START) + r".*?" + re.escape(END), "", readme, flags=re.S)
    if IMG.search(rest):
      raise FigureError(f"{key}: the README has a picture of its own; the folder card is only for folders without one")
    d = c["fn"]()
    o_svg, o_desc = overview(key, c)
    out[folder / "card-overview.svg"] = o_svg
    out[folder / "card-status.svg"] = status(key, c, d)
    blk = block(c, d, o_desc)
    if START in readme:
      new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: blk, readme, flags=re.S)
    else:
      m = re.search(r"^# .*\n", readme, re.M)
      if not m:
        raise FigureError(f"{key}: README has no title line")
      new = readme[:m.end()] + "\n" + blk + "\n" + readme[m.end():]
    out[folder / "README.md"] = new
  return out


def main(argv: list[str]) -> int:
  check = "--check" in argv
  try:
    out = build()
  except FigureError as e:
    print(f"folder_cards: {e}", file=sys.stderr)
    return 1
  stale = [p for p, s in out.items() if not p.exists() or p.read_text(encoding="utf-8") != s]
  if check:
    if stale:
      print("folder_cards: stale; run assurance/01-management/figures/folder_cards.py: " +
            ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
      return 1
    print(f"folder_cards: {len(CARDS)} folder cards current")
    return 0
  for p in stale:
    p.write_text(out[p], encoding="utf-8")
  print(f"folder_cards: {len(CARDS)} folder cards, {len(stale)} files written")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
