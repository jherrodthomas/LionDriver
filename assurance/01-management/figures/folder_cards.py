IMG = re.compile(r"!\[|<img\b")


def block(c, d, o_desc):
  return "\n".join([START, f"![{c['title']}, where it sits. {o_desc}](card-overview.svg)", "",
                    f"![{c['title']}, at a glance: {d['alt']}](card-status.svg)", END])


def build() -> dict[Path, str]:
  out: dict[Path, str] = {}
  for key, c in CARDS.items():
    folder = A / key
    readme = (folder / "README.md").read_text(encoding="utf-8")
    if c["quote"] not in readme:
      raise FigureError(f"{key}: the README no longer says '{c['quote']}'")
    rest = re.sub(re.escape(START) + r".*?" + re.escape(END), "", readme, flags=re.S)
    if IMG.search(rest):
      raise FigureError(f"{key}: the README has a picture of its own; the folder card is only for folders without one")
    d = c["fn"]()
    o_svg, o_desc = overview(key, c)
    out[folder / "card-overview.svg"] = o_svg
    out[folder / "card-status.svg"] = status(key, c, d)
    blk = block(c, d, o_desc)
    if START in readme:
      new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: blk, readme, flags=re.S)
    else:
      m = re.search(r"^# .*\n", readme, re.M)
      if not m:
        raise FigureError(f"{key}: README has no title line")
      new = readme[:m.end()] + "\n" + blk + "\n" + readme[m.end():]
    out[folder / "README.md"] = new
  return out


def main(argv: list[str]) -> int:
  check = "--check" in argv
  try:
    out = build()
  except FigureError as e:
    print(f"folder_cards: {e}", file=sys.stderr)
    return 1
  stale = [p for p, s in out.items() if not p.exists() or p.read_text(encoding="utf-8") != s]
  if check:
    if stale:
      print("folder_cards: stale; run assurance/01-management/figures/folder_cards.py: " +
            ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
      return 1
    print(f"folder_cards: {len(CARDS)} folder cards current")
    return 0
  for p in stale:
    p.write_text(out[p], encoding="utf-8")
  print(f"folder_cards: {len(CARDS)} folder cards, {len(stale)} files written")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
