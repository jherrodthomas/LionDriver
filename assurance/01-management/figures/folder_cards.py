def test_sites():
  md = read("06-validation/test-sites/README.md")
  _, cand = rows(md, "## 3. Candidates in the corridor")
  sites = [r[0] for r in cand if re.fullmatch(r"TS-\d\d", fk.plain(r[0]))]
  if len(sites) != len(cand) or len(set(sites)) != len(sites):
    raise FigureError("test sites: §3 rows must each be one TS-nn")
  _, tiers = rows(md, "### 2.1 Test tiers")
  head, log = rows(md, "## 6. Contact log")
  oc = fk.col(head, "Outcome")
  contacted = [r for r in log if fk.plain(r[0]) not in ("—", "-", "")]
  booked = [r for r in contacted if re.search(r"\bbooked\b|agreement", r[oc], re.I) and not re.search(r"\bnot\b", r[oc], re.I)]
  calls = re.findall(r"^### 5\.\d+ First-call sheet: (TS-\d\d)", md, re.M)
  status = field(md, "Status")
  research = phrase(status, {"desk research only": ("desk research only", "bad"), "contacted": ("sites contacted", "part")},
                    "test sites Status")
  dq = re.search(r"decision register (DQ-\d+), ([A-D])", md)
  if not dq:
    raise FigureError("test sites: §4 no longer names its decision")
  version = field(md, "Version").split(" ")[0]
  steps = [("Researched", len(sites)), ("First call drafted", len(calls)), ("Contacted", len(contacted)),
           ("Assessed on site", 0 if not contacted else len(contacted)), ("Booked", len(booked))]
  return dict(
    tiles=[(len(sites), "candidate sites", "n"), (len(contacted), "contacted", "ok" if contacted else "bad"),
           (len(booked), "booked", "ok" if booked else "bad"), (len(tiers), "test tiers", "n")],
    chips=[(f"Draft v{version}", "part"), (research[0], research[1]), (f"decided: {dq.group(1)} {dq.group(2)}", "ok")],
    picture=("ladder", steps),
    caption=(f"How far the site search has got: {len(sites)} researched, {len(calls)} first-call sheet drafted, "
             f"{len(contacted)} contacted, {len(booked)} booked."),
    alt=(f"{len(sites)} candidate sites researched; {len(calls)} first-call sheet drafted; {len(contacted)} contacted; "
         f"{len(booked)} booked; {len(tiers)} test tiers; Draft v{version}, {research[0]}, decided {dq.group(1)} {dq.group(2)}"))


def fret():
  y = fmd.load_yaml(read("models/fret/tsr-fretish.yaml"))
  reqs, finds = y["requirements"], y["findings"]
  fr = [r for r in reqs if r["id"].startswith("FR-")]
  fa = [r for r in reqs if r["id"].startswith("FA-")]
  if len(fr) + len(fa) != len(reqs):
    raise FigureError("fret: a requirement ID is neither FR- nor FA-")
  tsrs = sorted({r["tsr"] for r in reqs})
  fixed = [f for f in finds if str(f["status"]).lower().startswith("fixed")]
  real = read("models/fret/fret-realizability.md")
  comps = re.findall(r"^\| \[(\w+)\]\([^)]*\) \|.*\| \*\*(realizable|unrealizable)\*\* \|", real, re.M)
  if not comps:
    raise FigureError("fret: no component result in fret-realizability.md")
  ok = [c for c, r in comps if r == "realizable"]
  mon = read("models/fret/monitor/monitor-results.md")
  _, mutants = rows(mon, "## Defects injected on purpose")
  caught = [r for r in mutants if fk.plain(r[-1]).lower() == "yes"]
  formal = __import__("json").loads(read("models/fret/fretish-formalizations.json"))["requirements"]
  readme = read("models/fret/README.md")
  evidence = field(readme, "Evidence")
  steps = [("TSRs restated", f"{len(tsrs)} TSRs"), ("FRETish", f"{len(fr)} + {len(fa)} assumptions"),
           ("Formalised by FRET", f"{len(formal)} formulas"), ("Kind 2 realizability", f"{len(ok)} of {len(comps)} realizable"),
           ("Copilot monitors", f"{len(caught)} of {len(mutants)} mutants caught")]
  return dict(
    tiles=[(len(reqs), f"FRETish for {len(tsrs)} TSRs", "n"), (f"{len(fixed)}/{len(finds)}", "findings fixed",
           "ok" if len(fixed) == len(finds) else "part"), (f"{len(ok)}/{len(comps)}", "components realizable",
           "ok" if len(ok) == len(comps) else "bad"), (f"{len(caught)}/{len(mutants)}", "mutants caught", "ok" if len(caught) == len(mutants) else "bad")],
    chips=[("pilot TE-03", "n"), ("no evidence credit" if evidence.lower().startswith("none") else evidence, "bad"),
           ("WP-S-02 stays the record", "n")],
    picture=("pipeline", steps),
    caption=(f"The pilot's steps: {len(tsrs)} TSRs restated in FRETish, formalised, checked for realizability "
             f"({len(ok)} of {len(comps)}), and turned into monitors that caught {len(caught)} of {len(mutants)} injected defects."),
    alt=(f"{len(reqs)} FRETish requirements ({len(fr)} plus {len(fa)} assumptions) for {len(tsrs)} TSRs; {len(fixed)} of "
         f"{len(finds)} findings fixed; {len(ok)} of {len(comps)} components realizable; {len(caught)} of {len(mutants)} "
         "injected defects caught by the monitors; no evidence credit"))


IMPACT_STATUS = {"Integrated": ("integrated", "ok"), "Implemented": ("implemented", "ok"), "Proposed": ("proposed", "part"),
                 "Draft": ("draft", "grey")}


def impact():
  d = A / "07-supporting/impact"
  recs = sorted(p for p in d.glob("*.md") if p.name != "README.md")
  if not recs:
    raise FigureError("impact: no records")
  counts = {v[0]: 0 for v in IMPACT_STATUS.values()}
  counts["no status row"] = 0
  months: dict[str, int] = {}
  for p in recs:
    md = p.read_text(encoding="utf-8")
    m = re.search(r"\d{4}-\d\d", p.name)
    if not m:
      raise FigureError(f"impact: {p.name} has no date in its name")
    months[m.group(0)] = months.get(m.group(0), 0) + 1
    s = re.search(r"^\| Status \| \**([A-Z][a-z]+)", md, re.M)
    if not s:
      counts["no status row"] += 1
      continue
    if s.group(1) not in IMPACT_STATUS:
      raise FigureError(f"impact: {p.name} status '{s.group(1)}' has no colour")
    counts[IMPACT_STATUS[s.group(1)][0]] += 1
  sync = len([p for p in recs if p.name.startswith("sync-")])
  done = counts["integrated"] + counts["implemented"]
  segs = [(k, v, dict(IMPACT_STATUS.values()).get(k, "bad")) for k, v in counts.items() if v]
  return dict(
    tiles=[(len(recs), "impact records", "n"), (done, "integrated", "ok"),
           (counts["proposed"], "still say proposed", "part"), (counts["no status row"], "without a status row", "bad" if counts["no status row"] else "ok")],
    chips=[("CT-3 upstream syncs", "n"), ("WP-M-12 §7.3 template", "n")],
    picture=("stack", segs, sorted(months.items())),
    caption=(f"The {len(recs)} impact records by the status each one states: {done} integrated or implemented, "
             f"{counts['proposed']} still say proposed."),
    alt=(f"{len(recs)} impact records, {sync} of them sync reports: " +
         ", ".join(f"{v} {k}" for k, v, _ in segs) + "; by month " + ", ".join(f"{m} {n}" for m, n in sorted(months.items()))))


