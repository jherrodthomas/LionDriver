def missing_sources() -> list[str]:
  return [f"{d.name} [{k}]: {s}" for k, (d, s) in SRC.items() if s not in d.read_text(encoding="utf-8")]


def build() -> dict[str, str]:
  md = doc()
  return {"fig-m02-3-1-raci.svg": fig_raci(md), "fig-m02-4-1-lifecycle.svg": fig_lifecycle(md),
          "fig-m02-4-2-at-risk.svg": fig_at_risk(md), "fig-m02-9-1-anomaly.svg": fig_anomaly(md)}
