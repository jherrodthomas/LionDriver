# §3.2 column abbreviations, as defined in the sentence above the RACI table
ABBR_RE = re.compile(r"(\b[A-Z]{2,3}) = ([a-zA-Z/ ]+?)(?:,|\.)")
REVIEW_COLS = ("VR", "EA", "QA")      # columns whose R is a review, audit or assessment of someone else's work
APPROVED = {"approved", "verified", "baselined"}


# ================================================================ data

@dataclass
class Role:
  name: str
  holder: str              # as written in §3.1
  needed_by: str

  @property
  def tag(self) -> str:
    return "TBD" if self.holder.startswith("TBD") else "".join(w[0] for w in self.holder.split()[:2])


@dataclass
class AtRisk:
  change: str
  reqs: list[str]
  record: str              # file name
  approved: bool
  reviewed: bool
  hil: bool
  status: str              # Status field of the record, plain


def doc() -> str:
  return WP_M_02.read_text(encoding="utf-8")


def load_roles(md: str) -> tuple[dict[str, Role], list[str], list[list[str]]]:
  """({abbr: Role}, RACI header, RACI rows)."""
  _, roles = table(section(md, "### 3.1 Role assignments"), "Role")
  s32 = section(md, "### 3.2 RACI per activity")
  head, rows = table(s32, "Activity")
  names = {a: n.strip() for a, n in ABBR_RE.findall(s32.split("\n|")[0])}
  out = {}
  for a in head[1:]:
    if a not in names:
      raise FigureError(f"WP-M-02 §3.2: column {a} is not defined in the sentence above the table")
    full = names[a].lower()
    match = [r for r in roles if plain(r[0]).lower().startswith(full.split(" (")[0][:12])]
    if not match:
      match = [r for r in roles if full.split()[0] in plain(r[0]).lower()]
    if not match:
      raise FigureError(f"WP-M-02 §3.2 column {a} ({names[a]}) has no role in §3.1")
    r = match[0]
    out[a] = Role(plain(r[0]), plain(r[2]), plain(r[3]))
  return out, head, rows


def trace_status() -> dict[str, str]:
  st = {}
  for p in sorted(TRACE_ITEMS.glob("*.yaml")):
    cur = None
    for ln in p.read_text(encoding="utf-8").splitlines():
      m = re.match(r"^- id: (\S+)", ln)
      if m:
        cur = m.group(1)
      m = re.match(r"^  status: (\S+)", ln)
      if m and cur:
        st[cur] = m.group(1)
  return st


def load_at_risk(md: str) -> list[AtRisk]:
  s41 = section(md, "### 4.1 Early implementation (at-risk work)")
  head, rows = table(s41, "Change")
  st = trace_status()
  out = []
  for r in rows:
    reqs = re.findall(r"(?:TSR|SWSR)-\d+", r[col(head, "Requirement")])
    m = re.search(r"\]\(([^)]+\.md)\)", r[col(head, "Impact record")])
    if not m:
      raise FigureError(f"WP-M-02 §4.1 row {r[0]!r} has no impact record link")
    path = (DOC_DIR / m.group(1)).resolve()
    rec = path.read_text(encoding="utf-8")
    sm = re.search(r"^\| Status \| (.+?) \|$", rec, re.M)
    status = plain(sm.group(1)) if sm else ""
    missing = [q for q in reqs if q not in st]
    if missing:
      raise FigureError(f"WP-M-02 §4.1 {r[0]!r}: {missing} not in assurance/trace/items")
    reviewed = bool(status) and not re.search(r"not (?:been )?reviewed|not yet reviewed|reviewer[^.]*TBD", status) \
      and bool(re.search(r"reviewed (?:at I[1-3]|independently)", status))
    hil = bool(re.search(r"HIL evidence|verified on the (?:HIL|bench)", status)) and \
      not re.search(r"not (?:yet )?verified on (?:the )?(?:HIL|bench|hardware)|HIL not run", status)
    out.append(AtRisk(plain(r[0]), reqs, path.name, all(st[q] in APPROVED for q in reqs), reviewed, hil, status))
  return out


# ================================================================ helpers

def wrap(s: str, width: float, size: float, lines: int) -> list[str]:
  words, out, cur = s.split(), [], ""
  for w in words:
    if cur and text_w(cur + " " + w, size) > width:
      out.append(cur)
      cur = w
    else:
      cur = (cur + " " + w).strip()
  if cur:
    out.append(cur)
  if len(out) > lines:
    out = out[:lines]
    out[-1] = fit(out[-1] + " …", width, size)
  return out


def first_sentence(s: str) -> str:
  s = plain(s)
  m = re.match(r"(.+?[a-z0-9)])\.(?:\s|$)", s)
  return m.group(1) if m else s


# ================================================================ Figure 3-1 RACI

RACI_STYLE = {"A": (INK, "#FFFFFF"), "R": (HW, "#FFFFFF"), "C": (HW_BG, HW), "I": (GREY_BG, FAINT)}


def fig_raci(md: str) -> str:
  roles, head, rows = load_roles(md)
  cols = head[1:]
  W = 1280
  holders = sorted({m.group(1) for r in roles.values() if (m := re.match(r"([A-Z][a-z]+(?: [A-Z][a-z]+)+)", r.holder))})
  body = header(W, "3-1", "Who does what (RACI), and who holds each role today",
                "§3.2 grid; above each column its holder from §3.1. The last column asks whether the review, audit or "
                "assessment the activity needs has a named person who is not its author", "WP-M-02 §3.1, §3.2")
  X0, CW, y0, RH = 300, 76, 156, 32
  XI = X0 + len(cols) * CW + 16
  for j, c in enumerate(cols):
    x = X0 + j * CW
    ro = roles[c]
    body.append(text(x + CW / 2, y0 - 44, c, size=12, weight=700, anchor="middle"))
    named = not ro.holder.startswith("TBD")
    lab = ro.tag
    w = text_w(lab, 9.5, True) + 12
    body.append(rect(x + CW / 2 - w / 2, y0 - 34, w, 16, fill=SAFETY if named else "#FFFFFF",
                     stroke="none" if named else FAINT, rx=8, sw=1, dash="" if named else "3 2"))
    body.append(text(x + CW / 2, y0 - 22.5, lab, size=9.5, weight=700, fill="#FFFFFF" if named else MUTED,
                     anchor="middle"))
    body.append(text(x + CW / 2, y0 - 6, f"by {ro.needed_by}", size=8.5, fill=FAINT, anchor="middle"))
  body.append(text(XI + 4, y0 - 34, "Independent", size=10.5, weight=700, fill=MUTED))
  body.append(text(XI + 4, y0 - 20, "party named?", size=10.5, weight=700, fill=MUTED))
  y = y0
  missing = 0
  for r in rows:
    body.append(text(40, y + 20, fit(plain(r[0]), 250, 11.5), size=11.5))
    need = []
    for j, v in enumerate(r[1:]):
      x = X0 + j * CW
      key = v.strip()[:1] if v.strip() else ""
      fill, fg = RACI_STYLE.get(key, ("#FFFFFF", INK))
      body.append(rect(x + 3, y + 3, CW - 6, RH - 6, fill=fill, stroke="none", rx=5))
      body.append(text(x + CW / 2, y + 20, fit(v, CW - 10, 10), size=10, fill=fg, weight=700, anchor="middle"))
      if cols[j] in REVIEW_COLS and key == "R":
        need.append(cols[j])
    if need:
      named = [c for c in need if not roles[c].holder.startswith("TBD")]
      ok = len(named) == len(need)
      missing += not ok
      lab = "yes" if ok else "no: " + ", ".join(c for c in need if c not in named) + " TBD"
      body.append(text(XI + 4, y + 20, lab, size=10.5, weight=700, fill=GREEN if ok else RED))
    else:
      body.append(text(XI + 4, y + 20, "—", size=10.5, fill=FAINT))
    y += RH
  y += 10
  jt = [c for c, ro in roles.items() if not ro.holder.startswith("TBD")]
  note = (f"{len(jt)} of {len(cols)} roles are held by {' and '.join(holders) or 'nobody'}; "
          f"{missing} of {len(rows)} activities need a review, audit or assessment by someone not yet named. "
          "One person may hold several roles, but not review their own work (§3.1).")
  body.append(rect(40, y, W - 80, 30, fill=RED_BG if missing else GREEN_BG, stroke="none", rx=8))
  body.append(text(54, y + 19, fit(note, W - 110, 10.5), size=10.5, weight=600, fill=RED if missing else GREEN))
  y += 52
  lg, _ = legend(40, y, [(INK, "none", "A accountable"), (HW, "none", "R responsible"), (HW_BG, "none", "C consulted"),
                         (GREY_BG, "none", "I informed"), (SAFETY, "none", "holder named (initials)"),
                         ("#FFFFFF", FAINT + " dashed", "holder TBD")])
  body += lg
  body.append(text(W - 40, y, GENERATED, size=10, fill=FAINT, anchor="end"))
  desc = (f"RACI of {len(rows)} activities over {len(cols)} roles. Named holders: "
          f"{', '.join(f'{c} {roles[c].holder}' for c in jt)}. TBD: {', '.join(c for c in cols if c not in jt)}. "
          f"{missing} activities lack a named independent reviewer, auditor or assessor.")
  return svg(W, int(y + 20), "Figure 3-1. RACI per activity with role holders (WP-M-02 §3.1, §3.2)", desc, body)


# ================================================================ Figure 4-1 lifecycle

def fig_lifecycle(md: str) -> str:
  _, rows = table(section(md, "## 4. Lifecycle activities per phase"), "Phase")
  _, cm = table(section(md, "## 8. Confirmation measures"), "Gate")
  _, sc = table(section(md, "## 11. Safety case planning"), "Gate")
  W = 1280
  n = len(rows)
  X0, Y0 = 170, 100
  CW = (W - 40 - X0) / n

  def at_gate(tab: list[list[str]], g: int) -> str:
    for k, v in tab:
      m = re.match(r"G(\d)(?:\s*[–-]\s*G(\d))?$", plain(k))
      if m and int(m.group(1)) <= g <= int(m.group(2) or m.group(1)):
        return plain(v)
    return ""
  body = header(W, "4-1", "Safety lifecycle at a glance: phases, gates, confirmation and the safety case",
                "One column per phase of §4. Each phase ends at its gate; the confirmation measures (§8) and the safety "
                "case content (§11) are those due at that gate", "WP-M-02 §4, §8, §11")
  for j, r in enumerate(rows):
    x = X0 + j * CW
    ph = plain(r[0])
    pid, name = ph.split(" ", 1)
    now = j == 0
    body.append(rect(x + 3, Y0, CW - 6, 42, fill=INK if now else "#FFFFFF", stroke=INK if now else LINE))
    body.append(text(x + 13, Y0 + 18, pid, size=13, weight=700, fill="#FFFFFF" if now else INK))
    body.append(text(x + 13, Y0 + 33, fit(name, CW - 34, 10), size=10, fill="#CBD5E1" if now else MUTED))
    gx = x + CW - 3
    body.append(el("path", None, d=f"M{fmt(gx)} {Y0 + 13} l8 8 l-8 8 l-8 -8 z", fill="#FFFFFF", stroke=RED,
                   stroke_width=1.4, stroke_dasharray="2 2"))
    body.append(text(gx, Y0 + 54, f"G{j}", size=9.5, weight=700, fill=RED, anchor="middle"))
  y = Y0 + 66
  lanes = [("Activities (§4)", 1, 10, INK, CHIP, HAIR), ("Responsible", 2, 2, MUTED, CHIP, HAIR),
           ("Key outputs", 3, 3, SW, SW_BG, "none")]
  for lname, ci, maxl, color, bg, stroke in lanes:
    hh = 12 + maxl * 13
    body.append(text(40, y + 16, lname, size=11, weight=700, fill=MUTED))
    for j, r in enumerate(rows):
      x = X0 + j * CW
      body.append(rect(x + 3, y, CW - 6, hh, fill=bg, stroke=stroke))
      for k, ln in enumerate(wrap(plain(r[ci]), CW - 20, 9.5, maxl)):
        body.append(text(x + 10, y + 15 + k * 13, ln, size=9.5, fill=color))
    y += hh + 8
  for lname, tab, color, bg in [("Confirmation at the gate (§8)", cm, HW, HW_BG),
                                ("Safety case at the gate (§11)", sc, SAFETY, SAFETY_BG)]:
    hh = 12 + 4 * 13
    for k, ln in enumerate(wrap(lname, 120, 11, 2)):
      body.append(text(40, y + 16 + k * 14, ln, size=11, weight=700, fill=MUTED))
    for j in range(n):
      v = at_gate(tab, j)
      x = X0 + j * CW
      if not v:
        body.append(rect(x + 3, y, CW - 6, hh, fill="#FFFFFF", stroke=HAIR, dash="3 3"))
        body.append(text(x + 10, y + 15, "none at this gate", size=9.5, fill=FAINT, style="italic"))
        continue
      body.append(rect(x + 3, y, CW - 6, hh, fill=bg, stroke="none"))
      for k, ln in enumerate(wrap(v, CW - 20, 9.5, 4)):
        body.append(text(x + 10, y + 15 + k * 13, ln, size=9.5, fill=color))
    y += hh + 8
  # hold point after G1, and today
  hx = X0 + 2 * CW - 3
  body.append(rect(hx - 96, y + 6, 192, 38, fill=RED, stroke="none"))
  body.append(text(hx, y + 21, "HOLD POINT at G1 (§4)", size=10, weight=700, fill="#FFFFFF", anchor="middle"))
  body.append(text(hx, y + 35, "no public-road use before G1 and WP-V-07", size=9, fill="#FFFFFF", anchor="middle"))
  body.append(rect(40, y + 6, 120, 38, fill=INK, stroke="none"))
  body.append(text(50, y + 21, "Today: P0", size=10.5, weight=700, fill="#FFFFFF"))
  body.append(text(50, y + 35, "no gate passed", size=9, fill="#CBD5E1"))
  y += 66
  lg, _ = legend(40, y, [("#FFFFFF", RED + " dashed", "gate, not passed"), (SW_BG, "none", "work products"),
                         (HW_BG, "none", "confirmation measure"), (SAFETY_BG, "none", "safety case content")])
  body += lg
  body.append(text(W - 40, y, GENERATED, size=10, fill=FAINT, anchor="end"))
  desc = (f"{n} phases {', '.join(plain(r[0]) for r in rows)}, each with its activities, responsible roles and key "
          "outputs, the confirmation measures and safety case content due at its gate, and the hold point at G1.")
  return svg(W, int(y + 20), "Figure 4-1. Safety lifecycle per phase (WP-M-02 §4, §8, §11)", desc, body)


# ================================================================ Figure 4-2 at-risk work

def fig_at_risk(md: str) -> str:
  items = load_at_risk(md)
  W = 1280
  body = header(W, "4-2", "At-risk changes and the three conditions for credit",
                "Each change of §4.1 earns credit toward G2/G3 only when (a) its requirements are approved, (b) it has an "
                "independent review at I1 or above and (c) its HIL evidence exists (§4.1 item 3)", "WP-M-02 §4.1")
  X0, CW, y, RH = 640, 150, 118, 34
  heads = [("(a) requirement", "approved"), ("(b) independent", "review ≥ I1"), ("(c) HIL", "evidence")]
  body.append(text(40, y - 4, "Change (§4.1) · main requirement", size=11, weight=700, fill=MUTED))
  for j, (a, b) in enumerate(heads):
    body.append(text(X0 + j * CW + CW / 2, y - 18, a, size=11, weight=700, anchor="middle"))
    body.append(text(X0 + j * CW + CW / 2, y - 4, b, size=11, weight=700, anchor="middle"))
  body.append(text(X0 + 3 * CW + 10, y - 4, "Credit", size=11, weight=700, fill=MUTED))
  y += 8
  credited = 0
  for it in items:
    body.append(line(40, y, W - 40, y, stroke=HAIR, sw=1))
    body.append(text(40, y + 21, fit(it.change, 440, 11.5), size=11.5, weight=600))
    body.append(text(X0 - 14, y + 21, fit(", ".join(it.reqs), 140, 10.5), size=10.5, family=MONO, fill=MUTED,
                     anchor="end"))
    for j, ok in enumerate((it.approved, it.reviewed, it.hil)):
      cx = X0 + j * CW + CW / 2
      body.append(rect(cx - 52, y + 6, 104, RH - 12, fill=GREEN if ok else RED_BG, stroke="none", rx=11))
      body.append(text(cx, y + 21, "met" if ok else "not met", size=10, weight=700, fill="#FFFFFF" if ok else RED,
                       anchor="middle"))
    full = it.approved and it.reviewed and it.hil
    credited += full
    body.append(text(X0 + 3 * CW + 10, y + 21, "earned" if full else "none", size=10.5, weight=700,
                     fill=GREEN if full else RED))
    y += RH
  body.append(line(40, y, W - 40, y, stroke=HAIR, sw=1))
  y += 18
  note = (f"{credited} of {len(items)} changes have earned credit. (a) reads the requirement status in "
          "assurance/trace/items; (b) and (c) read the Status field of each change impact record. The hold point still "
          "applies: implemented changes do not permit public-road operation (§4.1 item 4).")
  for k, ln in enumerate(wrap(note, W - 80, 10.5, 2)):
    body.append(text(40, y + k * 15, ln, size=10.5, fill=MUTED))
  y += 46
  lg, _ = legend(40, y, [(GREEN, "none", "condition met"), (RED_BG, "none", "condition not met")])
  body += lg
  body.append(text(W - 40, y, GENERATED, size=10, fill=FAINT, anchor="end"))
  desc = (f"{len(items)} at-risk changes: " + "; ".join(
    f"{it.change}: a {'met' if it.approved else 'not met'}, b {'met' if it.reviewed else 'not met'}, "
    f"c {'met' if it.hil else 'not met'}" for it in items) + f". {credited} earned credit.")
  return svg(W, int(y + 20), "Figure 4-2. At-risk changes against the conditions for credit (WP-M-02 §4.1)", desc, body)


# ================================================================ Figure 9-1 anomaly handling

def fig_anomaly(md: str) -> str:
  _, rows = table(section(md, "## 9. Safety anomaly handling"), "Step")
  steps = [r for r in rows if plain(r[0]) != "Gate rule"]
  gate = next((plain(r[1]) for r in rows if plain(r[0]) == "Gate rule"), "")
  W = 1280
  n = len(steps)
  body = header(W, "9-1", "Safety anomaly handling: from report to closure",
                "The steps of §9 in order, each with the rule written in its row; the gate rule applies at every gate review",
                "WP-M-02 §9")
  y = 108
  gap = 26
  bw = (W - 80 - (n - 1) * gap) / n
  hmax = 0
  blocks = []
  for i, r in enumerate(steps):
    lines_ = wrap(plain(r[1]), bw - 24, 10, 13)
    blocks.append(lines_)
    hmax = max(hmax, 40 + len(lines_) * 13.5)
  for i, (r, lines_) in enumerate(zip(steps, blocks)):
    x = 40 + i * (bw + gap)
    stop = plain(r[0]) == "Immediate action"
    body.append(rect(x, y, bw, hmax, fill=RED_BG if stop else "#FFFFFF", stroke=RED if stop else LINE))
    body.append(text(x + 12, y + 22, f"{i + 1} · {plain(r[0])}", size=12.5, weight=700, fill=RED if stop else INK))
    for k, ln in enumerate(lines_):
      body.append(text(x + 12, y + 42 + k * 13.5, ln, size=10, fill=MUTED))
    if i < n - 1:
      ay = y + 22
      body.append(line(x + bw + 3, ay - 4, x + bw + gap - 8, ay - 4, stroke=MUTED, sw=2))
      body.append(el("path", None, d=f"M{fmt(x + bw + gap - 2)} {fmt(ay - 4)} l-7 -5 l0 10 z", fill=MUTED))
  y += hmax + 18
  if gate:
    lines_ = wrap("Gate rule: " + gate, W - 112, 10.5, 2)
    body.append(rect(40, y, W - 80, 14 + 15 * len(lines_), fill=AMBER_BG, stroke="#FCD34D"))
    for k, ln in enumerate(lines_):
      body.append(text(56, y + 19 + k * 15, ln, size=10.5, fill=AMBER, weight=600))
    y += 14 + 15 * len(lines_)
  y += 26
  body.append(text(W - 40, y, GENERATED, size=10, fill=FAINT, anchor="end"))
  desc = f"Steps {', '.join(plain(r[0]) for r in steps)}. Gate rule: {gate}"
  return svg(W, int(y + 16), "Figure 9-1. Safety anomaly handling (WP-M-02 §9)", desc, body)


