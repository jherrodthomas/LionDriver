"""Figures of the functional safety plan WP-M-02, drawn from its tables.

- Figure 3-1 (`fig-m02-3-1-raci.svg`): the §3.2 RACI grid with each column's holder from §3.1, and per activity
  whether an independent party is named for the review it needs.
- Figure 4-1 (`fig-m02-4-1-lifecycle.svg`): one column per phase of §4 (activities, responsible, key outputs), with
  the confirmation measures of §8 and the safety case content of §11 at each gate, the §4 hold point and today.
- Figure 4-2 (`fig-m02-4-2-at-risk.svg`): every at-risk change of §4.1 against the three conditions of §4.1 item 3
  for credit: (a) its requirement approved (status in `assurance/trace/items`), (b) an independent review at I1 or
  above, (c) HIL evidence (both read from the Status field of its change impact record).
- Figure 9-1 (`fig-m02-9-1-anomaly.svg`): the §9 safety anomaly handling steps as a flow, with the gate rule.

Called by fig_m_management.py, which owns `--check`. Standard library only; deterministic.
"""

