CHAR = {"tb": 0.6, "t2": 0.53, "g": 0.56, "h": 0.56}
SIZE = {"tb": 13, "t2": 13, "g": 13, "h": 21}


def el(tag: str, content: str | None = None, **attrs) -> str:
  a = "".join(f' {k.rstrip("_").replace("_", "-")}="{v}"' for k, v in attrs.items() if v not in ("", None))
  return f"<{tag}{a}/>" if content is None else f"<{tag}{a}>{escape(content)}</{tag}>"


def T(x, y, s, cls="t2", anchor="") -> str:
  return el("text", s, x=f"{x:g}", y=f"{y:g}", class_=cls, text_anchor=anchor)


def fit(s: str, w: float, cls: str) -> str:
  per = CHAR[cls] * SIZE[cls]
  return s if len(s) * per <= w else s[:max(1, int(w / per) - 1)].rstrip(" ,;(") + "…"


# ---------------------------------------------------------------- sources

def layout() -> dict[str, tuple[str, str]]:
  """{folder: (content, clauses)} from the Layout table of assurance/README.md."""
  head, rows = table(section(README.read_text(encoding="utf-8"), "## Layout"), "Folder")
  out = {}
  for r in rows:
    out[plain(r[col(head, "Folder")]).strip("/")] = (r[col(head, "Content")], plain(r[col(head, "Primary standard clauses")]))
  return out


def register_rows() -> dict[str, tuple[str, list[dict]]]:
  """{folder: (section title, rows)}; each row has id, href (relative to WP-M-00), name, gate text, gates, status."""
  md = WP_M_00.read_text(encoding="utf-8")
  reg = load_register(md)
  by_id = {w.wid: w for w in reg.products}
  s3 = section(md, "## 3. Register")
  out = {}
  for num, title, folder in re.findall(r"^### (3\.\d+) (.+?) \(`([^`]*)/`\)\s*$", s3, re.M):
    head, rows = table(section(s3, f"### {num} "), "ID")
    items = []
    for r in rows:
      cell = r[col(head, "ID")]
      m = re.match(r"\[([^\]]+)\]\(([^)]+)\)", cell)
      wid = plain(cell)
      w = by_id[wid]
      items.append({"id": wid, "href": m.group(2) if m else "", "name": w.name, "gate": w.gate_text,
                    "gates": w.gates, "status": w.status})
    out[folder] = (title, items)
  return out, reg


def href_in_folder(href: str, folder: str) -> str:
  """A WP-M-00 link (relative to 01-management/) as seen from the folder's own README."""
  target = (ASSURANCE / "01-management" / href).resolve()
  try:
    return target.relative_to((ASSURANCE / folder).resolve()).as_posix()
  except ValueError:
    return Path("..", target.relative_to(ASSURANCE.resolve())).as_posix()


def rebase(text: str, folder: str) -> str:
  """Relative links of a cell from assurance/README.md, rewritten to work from the folder's README."""
  def fix(m):
    url = m.group(2)
    if re.match(r"[a-z]+:|#|/", url):
      return m.group(0)
    path, _, frag = url.partition("#")
    target = (ASSURANCE / path).resolve()
    try:
      rel = target.relative_to((ASSURANCE / folder).resolve()).as_posix()
    except ValueError:
      rel = Path("..", target.relative_to(ASSURANCE.resolve())).as_posix()
    return f"[{m.group(1)}]({rel}{'#' + frag if frag else ''})"
  return re.sub(r"\[([^\]]*)\]\(([^)]+)\)", fix, text)


def rebase_from(text: str, src: Path, dst: Path) -> str:
  """Relative links and images of markdown written in folder src, rewritten to work from folder dst."""
  def fix(m):
    url = m.group(3)
    if re.match(r"[a-z]+:|#|/", url):
      return m.group(0)
    path, _, frag = url.partition("#")
    rel = Path(os.path.relpath((src / path).resolve(), dst.resolve())).as_posix()
    return f"{m.group(1)}[{m.group(2)}]({rel}{'#' + frag if frag else ''})"
  return re.sub(r"(!?)\[([^\]]*)\]\(([^)]+)\)", fix, text)


def md_title(p: Path) -> str:
  for ln in p.read_text(encoding="utf-8", errors="replace").splitlines():
    if ln.startswith("# "):
      return plain(ln[2:].strip())
  return ""


# ---------------------------------------------------------------- figure

def figure(folder: str, title: str, items: list[dict], reg) -> str:
  gates = [g for g, _ in reg.gates]
  X0, XG, ROW = 24, 372, 40
  GW = (W - 24 - XG) / len(gates)
  sub = f"WP-M-00 §3 ({title}): a chip at each gate the work product is needed for"
  per = CHAR["t2"] * SIZE["t2"]
  if len(sub) * per > W - 48:     # too wide for the phone width: break before the explanation
    sub = [f"WP-M-00 §3 ({title}):", "a chip at each gate the work product is needed for"]
  else:
    sub = [sub]
  dy = 18 * (len(sub) - 1)
  body = [T(24, 34, f"{folder}: work products by gate", "h"),
          *(T(24, 56 + 18 * i, ln, "t2") for i, ln in enumerate(sub)),
          el("line", None, x1=24, y1=70 + dy, x2=W - 24, y2=70 + dy, class_="hair")]
  y = 96 + dy
  for i, g in enumerate(gates):
    body.append(T(XG + GW * i + GW / 2, y, g, "g", "middle"))
  y += 10
  for k, it in enumerate(items):
    if k % 2 == 0:
      body.append(el("rect", None, x=X0 - 8, y=f"{y:g}", width=W - 2 * (X0 - 8), height=ROW, rx=4, class_="lane"))
    body.append(T(X0, y + 16, it["id"], "tb"))
    body.append(T(X0, y + 32, fit(it["name"], XG - X0 - 12, "t2")))
    for g in it["gates"]:
      body.append(el("rect", None, x=f"{XG + GW * g + 4:.1f}", y=f"{y + 13:g}", width=f"{GW - 8:.1f}", height=14, rx=7,
                     class_=STATUS_CLS[it["status"]]))
    y += ROW
  y += 22
  x = X0
  names = dict(reg.statuses)
  for s in sorted({it["status"] for it in items}, key=list(STATUS_CLS).index):
    body += [el("rect", None, x=x, y=f"{y - 11:g}", width=26, height=14, rx=7, class_=STATUS_CLS[s]),
             T(x + 32, y, names[s])]
    x += 32 + len(names[s]) * CHAR["t2"] * SIZE["t2"] + 20
  y += 18
  desc = (f"Work products of {folder} from WP-M-00 §3, by the gates they are needed for: " +
          "; ".join(f"{it['id']} {it['name']}: {it['gate']}, {names[it['status']]}" for it in items) + ".")
  head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{int(y)}" viewBox="0 0 {W} {int(y)}" '
          'role="img" aria-labelledby="t d">')
  return "\n".join([head, el("title", f"{folder}: work products by gate and status", id="t"), el("desc", desc, id="d"),
                    STYLE, f'<rect class="bg" width="{W}" height="{int(y)}"/>', *body, "</svg>"]) + "\n"


# ---------------------------------------------------------------- page

def page(folder: str, lay: dict, regs: dict, reg) -> tuple[str, str | None]:
  d = ASSURANCE / folder
  content, clauses = lay.get(folder, ("", ""))
  if folder not in lay:
    raise FigureError(f"assurance/README.md Layout table has no row for {folder}/")
  title, items = regs.get(folder, ("", []))
  names = dict(reg.statuses)
  out = [GENERATED, "", f"# {folder}", "", rebase(content, folder) + ".", "", f"Standard clauses: {clauses}." if clauses else "", ""]
  top = d / "figures" / "index-top.md"
  if top.exists():
    out += [rebase_from(top.read_text(encoding="utf-8").rstrip(), top.parent, d), ""]
  svg = None
  if items:
    svg = figure(folder, title, items, reg)
    per_gate = [f"{sum(g in it['gates'] for it in items)} at {name}" for g, (name, _) in enumerate(reg.gates)
                if any(g in it["gates"] for it in items)]
    per_status = [f"{sum(it['status'] == s for it in items)} {names[s].lower()}" for s in STATUS_CLS
                  if any(it["status"] == s for it in items)]
    out += [f"![The {len(items)} work products of this folder, one row each, with a chip at every gate G0 to G6 it is "
            f"needed for, coloured by its status in the WP-M-00 register: {', '.join(per_gate)}; "
            f"{', '.join(per_status)}]({SVG_NAME})", "",
            f"*Drawn from [WP-M-00](../01-management/WP-M-00-work-product-register.md#3-register) §3 ({title}), "
            "which also has the clauses of each work product and the register for every folder.*", "",
            "## Work products", "", "| ID | Work product | Gate | Status |", "|---|---|---|---|"]
    for it in items:
      href = href_in_folder(it["href"], folder) if it["href"] else ""
      link = f"[{it['id']}]({href})" if href else it["id"]
      out.append(f"| {link} | {it['name']} | {it['gate']} | {names[it['status']]} |")
    out.append("")
  extra = d / "figures" / "index-section.md"
  if extra.exists():
    out += [rebase_from(extra.read_text(encoding="utf-8").rstrip(), extra.parent, d), ""]
  subdirs = sorted(p for p in d.iterdir() if p.is_dir() and p.name not in ("figures", "__pycache__"))
  if subdirs:
    out += ["## Subfolders", "", "| Folder | What it holds |", "|---|---|"]
    for p in subdirs:
      rd = p / "README.md"
      out.append(f"| [`{p.name}/`]({p.name}/{'README.md' if rd.exists() else ''}) | {md_title(rd) if rd.exists() else '—'} |")
    out.append("")
  out += ["GitHub lists this folder's files above this page; each work product's document embeds its own figures.", ""]
  text = "\n".join(ln for i, ln in enumerate(out) if not (ln == "" and i and out[i - 1] == "")).rstrip() + "\n"
  return text, svg


def build() -> dict[Path, str]:
  lay = layout()
  regs, reg = register_rows()
  outputs = {}
  for folder in FOLDERS:
    text, svg = page(folder, lay, regs, reg)
    outputs[ASSURANCE / folder / "README.md"] = text
    if svg:
      outputs[ASSURANCE / folder / SVG_NAME] = svg
  return outputs


def problems(outputs: dict[Path, str]) -> list[str]:
  """Register rows of a phase folder whose file does not exist, and register folders that are not on disk."""
  regs, _ = register_rows()
  out = []
  for folder, (_t, items) in regs.items():
    if re.match(r"\d\d-", folder) and folder not in FOLDERS:
      out.append(f"WP-M-00 names {folder}/, which does not exist")
    for it in items:
      if it["href"] and not (ASSURANCE / "01-management" / it["href"].split("#")[0]).exists():
        out.append(f"WP-M-00 {it['id']}: {it['href']} does not exist")
  return out


def orphans(outputs: dict[Path, str]) -> list[Path]:
  """index-status.svg files of folders that no longer get one (their register section went away)."""
  return [p for p in (ASSURANCE / f / SVG_NAME for f in FOLDERS) if p.exists() and p not in outputs]


def main(argv: list[str]) -> int:
  try:
    outputs = build()
  except FigureError as e:
    print(f"folder_index: {e}", file=sys.stderr)
    return 1
  errs = problems(outputs)
  for e in errs:
    print(f"folder_index: {e}", file=sys.stderr)
  if "--check" in argv:
    stale = [p for p, c in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
    extra = orphans(outputs)
    for p in stale:
      print(f"stale: assurance/{p.relative_to(ASSURANCE).as_posix()}", file=sys.stderr)
    for p in extra:
      print(f"no longer generated: assurance/{p.relative_to(ASSURANCE).as_posix()}", file=sys.stderr)
    if stale or extra:
      print("the phase-folder pages follow WP-M-00 §3, the assurance README Layout table and the files in each folder",
            file=sys.stderr)
      print("run: python3 assurance/01-management/figures/folder_index.py", file=sys.stderr)
      return 1
    if not errs:
      print(f"folder_index: {len(FOLDERS)} folder pages current")
    return 1 if errs else 0
  for p in orphans(outputs):
    p.unlink()
  for p, c in outputs.items():
    p.write_text(c, encoding="utf-8")
  print(f"folder_index: wrote {len(outputs)} files for {len(FOLDERS)} folders")
  return 1 if errs else 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
