#!/usr/bin/env python3
"""Vehicle register (docs/liondriver/vehicles/vehicles.yaml): render its page and check the documents that cite it.

The register is the single source of vehicle facts (model codes, model years, powertrain, platform, firmware,
physical data). Safety documents cite a family (VF-nnn) or configuration (CFG-nnn) and must agree with it:

  V1  every CARS.md string the register names is in docs/CARS.md
  V2  each configuration has an assurance record with the same ID, platform and codename
  V3  WP-C-01 §1 "Reference vehicle" names the codename, the model years and links the register
  V4  the FMEA item structure (variants.yaml) takes its families and configurations from the register
  V5  no document restates the old single-year name ("2020 Corolla LE", "2020 Toyota Corolla")

Usage (from the repository root):
    python3 tools/vehicles/vehicle_register.py           # write docs/liondriver/vehicles/README.md
    python3 tools/vehicles/vehicle_register.py --check   # fail on a stale page or a disagreeing document

Requires PyYAML.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
REGISTER = Path("docs/liondriver/vehicles/vehicles.yaml")
PAGE = Path("docs/liondriver/vehicles/README.md")
CARS = Path("docs/CARS.md")
CONFIGS = Path("assurance/case-records/configurations")
ITEM_DEF = Path("assurance/02-concept/WP-C-01-item-definition.md")
VARIANTS = Path("assurance/08-analyses/fmea/item/variants.yaml")
OLD_NAME = re.compile(r"\b2020 (Toyota )?Corolla( LE)?\b")
OLD_NAME_SCOPE = ("assurance", "tools", "docs/liondriver")


def load(root: Path = ROOT) -> dict:
  return yaml.safe_load((root / REGISTER).read_text(encoding="utf-8"))


def family(reg: dict, fid: str) -> dict:
  return next(f for f in reg["families"] if f["id"] == fid)


def config(reg: dict, cid: str) -> dict:
  return next(c for c in reg["configurations"] if c["id"] == cid or cid in c.get("aliases", []))


def years(cfg: dict) -> str:
  y = cfg["model_years"]
  return f"{y['first']}–{y['last']}" if y["first"] != y["last"] else str(y["first"])


def reference_label(root: Path = ROOT, cid: str = "CFG-001") -> str:
  """The reference configuration as named in export headers, e.g. FMEA and FMEDA workbooks."""
  cfg = config(load(root), cid)
  return f"{cfg['codename']} ({cfg['id']} / {', '.join(cfg.get('aliases', []))}), model years {years(cfg)}"


# ---------------------------------------------------------------- page

def val(v) -> str:
  if isinstance(v, dict):
    mark = "" if v.get("confirmed", True) else " *(to confirm)*"
    if "value" in v:
      return f"{v['value']}{mark}"
    return f"{v['min']}–{v['max']}{mark}"
  return str(v)


def render(reg: dict) -> str:
  out = ["# Vehicle register", "",
         "<!-- Generated by tools/vehicles/vehicle_register.py from vehicles.yaml. Do not edit by hand. -->", "",
         " ".join(["The vehicles LionDriver targets, as engineering facts. This page makes no safety claim: what the safety case",
                   "covers, and how far, is in the [configuration records](../../../assurance/case-records/configurations/) and the",
                   "[item definition](../../../assurance/02-concept/WP-C-01-item-definition.md), which cite the IDs below.",
                   "Source: [`vehicles.yaml`](vehicles.yaml). Values marked *to confirm* are working values awaiting their source."]), ""]
  for cfg in reg["configurations"]:
    fam = family(reg, cfg["family"])
    fw = cfg["firmware_fingerprints"]
    out += [f"## {cfg['id']} · {cfg['codename']}", "",
            f"Also known as {', '.join(cfg.get('aliases', []))} in the FMEA item structure. Family {fam['id']} ({fam['name']}).", "",
            "| Attribute | Value | Source |", "|---|---|---|",
            f"| Vehicle | {cfg['make']} {cfg['model']} {cfg['body']}, {cfg['market']} market | |",
            f"| Model years | **{years(cfg)}** | {cfg['model_years_note']} |",
            f"| Toyota model code | {val(cfg['model_code'])} | {cfg['model_code']['source']} |",
            f"| Engine | {val(cfg['engine'])} | {cfg['engine']['source']} |",
            f"| Transmission | {val(cfg['transmission'])} | {cfg['transmission']['source']} |",
            f"| Trims | {val(cfg['trims'])} | {cfg['trims']['source']} |",
            f"| Driver assistance | {cfg['adas']} | |",
            f"| openpilot platform | `{cfg['opendbc_platform']}`, safety mode `{cfg['safety_mode']}` | opendbc |",
            f"| CARS.md entry | {cfg['cars_md_member']} | [`docs/CARS.md`](../../CARS.md) |",
            f"| Harness and device | {cfg['harness']}; {cfg['device']} | |",
            f"| Curb mass | {val(cfg['physical']['curb_mass_kg'])} kg | {cfg['physical']['curb_mass_kg']['source']} |",
            f"| Width | {val(cfg['physical']['width_mm'])} mm | {cfg['physical']['width_mm']['source']} |",
            f"| Seats | {val(cfg['physical']['seats'])} | {cfg['physical']['seats']['source']} |",
            f"| ECU firmware set | {len(fw['versions'])} versions recorded ({fw['status']}) | {fw['note']} |",
            "", "**Not covered by this configuration:**", ""]
    out += [f"- {e}" for e in cfg["excluded"]]
    out.append("")
  for fam in reg["families"]:
    out += [f"## {fam['id']} · {fam['name']}", "",
            f"Generation {fam['generation']} on opendbc platform `{fam['opendbc_platform']}`.", "",
            "| docs/CARS.md entry | Relation |", "|---|---|"]
    out += [f"| {m} | Family member |" for m in fam["members"]]
    out += [f"| {m} | Same platform, not in the family |" for m in fam.get("platform_siblings", [])]
    out += [f"| {n['item']} | Not supported: {n['reason']} |" for n in fam.get("not_supported", [])]
    out.append("")
  return "\n".join(out)


# ---------------------------------------------------------------- checks

def cars_md_names(root: Path) -> set[str]:
  names = set()
  for line in (root / CARS).read_text(encoding="utf-8").splitlines():
    cells = line.split("|")
    if len(cells) > 3 and line.startswith("|") and cells[1] not in ("Make", "---"):
      model = re.sub(r"\[<sup>[^<]*</sup>\]\(#footnotes\)", "", cells[2]).strip()
      names.add(f"{cells[1].strip()} {model}")
  return names


def config_record(root: Path, cid: str) -> dict[str, str]:
  for path in sorted((root / CONFIGS).glob("*.yaml")):
    text = path.read_text(encoding="utf-8")
    if re.search(rf"^- id: {cid}$", text, re.M):
      return dict(re.findall(r'^  (\w+): "?(.*?)"?$', text, re.M))
  return {}


def check(root: Path, reg: dict) -> list[str]:
  errs: list[str] = []
  names = cars_md_names(root)
  for fam in reg["families"]:
    for m in fam["members"] + fam.get("platform_siblings", []):
      if m not in names:
        errs.append(f"V1 {fam['id']}: '{m}' is not in docs/CARS.md")
  item_row = next((ln for ln in (root / ITEM_DEF).read_text(encoding="utf-8").splitlines() if ln.startswith("| Reference vehicle |")), "")
  variants = yaml.safe_load((root / VARIANTS).read_text(encoding="utf-8"))
  for cfg in reg["configurations"]:
    cid = cfg["id"]
    if cfg["cars_md_member"] not in family(reg, cfg["family"])["members"]:
      errs.append(f"V1 {cid}: cars_md_member '{cfg['cars_md_member']}' is not a member of {cfg['family']}")
    rec = config_record(root, cid)
    if not rec:
      errs.append(f"V2 {cid}: no assurance configuration record in {CONFIGS}")
    else:
      if rec.get("platform") != cfg["opendbc_platform"]:
        errs.append(f"V2 {cid}: record platform {rec.get('platform')!r}, register {cfg['opendbc_platform']!r}")
      if cfg["codename"] not in rec.get("title", ""):
        errs.append(f"V2 {cid}: record title does not name the codename '{cfg['codename']}'")
    for need in (cfg["codename"], years(cfg), str(REGISTER.parent)):
      if need not in item_row:
        errs.append(f"V3 WP-C-01 §1 'Reference vehicle' does not contain '{need}'")
    acs = [a for a in variants.get("assured_configurations", []) if a.get("register_config") == cid]
    if not acs or any(a["id"] not in cfg.get("aliases", []) for a in acs):
      errs.append(f"V4 variants.yaml: no assured configuration with register_config {cid} and an ID listed in its aliases")
  for vf in variants.get("families", []):
    if "register_family" not in vf or any(k in vf for k in ("members", "platform_siblings")):
      errs.append(f"V4 variants.yaml family {vf.get('id')}: must cite register_family and not list members itself")
  for top in OLD_NAME_SCOPE:
    for path in sorted((root / top).rglob("*")):
      # The register (and its page) holds source citations; this tool and its tests hold the pattern.
      if path.suffix not in (".md", ".yaml", ".py") or any(d in path.parents for d in (root / REGISTER.parent, root / "tools/vehicles")):
        continue
      for n, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        if OLD_NAME.search(line):
          errs.append(f"V5 {path.relative_to(root)}:{n}: single-year vehicle name; cite the configuration ({OLD_NAME.search(line).group(0)!r})")
  return errs


def main(argv: list[str]) -> int:
  root = ROOT
  reg = load(root)
  text = render(reg)
  errs = check(root, reg)
  if "--check" in argv:
    if not (root / PAGE).exists() or (root / PAGE).read_text(encoding="utf-8") != text:
      errs.insert(0, f"{PAGE} is stale; run tools/vehicles/vehicle_register.py")
  else:
    (root / PAGE).write_text(text, encoding="utf-8")
    print(f"wrote {PAGE}")
  for e in errs:
    print(e)
  if errs:
    return 1
  print(f"vehicle register: {len(reg['configurations'])} configuration(s), {len(reg['families'])} family(ies); citing documents agree")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
