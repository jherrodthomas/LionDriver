#!/usr/bin/env python3
"""Spreadsheet previews that read in GitHub's web view: every sheet of a workbook as Markdown, large sheets as CSV.

GitHub shows an .xlsx only as a download. For each workbook in WORKBOOKS this writes a folder of review pages:

  <out>/README.md               every sheet in workbook order: small sheets as tables, large ones as a summary
                                matrix whose cells link to the rows
  <out>/<sheet>/<group>.csv     the rows of a large sheet, one file per group (GitHub shows a CSV as a searchable
                                table, and keeps each file well under its rendering limit)

The workbook is the source; the preview is regenerated, never edited. Values are the cached results of the
workbook's formulas (openpyxl data_only), so a workbook must have been recalculated before it is committed, as the
builders already do.

Usage:
  tools/xlsx_review.py            write every preview
  tools/xlsx_review.py --check    exit 1 if a committed preview differs from a fresh build, or a stale file is left
"""
from __future__ import annotations

import argparse
import csv
import io
import re
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
HARA = "assurance/02-concept/hara"
LARGE = 150            # a sheet with more data rows than this is split into CSVs
CSV_LIMIT = 300_000    # bytes; GitHub stops rendering a CSV as a table well above this
ASIL_BADGE = {"D": "🟥 D", "C": "🟧 C", "B": "🟨 B", "A": "🟩 A", "QM": "⬜ QM", "—": "—"}
ASIL_ORDER = ["D", "C", "B", "A", "QM", "—"]


class PreviewError(Exception):
  pass


@dataclass
class Workbook:
  src: str                      # repository path of the .xlsx
  out: str                      # repository path of the preview folder
  title: str
  note: str = ""
  split: dict[str, tuple[str, ...]] = field(default_factory=dict)   # large sheet -> group-by columns
  summary: dict[str, tuple[str, str, str]] = field(default_factory=dict)  # large sheet -> (row key, column key, value)


WORKBOOKS = [
  Workbook(f"{HARA}/WP-C-03-hara-cartesian.xlsx", f"{HARA}/review/reference",
           "WP-C-03 HARA, Cartesian workbook (reference scope, Chill mode)",
           "Generated by the HARA builder from [`hara_model.py`](../../hara_model.py); see the [HARA README](../../README.md).",
           split={"12_HARA_Worksheet": ("Function ID", "Malfunction ID")},
           summary={"12_HARA_Worksheet": ("Function ID", "Malfunction ID", "ASIL")}),
  Workbook(f"{HARA}/WP-C-03-hara-cartesian_experimental.xlsx", f"{HARA}/review/experimental",
           "WP-C-03 HARA, Cartesian workbook (Experimental Mode variant, D-08 option B)",
           "Generated by the HARA builder from [`hara_model.py`](../../hara_model.py); see the [HARA README](../../README.md).",
           split={"12_HARA_Worksheet": ("Function ID", "Malfunction ID")},
           summary={"12_HARA_Worksheet": ("Function ID", "Malfunction ID", "ASIL")}),
  Workbook("assurance/02-concept/reviews/RR-2026-003-hara-checklist.xlsx",
           "assurance/02-concept/reviews/preview/RR-2026-003-hara-checklist",
           "RR-2026-003 HARA review checklist",
           "The review record is [RR-2026-003](../../RR-2026-003.md)."),
]


# ---------------------------------------------------------------- reading

def text(v) -> str:
  if v is None:
    return ""
  if isinstance(v, float) and v.is_integer():
    v = int(v)
  return str(v).strip()


def label_line(cells: list[str]) -> str:
  """A key/value row outside a table: "**Key.** value"; a single cell stays as it is."""
  if len(cells) < 2:
    return cells[0] if cells else ""
  return f"**{cells[0].rstrip('.:')}.** " + " · ".join(cells[1:])


def read_sheet(ws) -> tuple[list[str], list[str], list[list[str]], list[str]]:
  """(lines above the header, header, data rows, lines below the table). The header is the first row that has
  as many filled cells as the widest row; an untitled sheet of key/value rows has no header."""
  rows = [[text(c) for c in r] for r in ws.iter_rows(values_only=True)]
  width = max((sum(1 for c in r if c) for r in rows), default=0)
  if width == 0:
    return [], [], [], []
  hi = next(i for i, r in enumerate(rows) if sum(1 for c in r if c) == width)
  above = [label_line([c for c in r if c]) for r in rows[:hi] if any(r)]
  cols = [j for j in range(len(rows[hi])) if any(r[j] for r in rows[hi:] if j < len(r))]
  header = [rows[hi][j] for j in cols]
  body, below = [], []
  for r in rows[hi + 1:]:
    cells = [r[j] if j < len(r) else "" for j in cols]
    filled = sum(1 for c in cells if c)
    if filled == 0:
      if body:
        below.append("")
      continue
    if below or (filled == 1 and cells[0] and len(cells) > 2 and len(cells[0]) > 60):
      below.append(label_line([c for c in cells if c]))   # a note under the table
    else:
      body.append(cells)
  below = [b for b in below if b]
  return above, header, body, below


# ---------------------------------------------------------------- writing

def md_cell(s: str, col: str = "") -> str:
  if col.strip().upper() in ("ASIL", "WORST-CASE ASIL", "ASIL IF ⚠ AOUS FAIL") and s in ASIL_BADGE:
    s = ASIL_BADGE[s]
  return s.replace("\\", "\\\\").replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


def md_table(header: list[str], body: list[list[str]]) -> list[str]:
  if not any(header):   # key/value block such as a title page: no header row
    return [f"| {' | '.join(md_cell(c) for c in r)} |" if i else
            f"| {' | '.join(md_cell(c) for c in r)} |\n|{'---|' * len(r)}" for i, r in enumerate(body)]
  out = [f"| {' | '.join(md_cell(h) for h in header)} |", f"|{'---|' * len(header)}"]
  out += [f"| {' | '.join(md_cell(c, h) for c, h in zip(r, header))} |" for r in body]
  return out


def slug(s: str) -> str:
  return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def csv_text(header: list[str], rows: list[list[str]]) -> str:
  buf = io.StringIO()
  w = csv.writer(buf, lineterminator="\n")
  w.writerow(header)
  w.writerows(rows)
  return buf.getvalue()


def build(wb: Workbook, root: Path = ROOT) -> dict[str, str]:
  """Relative path within wb.out -> file content."""
  src = root / wb.src
  if not src.exists():
    raise PreviewError(f"{wb.src}: workbook not found")
  book = openpyxl.load_workbook(src, data_only=True)
  files: dict[str, str] = {}
  rel_src = Path("/".join([".."] * len(Path(wb.out).relative_to(Path(wb.src).parent).parts))) / Path(wb.src).name
  page = [f"# {wb.title}", "",
          f"> Generated from [`{Path(wb.src).name}`]({rel_src.as_posix()}) by `tools/xlsx_review.py`, so it can be "
          "read and reviewed on GitHub without downloading the workbook. Regenerate, never edit this page. "
          + wb.note, "",
          "**Sheets.** " + " · ".join(f"[{ws.title}](#{slug(ws.title)})" for ws in book.worksheets), ""]
  for ws in book.worksheets:
    above, header, body, below = read_sheet(ws)
    page += [f"## {ws.title}", ""]
    for i, line in enumerate(above):   # each line its own paragraph; the first is the sheet's own title
      page += [f"*{md_cell(line)}*" if i == 0 and not line.startswith("**") else md_cell(line), ""]
    if not body and not header:
      page += ["*Empty sheet.*", ""]
      continue
    if len(body) > LARGE:
      if ws.title not in wb.split:
        raise PreviewError(f"{wb.src} {ws.title}: {len(body)} rows; name the columns to split it by in WORKBOOKS")
      page += large_sheet(wb, ws.title, header, body, files)
    else:
      page += md_table(header, body) + [""]
    for line in below:
      page += [md_cell(line), ""]
  files["README.md"] = "\n".join(page).rstrip() + "\n"
  return files


def large_sheet(wb: Workbook, title: str, header: list[str], body: list[list[str]], files: dict[str, str]) -> list[str]:
  keys = wb.split[title]
  missing = [k for k in keys if k not in header]
  if missing:
    raise PreviewError(f"{wb.src} {title}: split column(s) {', '.join(missing)} not in the header")
  ki = [header.index(k) for k in keys]
  groups: dict[tuple[str, ...], list[list[str]]] = defaultdict(list)
  for r in body:
    groups[tuple(r[i] for i in ki)].append(r)
  folder = slug(title)
  names: dict[tuple[str, ...], str] = {}
  for g, rows in sorted(groups.items()):
    name = f"{folder}/{'-'.join(slug(x) or 'none' for x in g)}.csv"
    content = csv_text(header, rows)
    if len(content.encode()) > CSV_LIMIT:
      raise PreviewError(f"{wb.src} {title}: {name} is {len(content.encode())} bytes; split it further")
    files[name] = content
    names[g] = name
  out = [f"{len(body)} rows, too many for one table. They are split into {len(groups)} CSV files by "
         f"{' and '.join(keys)}; GitHub shows each as a searchable table.", ""]
  if title in wb.summary:
    rk, ck, vk = wb.summary[title]
    ri, ci, vi = header.index(rk), header.index(ck), header.index(vk)
    label = {}
    for r in body:   # a readable name for each row key: the column after it, if it is text
      if ri + 1 < len(header) and r[ri + 1]:
        label.setdefault(r[ri], r[ri + 1])
    cols = sorted({r[ci] for r in body})
    worst: dict[tuple[str, str], Counter] = defaultdict(Counter)
    for r in body:
      worst[(r[ri], r[ci])][r[vi]] += 1
    out += [f"**{vk} by {rk} and {ck}.** Each cell gives the worst {vk} and the number of rows; it links to those "
            "rows. ⬜ QM and — (S0, no requirement) rows are counted too.", ""]
    out += [f"| {rk} | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for rkey in sorted({r[ri] for r in body}):
      cells = []
      for c in cols:
        cnt = worst.get((rkey, c))
        if not cnt:
          cells.append("")
          continue
        top = min(cnt, key=lambda a: ASIL_ORDER.index(a) if a in ASIL_ORDER else len(ASIL_ORDER))
        g = next(k for k in names if k[keys.index(rk)] == rkey and k[keys.index(ck)] == c) if len(keys) == 2 else None
        badge = ASIL_BADGE.get(top, top)
        cells.append(f"[{badge} ({sum(cnt.values())})]({names[g]})" if g else f"{badge} ({sum(cnt.values())})")
      name = f"{rkey} {label.get(rkey, '')}".strip()
      out.append(f"| {md_cell(name)} | " + " | ".join(cells) + " |")
    out.append("")
  else:
    out += [f"- [{' · '.join(g)}]({n}) ({len(groups[g])} rows)" for g, n in names.items()] + [""]
  return out


# ---------------------------------------------------------------- main

def write_all(root: Path = ROOT, check: bool = False) -> list[str]:
  problems = []
  for wb in WORKBOOKS:
    files = build(wb, root)
    out = root / wb.out
    present = {p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file()} if out.exists() else set()
    for rel, content in files.items():
      p = out / rel
      if check:
        if not p.exists() or p.read_text(encoding="utf-8") != content:
          problems.append(f"stale: {wb.out}/{rel}")
      else:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    for rel in sorted(present - set(files)):
      if check:
        problems.append(f"leftover: {wb.out}/{rel}")
      else:
        (out / rel).unlink()
  return problems


def main() -> int:
  ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  ap.add_argument("--check", action="store_true", help="fail if a committed preview is stale")
  args = ap.parse_args()
  try:
    problems = write_all(check=args.check)
  except PreviewError as e:
    print(f"xlsx_review: {e}", file=sys.stderr)
    return 2
  if problems:
    print("\n".join(problems), file=sys.stderr)
    print("run: python3 tools/xlsx_review.py", file=sys.stderr)
    return 1
  n = len(WORKBOOKS)
  print(f"xlsx_review: {n} workbook previews {'current' if args.check else 'written'}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
